TERRAIN = {'joseon': 'joseon-korea', 'wuxia': 'wuxia-china', 'sengoku': 'sengoku-japan'}


def build(cid, c, base):
    j = copy.deepcopy(base)
    j['id'] = cid + '-5act'
    j['name'] = c['name']
    j['terrain'] = TERRAIN[cid]
    j['desc'] = c['desc'] + ' 장소 id 는 판타지 5막과 같고(지형 코드·검사가 id 로 부른다) 표시 이름은 label 이다.'
    j['terrain_bound_note'] = base['terrain_bound_note'] + ' 이 여정의 표시 이름은 places[].label.'
    for a, name in zip(j['acts'], c['acts']):
        a['name'] = name
    keys = {'pass': 'pass_', 'ship': 'ship', 'skiff': 'skiff', 'air': 'air'}
    for b, (bname, bdesc) in zip(j['barriers'], c['barriers']):
        b['name'], b['desc'] = bname, bdesc
    bar = {b['means']: b['name'] for b in j['barriers']}
    for k, m in j['means'].items():
        m['name'] = c['means'][keys[k]]
        m['barrier'] = bar[k] if k != 'air' else bar['air']
    for p in j['places']:
        label, story = c['places'][p['id']]
        p['label'], p['story'], p['note'] = label, story, label
    for e in j['main_line']:
        e['event'] = c['events'].get(e['event'], e['event'])
    return j


def main():
    base = json.loads((ROOT / 'fantasy-5act.json').read_text())
    for cid, c in CULTURES.items():
        missing = {p['id'] for p in base['places']} - set(c['places'])
        assert not missing, (cid, missing)
        j = build(cid, c, base)
        (ROOT / (j['id'] + '.json')).write_text(json.dumps(j, ensure_ascii=False, indent=1) + '\n')
        print('journeys/%s.json' % j['id'])


if __name__ == '__main__':
    main()
