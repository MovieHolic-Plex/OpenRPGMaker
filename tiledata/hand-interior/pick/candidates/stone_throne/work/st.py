from w6lib import emit, Cv
LG={}
for i,ch in enumerate('0123456'): LG[ch]=f'black:{i}'      # 검은 돌
for i,ch in enumerate('abcdefg'): LG[ch]=f'gold:{i}'       # 금 띠
for i,ch in enumerate('hijklmn'): LG[ch]=f'red:{i}'        # 보석
LG.update({'~':'P:~','-':'P:-'})
# 검은돌: 1 윤곽, 2 그늘, 3 몸, 4 빛, 5 모서리 하이라이트, 6 반짝
# 금: c(2) 그늘, d(3) 몸, e(4) 밝음, f(5) 하이라이트, g(6) 반짝

def A(strong=False):
    c=Cv(16,32)
    # 등받이 몸통
    c.rect(3,3,10,16,'3')
    c.hl(4,2,8,'1'); c.vl(3,3,16,'1'); c.vl(12,3,16,'1')
    # 윗 모서리 깎기
    c.px(3,3,'.') ; c.px(12,3,'.'); c.px(3,4,'1'); c.px(12,4,'1'); c.px(4,3,'1'); c.px(11,3,'1')
    # 금 꼭대기 띠
    c.hl(4,3,8,'e'); c.hl(4,3,3,'f'); c.px(11,3,'d')
    c.hl(4,4,8,'d'); c.px(4,4,'e')
    # 빛/그늘 면: 왼 두 줄 밝게, 오른 두 줄 어둡게
    for y in range(5,19):
        c.px(4,y,'5' if strong else '4'); c.px(5,y,'4')
        c.px(11,y,'2'); 
        if strong: c.px(10,y,'2')
    # 금 띠 (허리)
    c.hl(4,6,8,'e'); c.hl(4,6,3,'f'); c.px(11,6,'d')
    c.hl(4,7,8,'d')
    # 새긴 판 : 어두운 안쪽, 위-왼 모서리는 그늘, 아래-오른 모서리는 빛(파낸 홈)
    c.rect(5,9,6,9,'2')
    c.hl(5,9,6,'1'); c.vl(5,9,9,'1')
    c.px(5,9,'.'); c.px(5,9,'3'); c.px(10,9,'3'); c.px(5,10,'1')
    c.hl(5,18,6,'4'); c.vl(10,10,8,'4'); c.px(5,18,'3')
    # 보석
    c.px(7,11,'k'); c.px(8,11,'j'); c.px(7,12,'i'); c.px(8,12,'h'); c.px(7,10,'m'); c.px(8,10,'k'); c.px(6,11,'k'); c.px(9,11,'i'); c.px(6,12,'i'); c.px(9,12,'h');
    c.px(7,13,'l'); c.px(8,13,'i'); c.px(7,14,'e'); c.px(8,14,'d')
    # 팔걸이
    c.rect(1,18,3,6,'3'); c.rect(12,18,3,6,'3')
    c.hl(1,17,3,'1'); c.hl(12,17,3,'1')
    c.hl(1,18,3,'e'); c.px(1,18,'f'); c.hl(12,18,3,'d'); c.px(12,18,'e')
    c.px(1,19,'5' if strong else '4'); c.px(12,19,'4'); c.vl(1,19,5,'4'); c.vl(3,19,5,'2'); c.vl(14,19,5,'1'); c.vl(12,19,5,'3'); c.vl(13,19,5,'2')
    # 앉는 자리: 윗면(밝음) 앞면
    c.hl(4,19,8,'5'); c.hl(4,20,8,'4'); c.hl(4,21,8,'3'); c.hl(4,22,8,'2') 
    c.hl(4,22,8,'d'); c.px(4,22,'e')  # 금 테두리
    c.hl(4,23,8,'1')
    # 몸통 아래 받침대
    c.rect(2,24,12,4,'3')
    for x in range(2,14):
        c.px(x,24,'2')
    c.px(2,24,'1'); c.px(13,24,'1')
    for x in (3,6,9,12):
        c.vl(x,25,3,'4' if x<8 else '2'); 
    c.vl(2,25,3,'4'); c.vl(13,25,3,'1')
    # 발 단
    c.hl(0,28,16,'5'); c.px(0,28,'6')
    c.hl(0,29,16,'3'); c.hl(0,30,16,'2'); c.hl(0,31,16,'1')
    c.vl(0,29,3,'4'); c.vl(15,28,4,'1'); c.px(15,28,'2')
    if strong:
        c.hl(1,31,14,'1')
    return c
if __name__=='__main__':
    c=A(); c.show()
    emit('../w6-A.pxg',LG,c.rows())

def B():
    c=A(True)
    # 발 단을 한 줄 올리고 아래 줄에 접지 그림자
    c.hl(0,31,16,'.')
    c.hl(0,30,16,'1'); c.hl(0,29,16,'2'); c.hl(0,28,16,'5'); c.px(0,28,'6')
    c.vl(0,29,2,'4'); c.px(15,28,'2'); c.px(15,29,'1')
    c.hl(2,31,14,'~'); c.hl(1,31,1,'-'); c.px(15,31,'-')
    # 등받이 오른쪽 기둥과 팔걸이 그늘 강화
    for y in range(3,18): c.px(11,y,'1'); c.px(10,y,'2') if y>7 else None
    for y in range(19,24): c.px(13,y,'1')
    # 앉는 자리 앞에 그림자 (팔걸이가 드리움)
    c.px(4,20,'3'); c.px(4,21,'2'); 
    # 금띠 반짝
    c.px(4,3,'g'); c.px(4,6,'g')
    return c
if __name__=='__main__':
    emit('../w6-B.pxg',LG,B().rows())
