    rows = grid(g); out = ['// ore_vein 후보 %s (w27)' % k, '@size 16 16', '@cell 16', '@palette palette.pal']
    px = []
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c != '.': px.append('%d %d %s' % (x, y, LEG[c]))
    for i in range(0, len(px), 10): out.append('@px ' + ' '.join(px[i:i+10]))
