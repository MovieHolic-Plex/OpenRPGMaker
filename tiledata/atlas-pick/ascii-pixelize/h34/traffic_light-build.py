D = "."
R = []
R.append(D * 32)
R.append(D * 27 + "&&&" + D * 2)
R.append(D * 2 + "&" + ":" * 23 + "&:==&.")
for _ in range(3):
    R.append(".&=" + ":" * 23 + "&=+&@.")
R.append(".@:" + "+" * 23 + "&=+&@.")
red = ["@###@", "#:~~*", "#~~**", "#***#", "@###@"]
yel = ["@$$$@", "$+$$$", "$$$$$", "$$$$$", "@$$$@"]
grn = ["@%%%@", "%+%%%", "%%%%%", "%%%%%", "@%%%@"]
R.append(".@+&" + "&" + "@" * 5 + "&&" + "@" * 5 + "&&" + "@" * 5 + "&&" + "&=+&@.")
for i in range(5):
    R.append(".@+&" + "&" + red[i] + "&&" + yel[i] + "&&" + grn[i] + "&&" + "&=+&@.")
R.append(D * 2 + "@" + "&" * 23 + "&=+&@.")
R.append(D * 3 + "@" * 23 + "@=+&@.")
for _ in range(23):
    R.append(D * 26 + "@=+&@.")
R.append(D * 25 + "@@=+&@@")
for b in ["@:====+@", "@=====+@", "@+++++&@", "@+&&&&&@", "@&&&&&&@", "@&&&&&&@", "@&&&&&&@", "@&&&&&&@", "@@@@@@@@"]:
    R.append(D * 24 + b)
assert len(R) == 48, len(R)
for i, r in enumerate(R):
    assert len(r) == 32, (i + 1, len(r))
open("traffic_light-post.txt", "w").write("\n".join(R) + "\n")
print("ok")
