# C: 세워 둔 말아 놓은 매트
c = C(32, 32)
# 몸통 원기둥 (정면): 폭 12, 높이 24
x0, w, y0, h = 10, 12, 4, 25
c.rect(x0, y0 + 2, w, h - 2, G(3))
c.vl(x0, y0 + 2, h - 2, G(5)); c.vl(x0 + 1, y0 + 2, h - 2, G(4))
c.vl(x0 + w - 1, y0 + 2, h - 2, G(1)); c.vl(x0 + w - 2, y0 + 2, h - 2, G(2))
# 윗면 타원 + 말린 소용돌이
for y, xs, xe in [(y0, x0 + 3, x0 + w - 3), (y0 + 1, x0 + 1, x0 + w - 1)]:
    c.hl(xs, y, xe - xs, G(4))
c.hl(x0 + 3, y0, w - 6, G(5))
c.hl(x0 + 4, y0 + 1, 4, G(2)); c.hl(x0 + 6, y0 + 2, 3, G(1)); c.px(x0 + 5, y0 + 1, G(1))
# 아래 둥글림
c.hl(x0 + 1, y0 + h, w - 2, G(0)); c.px(x0, y0 + h - 1, G(0)); c.px(x0 + w - 1, y0 + h - 1, G(0))
# 나선 가로 줄무늬(말린 층)
for yy in (10, 15, 20, 25):
    c.hl(x0 + 1, yy, w - 2, G(2)); 
# 묶음 끈 두 줄
for yy in (12, 22):
    c.rect(x0, yy, w, 2, ('vlinen', 4)); c.hl(x0, yy + 1, w, ('vlinen', 2)); c.px(x0 + 3, yy, ('vlinen', 6))
c.px(x0, y0 + 2, '.'); c.px(x0 + w - 1, y0 + 2, '.')
c.shadow(9, 29, 16, 2)
c.px(0, 31, '.'); c.px(31, 31, '.')
c.save(out('gym_mat', 'C'), '실루엣 다르게: 매트를 돌돌 말아 세워 둔 원통, 윗면에 말린 나선, 크림 끈 두 줄로 묶음')
