K, W_ = 'vblack', 'vwhite'
def L0():
    return {'0': (K, 0), '1': (K, 1), '2': (K, 2), '3': (K, 3), '4': (K, 4), '5': (K, 5), '6': (K, 6),
            'w': (W_, 5), 'x': (W_, 3), 'y': (W_, 1), 'z': (W_, 6),
            'i': ('viron', 3), 'j': ('viron', 5), 'k': ('vbrass', 4)}

def bench(c, x, y, w, seat, top, side, edge):
    """의자: 윗면 2줄 + 앞면 2줄 + 다리."""
    c.rect(x, y, w, 2, top); c.hl(x, y, w, edge)
    c.rect(x, y + 2, w, 2, seat)
    c.hl(x, y + 3, w, side)
    for px in (x + 1, x + w - 2):
        c.vl(px, y + 4, 3, side)

def piano_A():
    c = C(48, 32)
    L = L0()
    # 뚜껑(열림): 뒤로 기운 판, 안쪽 면이 보인다
    poly(c, [(6, 2), (30, 2), (40, 8), (12, 9)], '0')
    poly(c, [(7, 3), (29, 3), (38, 8), (13, 8)], '3')
    c.hl(8, 3, 21, '5'); c.hl(8, 4, 8, '4')   # 빛 쪽(왼쪽 위) 광택 한 줄
    c.hl(13, 8, 25, '2')                      # 뚜껑 아랫변 그늘
    # 뚜껑 받침대
    c.vl(37, 9, 6, 'j'); c.put(37, 9, 'j')
    # 몸통 윗면(날개 모양): 오른쪽이 둥글게 좁아짐
    poly(c, [(3, 15), (12, 10), (38, 10), (43, 14), (44, 19), (41, 22), (3, 22)], '0')
    poly(c, [(4, 15), (13, 11), (37, 11), (42, 14), (43, 19), (40, 21), (4, 21)], '2')
    c.hl(6, 13, 3, '4'); c.hl(13, 11, 24, '4'); c.vl(4, 16, 5, '4')   # 빛 가장자리
    c.hl(6, 15, 34, '3'); c.hl(4, 16, 38, '3')                        # 윗면 살짝 밝게
    c.hl(30, 20, 11, '1'); c.vl(43, 15, 4, '1')                       # 오른쪽 아래 더 어둡게
    # 건반 덮개 앞판
    c.rect(4, 22, 37, 2, '0'); c.hl(5, 22, 35, '3'); c.hl(5, 23, 35, '1')
    # 건반 줄
    c.rect(6, 22, 30, 1, '0')
    c.rect(7, 22, 28, 3, 'w'); c.hl(7, 24, 28, 'x')
    for x in range(7, 35, 2): c.put(x + 1, 23, 'y') if False else None
    for x in range(8, 35, 2): c.vl(x, 23, 2, 'y')
    for bx in (9, 11, 15, 17, 19, 23, 25, 29, 31, 33):
        c.vl(bx, 22, 2, '0')
    c.hl(6, 25, 30, '0')
    # 앞판(건반 아래)과 다리
    c.rect(4, 25, 37, 2, '2'); c.hl(4, 25, 37, '3'); c.hl(4, 26, 37, '1')
    for lx in (5, 38):
        c.rect(lx, 27, 3, 3, '2'); c.vl(lx, 27, 3, '4'); c.vl(lx + 2, 27, 3, '0'); c.hl(lx, 29, 3, '0')
    c.rect(20, 27, 6, 1, '1')                 # 페달 상자
    c.put(21, 28, 'k'); c.put(23, 28, 'k'); c.put(25, 28, 'k')
    # 의자(앞쪽, 낮게)
    bench(c, 13, 25, 16, '3', '4', '1', '5')
    c.hl(14, 26, 6, '5')
    # 발치 그림자
    for x in range(8, 45): c.put(x, 31, '~') if c.get(x, 31) == '.' else None
    for x in range(30, 46):
        if c.get(x, 30) == '.': c.put(x, 30, '-')
    for x in range(44, 47):
        for y in range(25, 31): 
            if c.get(x, y) == '.': c.put(x, y, '-')
    return c, L

