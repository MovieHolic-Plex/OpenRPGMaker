def piano_C():
    """실루엣: 뚜껑이 높이 솟은 삼각 날개, 굵은 건반 띠, 둥근 꼬리"""
    c = C(48, 32)
    L = L0()
    # 높이 솟은 뚜껑: 왼쪽 경첩에서 오른쪽 위로 활짝
    poly(c, [(5, 12), (8, 1), (42, 1), (45, 9), (12, 12)], '0')
    poly(c, [(6, 12), (9, 2), (41, 2), (44, 9), (13, 11)], '3')
    c.hl(10, 2, 30, '5'); c.vl(9, 3, 8, '5'); c.hl(12, 3, 14, '4')
    c.hl(14, 10, 30, '2'); c.hl(16, 9, 26, '2')
    # 받침 대각선
    line(c, 38, 10, 34, 15, 'j'); line(c, 39, 10, 35, 15, '5')
    # 몸통: 큰 D자 (오른쪽 둥글게)
    poly(c, [(2, 15), (34, 13), (43, 16), (46, 20), (43, 23), (2, 23)], '0')
    poly(c, [(3, 15), (34, 14), (42, 16), (45, 20), (42, 22), (3, 22)], '2')
    c.hl(4, 15, 30, '4'); c.vl(3, 16, 6, '4'); c.hl(35, 15, 6, '3')
    c.hl(26, 21, 16, '1'); c.vl(45, 18, 3, '1')
    # 굵은 건반 띠
    c.rect(4, 22, 34, 4, '0'); c.hl(5, 22, 32, '4')
    c.rect(5, 23, 32, 3, 'w'); c.hl(5, 25, 32, 'x')
    for x in range(7, 37, 3): c.vl(x, 24, 2, 'y')
    for bx in range(8, 36, 3):
        if (bx // 3) % 7 not in (2, 6): c.rect(bx, 23, 2, 2, '0')
    c.hl(4, 26, 34, '0')
    # 다리 셋(피아노 다리는 굵은 원통)
    c.rect(4, 27, 34, 1, '1')
    for lx in (4, 33):
        c.rect(lx, 27, 4, 3, '2'); c.vl(lx, 27, 3, '4'); c.vl(lx + 3, 27, 3, '0'); c.hl(lx, 29, 4, '0')
    c.rect(17, 27, 6, 2, '1'); c.hl(17, 27, 6, '3'); c.put(18, 28, 'k'); c.put(20, 28, 'k'); c.put(22, 28, 'k')
    # 의자: 둥근 스툴
    poly(c, [(40, 25), (46, 25), (47, 26), (46, 28), (41, 28), (39, 26)], '0')
    poly(c, [(41, 25), (45, 25), (46, 26), (45, 27), (41, 27), (40, 26)], '3')
    c.hl(41, 25, 4, '5'); c.vl(42, 28, 2, '1'); c.vl(45, 28, 2, '0')
    for x in range(6, 47):
        if c.get(x, 31) == '.': c.put(x, 31, '~')
    for x in range(30, 47):
        if c.get(x, 30) == '.': c.put(x, 30, '-')
    return c, L

