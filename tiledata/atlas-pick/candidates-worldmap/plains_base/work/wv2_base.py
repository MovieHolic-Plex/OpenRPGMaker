#!/usr/bin/env python3
"""wv2 plains_base A/B/C. 손으로 놓은 좌표(도장) -> 48x16 wgrass 2~4단. 세 칸 평균 명도 같게(체크 8 이내)."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '../../meadow/work'))
from wv2_lib import write_pxg
BASE = 3
# 도장: (dx,dy,단) 목록. 칸 안에서 16 주기로 감싼다(칸끼리 어떻게 섞여도 이음새 없음).
DIRS = {
 'A': [   # World.png 식: 민풀 바탕에 짧은 잎 낱개. 셋째 칸만 작은 덩이 하나
   [(2, 3, 2), (2, 2, 4), (11, 9, 2), (11, 8, 4), (6, 13, 4)],
   [(3, 2, 2), (4, 2, 2), (3, 1, 4), (12, 5, 2), (12, 4, 4), (7, 10, 2), (8, 10, 2), (7, 9, 4), (2, 13, 4), (13, 13, 2)],
   [(9, 3, 2), (10, 3, 2), (11, 3, 2), (10, 2, 4), (9, 2, 4), (3, 11, 4), (13, 12, 2)],
 ],
 'B': [   # 왼쪽 위 빛: 밝은 2칸 얼룩 + 오른쪽 아래 그늘 한 점
   [(3, 3, 4), (4, 3, 4), (3, 4, 4), (5, 4, 2), (4, 5, 2), (12, 10, 4), (13, 10, 4), (14, 11, 2), (13, 11, 2)],
   [(8, 2, 4), (9, 2, 4), (8, 3, 4), (10, 3, 2), (9, 4, 2), (2, 11, 4), (3, 11, 4), (4, 12, 2), (3, 12, 2)],
   [(2, 6, 4), (3, 6, 4), (2, 7, 4), (4, 7, 2), (3, 8, 2), (11, 13, 4), (12, 13, 4), (13, 14, 2), (12, 14, 2), (9, 1, 2)],
 ],
 'C': [   # 토끼풀 무리: 십자 셋 점(밝은 가운데 + 어두운 곁잎). 한 칸에 한두 무리
   [(4, 4, 4), (3, 4, 2), (5, 4, 2), (4, 5, 2), (11, 11, 4), (10, 11, 2), (12, 11, 2), (11, 12, 2)],
   [(9, 3, 4), (8, 3, 2), (10, 3, 2), (9, 4, 2), (3, 10, 4), (2, 10, 2), (4, 10, 2), (3, 11, 2), (13, 13, 2)],
   [(6, 7, 4), (5, 7, 2), (7, 7, 2), (6, 8, 2), (13, 2, 4), (12, 2, 2), (14, 2, 2), (13, 3, 2), (2, 13, 2)],
 ],
}
NOTE = {
 'A': 'World.png 식 3색 민풀. 짧은 잎 낱개(어둠 아래+밝음 위)만 흩어 놓고 셋째 칸에 작은 덩이 하나',
 'B': '왼쪽 위 빛: 밝은 얼룩 둘레 오른쪽 아래에 그늘 점. 그림자 없이 명도 차만으로 결',
 'C': '토끼풀 무리(밝은 가운데+어두운 곁잎). 한 칸에 한두 무리, 나머지는 민풀',
}
def build(k):
    grid = [[('wgrass', BASE)] * 48 for _ in range(16)]
    for ci, dots in enumerate(DIRS[k]):
        for dx, dy, st in dots:
            grid[dy % 16][ci * 16 + dx % 16] = ('wgrass', st)
    write_pxg(f'../wv2-{k}.pxg', f'plains_base wv2-{k}', grid, 48, 16)
    open(f'../wv2-{k}.note', 'w').write(NOTE[k] + '\n')
    L = {2: 0x36 * .3 + 0x78 * .59 + 0x34 * .11, 3: 0x54 * .3 + 0x9c * .59 + 0x46 * .11, 4: 0x82 * .3 + 0xbe * .59 + 0x64 * .11}
    for ci in range(3):
        m = sum(L[grid[y][ci * 16 + x][1]] for y in range(16) for x in range(16)) / 256
        print(k, ci, round(m, 2))
for k in 'ABC': build(k)
