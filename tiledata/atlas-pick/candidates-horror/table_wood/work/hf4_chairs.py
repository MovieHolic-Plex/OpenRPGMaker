import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from hf4_lib import *
MATS = {'m': 'mahog'}

def legs_front(c, tones=('1', '4', '2'), y=13):
    c.hline(13, 5, 10, '1')                                   # 앞 두께 밑 테(다리 사이는 비어 바닥이 보인다)
    for x0 in (2, 11):
        c.row(13, x0, ''.join(tones)); c.row(14, x0, ''.join(tones)); c.row(15, x0, '111')

# ── chair_wood: 남쪽을 보는 의자(등받이 앞면 + 앉는 판 윗면 + 앞다리) ─────────────────────────────
def cw_A():
    c = Cv(16, 16, mahog_legend(), MATS)
    c.hline(1, 3, 12, '1')
    c.row(2, 3, '1' + '6' * 7 + '5' + '1')
    for y in range(3, 7): c.row(y, 3, '1' + '5' + '4' * 6 + '3' + '1')
    c.row(3, 3, '1' + '5' + '5' * 6 + '3' + '1')
    c.vline(6, 4, 6, '2'); c.vline(9, 4, 6, '2')              # 세로 살 둘 사이 홈
    c.hline(7, 2, 13, '1')
    c.row(8, 2, '1' + '6' + '5' * 8 + '4' + '1')
    for y in (9, 10): c.row(y, 2, '1' + '5' * 10 + '1')
    c.row(10, 2, '1' + '4' * 10 + '1')
    c.row(11, 2, '1' + '4' + '3' * 8 + '2' + '1')
    c.row(12, 2, '1' + '2' * 10 + '1')
    legs_front(c)
    c.emit('chair_wood', 'A', 'A: v5 의자 S 꼴 깨끗하게 — 윗 테 밝게, 세로 살 둘(홈 2단), 앉는 판 5단 윗면에 앞 모서리 한 단 꺾임, 앞다리 둘. 탁자와 같은 mahog 3~6단')

def cw_B():
    c = Cv(16, 16, mahog_legend(), MATS)
    c.hline(1, 3, 12, '1')
    c.row(2, 3, '1' + '6' * 8 + '1')
    for y in range(3, 7): c.row(y, 3, '1' + '5' * 8 + '1')
    c.vline(6, 3, 6, '1'); c.vline(9, 3, 6, '1')              # 홈을 새까맣게 — 어두운 방에서도 살 둘이 읽힘
    c.hline(7, 2, 13, '1')
    for y in (8, 9, 10): c.row(y, 2, '1' + '6' * 10 + '1')
    c.row(10, 2, '1' + '5' * 10 + '1')
    c.row(11, 2, '1' + '3' * 10 + '1')
    c.row(12, 2, '1' + '1' * 10 + '1')
    legs_front(c, ('1', '5', '3'))
    c.emit('chair_wood', 'B', 'B: 어두운 방용 — 앉는 판·윗 테를 6단으로 크게 밝히고 앞 두께는 1~3 으로 떨궈 윗면이 먼저 뜸, 살 사이 홈은 1단으로 굵게')

def cw_C():
    c = Cv(16, 16, mahog_legend(), MATS)
    c.hline(0, 6, 9, '1')                                        # 등받이 위 장식(왕관 머리)
    c.row(1, 3, '1' + '6' * 3 + '6' * 2 + '6' * 3 + '5' + '1'); c.row(1, 3, '11' + '6666' + '6' + '5' + '11')
    c.row(2, 3, '1' + '5' + '6' * 6 + '4' + '1')
    for y in range(3, 7): c.row(y, 3, '1' + '5' + '4' * 6 + '3' + '1')
    for x, t in ((5, '2'), (8, '2')): c.vline(x, 3, 6, t)     # 새긴 홈 둘(2px 띄운 살 사이)
    for x in (6, 9): c.vline(x, 3, 6, '5')                     # 살의 밝은 등
    c.hline(7, 2, 13, '1')
    c.row(8, 2, '1' + '5' + '5' * 8 + '2' + '1')
    c.row(9, 2, '1' + '4' * 3 + '5' * 3 + '4' * 3 + '2' + '1')  # 널 이음 자리
    c.row(10, 2, '1' + '3' + '4' * 8 + '2' + '1')
    c.row(11, 2, '1' + '4' + '3' * 8 + '2' + '1')
    for x in range(3, 13, 3): c.px(x, 12, '3')
    c.row(12, 2, '1' + '2' * 10 + '1')
    for x in (4, 7, 10): c.px(x, 12, '4')
    c.hline(13, 5, 10, '1')
    for x0 in (2, 11):                                            # 깎은 다리: 밝은 마디 · 어두운 마디
        c.row(13, x0, '152'); c.row(14, x0, '132'); c.row(15, x0, '111')
    c.emit('chair_wood', 'C', 'C: 마녀의 집 결 — 왕관 머리 등받이, 새긴 홈과 살의 밝은 등, 앉는 판 널 이음, 앞 두께 조각 점, 깎은 다리 마디')

# ── chair_wood_back: 북쪽(탁자)을 보는 의자 — 등받이 뒷면이 앞에 크게 ──────────────────────────
def cb_A():
    c = Cv(16, 16, mahog_legend(), MATS)
    c.hline(1, 3, 12, '1')
    c.row(2, 3, '1' + '5' * 8 + '1'); c.row(3, 3, '1' + '4' * 8 + '1')   # 앉는 판 윗면 조금(등받이 너머)
    c.hline(4, 2, 13, '1')
    c.row(5, 2, '1' + '6' + '6' * 8 + '5' + '1')                  # 등받이 윗 테
    for y in range(6, 11): c.row(y, 2, '1' + '5' + '4' * 8 + '3' + '1')
    c.vline(6, 6, 10, '2'); c.vline(9, 6, 10, '2')              # 뒷면 살 둘 사이 홈
    c.row(11, 2, '1' + '3' * 10 + '1'); c.hline(12, 3, 12, '1')
    for x0 in (3, 10):                                             # 등받이 기둥 = 뒷다리
        c.row(12, x0, '1421'); c.row(13, x0, '1421'); c.row(14, x0, '1421'); c.row(15, x0, '1111')
    c.hline(12, 5, 10, '1')
    c.emit('chair_wood_back', 'A', 'A: 등받이 뒷면이 크게 — 윗 테, 살 둘 사이 홈, 등받이 밑 두께 3단, 기둥이 뒷다리로 이어짐. 앉는 판은 등받이 위로 두 줄만. chair_wood 와 같은 mahog')

