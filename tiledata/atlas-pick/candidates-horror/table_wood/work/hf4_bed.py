MATS = {'m': 'mahog', 's': 'sheet', 'v': 'velv', 't': 'tarn'}
def legend():
    lg = mahog_legend()
    for i, ch in enumerate('abcdefg'): lg[ch] = ('s', i)     # sheet 0~6
    for i, ch in enumerate('hijklm'): lg[ch] = ('v', i)      # velv 0~5
    for i, ch in enumerate('TUVWXY'): lg[ch] = ('t', i)      # tarn 0~5
    return lg
def new():
    return Cv(16, 48, legend(), MATS)
def R(c, y, s):
    assert len(s) == 16, (y, len(s), s)
    c.row(y, 0, s)
def rep(c, y0, y1, s):
    for y in range(y0, y1 + 1): R(c, y, s)

