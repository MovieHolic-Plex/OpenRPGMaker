MATS = {'m': 'mahog', 't': 'tarn', 'f': 'flame', 'w': 'wax'}
def legend():
    lg = mahog_legend()
    for i, ch in enumerate('TUVWXY'): lg[ch] = ('t', i)
    for i, ch in enumerate('abcdef'): lg[ch] = ('f', i)
    for i, ch in enumerate('ghijkl'): lg[ch] = ('w', i)
    return lg
def new(): return Cv(16, 16, legend(), MATS)
def R(c, y, s, x0=0):
    assert x0 + len(s) <= 16, (y, len(s), s)
    c.row(y, x0, s)

# ───────── 서랍장 (16x16) ─────────
def drawers(c, y0, edge, face, dark, knobtone, side_l, side_r, deco=None):
    """서랍 셋(각 3줄). 바깥 x0/x15 는 윤곽 '1'(또는 B는 '0')."""
    for k in range(3):
        y = y0 + 3 * k
        R(c, y, 'O' + side_l + edge * 12 + side_r + 'O')
        R(c, y + 1, 'O' + side_l + face * 12 + side_r + 'O')
        R(c, y + 2, 'O' + side_l + dark * 12 + side_r + 'O')
        c.px(5, y + 1, knobtone); c.px(10, y + 1, knobtone)
def fixO(c, o):
    for y in range(c.h):
        for x in range(c.w):
            if c.g[y][x] == 'O': c.g[y][x] = o

