def frame(g, mat, mold, foot_base, foot_mort, base_top, base_dark):
    # 몰딩 y0-2
    for y, t in enumerate(mold): g.hline(0, y, 32, mat, t)
    # 걸레받이 y29-31 : 맨 윗줄 밝게, 아래 둘은 가장 어둡게
    g.hline(0, 29, 32, mat, base_top); g.hline(0, 30, 32, mat, base_dark); g.hline(0, 31, 32, mat, base_dark)

def A():
    g = G(32, 32, wrapx=True)
    frame(g, 's', [1, 5, 3], 3, 1, 4, 0)
    M = 1
    course(g, 's', 3, 5, 0, [(16, 4), (8, 5), (8, 4)], 's', M)
    course(g, 's', 9, 5, 4, [(16, 4), (8, 4), (8, 5)], 's', M)
    course(g, 's', 15, 5, 6, [(8, 5), (16, 4), (8, 4)], 's', M)
    # 밑돌 y21-27 : 한 단 어둡게
    g.hline(0, 20, 32, 's', M)
    course(g, 's', 21, 7, 12, [(16, 3), (16, 4)], 's', 1, mort_row=False)
    g.hline(0, 28, 32, 's', 1)
    # 이끼 한 곳(3번째 줄 오른쪽 이음매 둘레)
    g.pts('m', [(21, 19, 3), (22, 19, 3), (23, 19, 2), (22, 18, 3), (21, 18, 2), (24, 19, 2)])
    return g, {'s': 'vstone', 'm': 'hmoss'}

