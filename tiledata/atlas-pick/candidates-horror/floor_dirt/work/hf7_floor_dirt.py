def stone(g, x, y, mat='s', t=(3, 2, 1)):
    # 3×2 작은 돌: 윗줄 밝게, 아랫줄 어둡게, 왼쪽 아래에 그림자 한 점
    g.hline(x, y, 3, mat, t[0]); g.hline(x, y + 1, 3, mat, t[1]); g.put(x + 1, y + 2, 'd', 1); g.put(x + 2, y + 2, 'd', 1)

def base(fill, n):
    g = G(32, 32, True, True); g.rect(0, 0, 32, 32, 'd', fill); return g

def A():
    g = base(2, 0)
    # 밟혀 다져진 자리: 타원 모양 톤 3 (손으로 행별 폭)
    for y, (x0, w) in enumerate([(8, 6), (6, 10), (5, 12), (5, 12), (6, 10), (8, 6)], start=10):
        g.hline(x0, y, w, 'd', 3)
    g.pts('d', [(10, 12, 4), (11, 12, 4), (14, 13, 4), (9, 14, 4)])
    # 어두운 흙덩이 점 (톤 1) — 손으로 찍음
    g.pts('d', [(2, 3, 1), (3, 3, 1), (21, 5, 1), (28, 9, 1), (29, 9, 1), (4, 24, 1), (16, 27, 1), (17, 27, 1), (26, 21, 1), (12, 1, 1), (23, 29, 1)])
    stone(g, 22, 15); stone(g, 3, 18); stone(g, 27, 27, t=(3, 2, 2))
    return g, {'d': 'soil', 's': 'vstone'}

def B():
    g = base(3, 0)
    for y, (x0, w) in enumerate([(9, 4), (7, 8), (6, 10), (6, 10), (7, 8), (9, 4)], start=11):
        g.hline(x0, y, w, 'd', 4)
    g.pts('d', [(3, 3, 1), (4, 3, 1), (4, 4, 1), (22, 6, 1), (23, 6, 1), (28, 12, 1), (6, 25, 1), (7, 25, 1), (7, 26, 1), (18, 27, 1), (19, 27, 1), (14, 2, 1)])
    stone(g, 22, 17, t=(4, 3, 2)); stone(g, 3, 19, t=(4, 3, 2))
    return g, {'d': 'soil', 's': 'grave'}

def C():
    g = base(2, 0)
    for y, (x0, w) in enumerate([(4, 6), (3, 9), (3, 10), (4, 8)], start=17):
        g.hline(x0, y, w, 'd', 3)
    # 굵은 나무 뿌리(rot) 한 가닥이 대각으로 가로지름
    for i, (x, y) in enumerate([(12, 2), (13, 3), (14, 3), (15, 4), (16, 5), (17, 5), (18, 6), (19, 7), (20, 7), (21, 8)]):
        g.put(x, y, 'w', 3); g.put(x, y + 1, 'w', 2)
    # 웅덩이 자국(가장 어두운 얼룩) + 자갈
    g.rect(22, 21, 5, 2, 'd', 1); g.hline(23, 23, 3, 'd', 1); g.pts('d', [(23, 21, 0), (24, 21, 0)])
    g.pts('d', [(2, 3, 1), (3, 3, 1), (28, 3, 1), (8, 29, 1), (9, 29, 1), (14, 12, 1), (30, 15, 1), (16, 25, 4)])
    stone(g, 6, 8); stone(g, 26, 12, t=(3, 2, 2)); stone(g, 15, 18)
    g.pts('m', [(27, 26, 2), (28, 26, 2), (28, 27, 1)])
    return g, {'d': 'soil', 's': 'vstone', 'w': 'rot', 'm': 'hmoss'}

