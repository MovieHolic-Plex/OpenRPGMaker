#!/usr/bin/env python3
"""floor_hosp_linoleum hf6 A·B·C — 32x32 @tile. 리놀륨 긴 판(높이 16px 가로 띠 둘), 이음은 띠마다 한 곳.
좌표는 전부 손으로 정한 목록. 모든 좌표는 32 로 감싼다(사방 이어짐)."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from hf6_lib import C, emit
SLUG, W = 'floor_hosp_linoleum', 'hf6'
MATS = {'a': 'ward', 's': 'sheet', 'g': 'grave', 'r': 'rust', 'm': 'murk', 'd': 'dust', 't': 'tin'}

def pts(c, mat, tone, lst):
    for (y, x) in lst: c.put(y, x, mat, tone)

def build_A():
    c = C(32, 32, wrap=True)
    c.rect(0, 31, 0, 31, 'a', 3)
    c.row(0, 0, 31, 'a', 2); c.row(16, 0, 31, 'a', 2)                # 띠 사이 이음(어두운 홑줄)
    c.col(9, 1, 15, 'a', 2); c.col(24, 17, 31, 'a', 2)               # 띠마다 끝 이음 한 곳
    # 광택 한 줄(왼쪽 위 빛): 짧게 끊은 밝은 홑줄
    for x in list(range(3, 12)) + list(range(14, 17)): c.put(6, x, 'a', 4)
    # 닳은 자리 하나: 밑판(sheet 1)이 비친다
    for (y, x) in [(10, 21), (10, 22), (10, 23), (11, 20), (11, 21), (11, 22), (11, 23), (11, 24), (12, 21), (12, 22), (12, 23)]: c.put(y, x, 's', 1)
    # 생채기 하나
    pts(c, 'a', 2, [(25, 6), (26, 7), (26, 8)])
    return c

def build_B():
    c = C(32, 32, wrap=True)
    c.rect(0, 31, 0, 31, 'a', 2)
    c.row(0, 0, 31, 'a', 1); c.row(16, 0, 31, 'a', 1)
    c.row(1, 0, 31, 'a', 3); c.row(17, 0, 31, 'a', 3)                # 이음 바로 아래 밝은 줄 = 방 모양이 어둠에서도 남게
    c.col(9, 2, 15, 'a', 1); c.col(24, 18, 31, 'a', 1)
    for x in range(4, 14): c.put(8, x, 'a', 3)
    for x in range(18, 27): c.put(24, x, 'a', 3)
    return c

def build_C():
    c = C(32, 32, wrap=True)
    c.rect(0, 31, 0, 31, 'a', 3)
    c.row(0, 0, 31, 'a', 1); c.row(16, 0, 31, 'a', 1)
    c.col(9, 1, 15, 'a', 1); c.col(24, 17, 31, 'a', 1)
    # 대리석 무늬 리놀륨: 어두운 점 덩이와 노르스름한 점 덩이를 손으로
    pts(c, 'a', 2, [(3,4),(3,5),(4,4),(2,14),(3,15),(3,16),(6,22),(6,23),(7,23),(12,3),(12,4),(13,4),(10,13),(11,13),(11,14),(14,27),(14,28),(15,27),
                    (19,6),(19,7),(20,7),(22,18),(22,19),(23,19),(28,12),(28,13),(29,13),(26,28),(27,28),(27,29),(20,26),(21,26)])
    pts(c, 's', 1, [(4,10),(5,10),(5,11),(9,26),(9,27),(10,27),(13,17),(13,18),(14,18),(18,15),(19,15),(19,14),(24,3),(24,4),(25,4),(30,21),(30,22),(29,22),(21,9),(22,9)])
    pts(c, 'a', 4, [(2,7),(5,18),(8,28),(11,9),(14,23),(19,20),(22,4),(26,16),(29,26),(24,10)])
    # 광택 한 줄
    for x in range(4, 12): c.put(7, x, 'a', 4)
    # 녹물 자국(눌은 물)
    pts(c, 'r', 1, [(26,22),(26,23),(27,21),(27,22),(27,23),(27,24),(28,22),(28,23)])
    pts(c, 'r', 2, [(27,22),(27,23)])
    # 이음 들뜸: 이음 옆 밝은 한 줄
    for y in range(2, 8): c.put(y, 10, 'a', 4)
    return c

NOTES = {
 'A': 'v5 결 기본: ward3 한 색 리놀륨, 16px 가로 띠 둘(띠마다 끝 이음 한 곳), 광택 홑줄 하나·닳은 자리(sheet1) 하나·생채기 하나 — 벽(ward4)보다 한 단 이상 어둡게',
 'B': '어둠에서 읽히게: 바닥 ward2 큰 면 한 장, 띠 이음 grave급 ward1 홑줄 + 바로 밑 ward3 밝은 줄로 방 모양을 남김, 무늬 없음',
 'C': '재료 결: 대리석 무늬 리놀륨(어두운 덩이·누런 덩이·광택 점을 손으로), 이음 옆 들뜬 밝은 줄, 눌은 녹물 자국 하나',
}
for L, b in (('A', build_A), ('B', build_B), ('C', build_C)):
    emit(SLUG, W, L, b(), MATS, NOTES[L], tile=True)
print('ok')
