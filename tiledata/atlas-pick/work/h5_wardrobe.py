from h5_lib import *
L = {str(i): ('mahog', i) for i in range(7)}
L.update({'d': ('dust', 3), 'D': ('dust', 5), 'W': ('dust', 6),
          'v': ('void', 1), 'V': ('void', 0), 'w': ('void', 2),
          't': ('tarn', 3), 'T': ('tarn', 5), 'g': ('tarn', 1),
          'b': ('bisque', 4), 'B': ('bisque', 2), 's': ('mahog', 2)})

def body(c, tones, lit=True):
    # tones: 문 색 (edge, face, dark)
    e, f, k = tones
    c.rect(0, 1, 16, 29, '0')
    c.hl(1, 1, 14, '5' if lit else '4')
    c.hl(1, 2, 14, e); c.hl(1, 3, 14, f); c.hl(1, 4, 14, '1')
    # base
    c.hl(1, 27, 14, f); c.hl(1, 28, 14, k)

def door(c, x0, w, e, f, k, y0=5, y1=26):
    c.rect(x0, y0, w, y1 - y0 + 1, f)
    c.vl(x0, y0, y1 - y0 + 1, e)
    c.vl(x0 + w - 1, y0, y1 - y0 + 1, k)
    # 들어간 판: 위·왼 어둡게, 아래·오른 밝게
    if w >= 5:
        c.hl(x0 + 1, y0 + 2, w - 2, k); c.hl(x0 + 1, y1 - 2, w - 2, e)
        c.vl(x0 + 1, y0 + 2, y1 - y0 - 3, k)
        c.vl(x0 + w - 2, y0 + 3, y1 - y0 - 4, e)

# ---- A
c = C(16, 32); body(c, ('4', '3', '2'))
door(c, 1, 7, '5', '4', '2')
c.rect(8, 5, 3, 22, 'V'); c.vl(8, 5, 22, 'w'); c.vl(9, 5, 22, 'v')
door(c, 11, 4, '4', '3', '1')
c.px(6, 15, 't'); c.px(6, 16, 'T'); c.px(12, 15, 'g'); c.px(12, 16, 't')
c.row(3, 1, 'ddDDdd'); c.px(11, 1, 'd'); c.px(12, 1, 'd')     # 윗면 먼지
c.px(3, 12, '1'); c.px(3, 13, '1'); c.px(4, 14, '1')           # 문 금 하나
save('wardrobe_ajar', 'h5-A', c, L, 'v5 옷장 크기·접지선 그대로. 오른쪽 문이 벌어져 틈 속 void 3px, 윗면 먼지 한 줄, 왼쪽 문에 금, 놋쇠 문고리 청록 바램')

