from lib import *
def top(c, x, y, w, h, m, back, body, hi, left=None, right=None):
    """윗면 T: 첫 줄 뒤 모서리(back), 몸통(body), 마지막 줄 앞 모서리 하이라이트(hi), 왼쪽 열 밝게."""
    c.R(x, y, w, h, m, body)
    c.R(x, y, w, 1, m, back)
    c.R(x, y+h-1, w, 1, m, hi)
    if left is not None: c.R(x, y+1, 1, h-1, m, left)
    if right is not None: c.R(x+w-1, y, 1, h-1, m, right)

def bedside_cabinet():
    c = Cv(16, 16, {'s':'sheet','t':'tin'})
    top(c, 2, 2, 12, 6, 's', 3, 5, 6, left=6, right=4)      # 윗면 6줄
    c.R(2, 8, 12, 1, 's', 0)                               # 처마 그늘
    c.R(2, 9, 12, 5, 's', 2)                               # 앞면(윗면보다 두 단 어둡게)
    c.R(2, 9, 12, 1, 's', 3)                               # 서랍1 윗 모서리
    c.R(2, 10, 12, 1, 's', 2)
    c.R(2, 11, 12, 1, 's', 0)                              # 서랍 사이 틈
    c.R(2, 12, 12, 1, 's', 3); c.R(2, 13, 12, 1, 's', 2)
    c.R(2, 9, 1, 5, 's', 3); c.R(13, 9, 1, 5, 's', 1)
    c.R(7, 10, 2, 1, 't', 4); c.R(7, 13, 2, 1, 't', 4)     # 손잡이
    c.R(3, 14, 2, 2, 't', 3); c.R(11, 14, 2, 2, 't', 2)
    c.R(3, 15, 2, 1, 't', 1); c.R(11, 15, 2, 1, 't', 1)
    outline(c, 1, bt=0)
    c.save('bedside_cabinet', note='v34-A: 3/4 시점 — 윗면 6줄(뒤 모서리·밝은 판·앞 모서리 하이라이트) + 처마 그늘 + 서랍 두 칸 앞면 + 다리. 같은 sheet/tin 램프')

def bench_gallery():
    c = Cv(32, 16, {'m':'velv','l':'tin'})
    top(c, 2, 2, 28, 7, 'm', 3, 4, 5, left=5, right=3)     # 시트 윗면
    for x in range(5, 28, 4):                             # 누빔 단추
        c.p(x, 5, 'm', 2); c.p(x, 4, 'm', 5)
    c.R(2, 9, 28, 1, 'm', 1)                               # 처마 그늘
    c.R(2, 10, 28, 2, 'm', 3)                              # 앞 두께
    c.R(2, 10, 28, 1, 'm', 4)
    c.R(2, 12, 28, 1, 'm', 1)
    c.R(4, 12, 4, 4, 'l', 3); c.R(24, 12, 4, 4, 'l', 3)    # 쇠다리
    c.R(4, 12, 1, 4, 'l', 5); c.R(24, 12, 1, 4, 'l', 5)
    c.R(7, 12, 1, 4, 'l', 1); c.R(27, 12, 1, 4, 'l', 1)
    c.R(4, 15, 4, 1, 'l', 1); c.R(24, 15, 4, 1, 'l', 1)
    outline(c, 1, mats={'m'}, bt=0)
    c.save('bench_gallery', note='v34-A: 3/4 시점 — 가죽 시트 윗면 7줄(뒤 그늘·밝은 판·앞 모서리) + 앞 두께 + 쇠다리 둘. 같은 velv/tin 램프')

def sofa_sheet():
    c = Cv(32, 16, {'a':'dust','b':'rot'})
    # 등받이 윗면 + 앞면
    top(c, 5, 1, 22, 3, 'a', 3, 5, 5, left=5)              # 등받이 윗(둥근 두루마리) 
    c.R(5, 4, 22, 3, 'a', 4)                               # 등받이 앞면
    c.R(5, 4, 3, 3, 'a', 5); c.R(24, 4, 3, 3, 'a', 3)
    for x in (11, 17, 23): c.R(x, 4, 1, 3, 'a', 2)        # 쿠션 주름
    c.R(5, 7, 22, 1, 'a', 0)                               # 등받이 밑 그늘
    # 앉는 면 윗
    top(c, 5, 8, 22, 4, 'a', 3, 4, 5, left=5)
    for x in (11, 17, 23): c.p(x, 9, 'a', 2); c.p(x, 10, 'a', 2)
    c.R(5, 12, 22, 1, 'a', 0)
    # 앞 천(가림천)
    c.R(4, 13, 24, 2, 'a', 3)
    for x in (7, 13, 19, 25): c.R(x, 13, 1, 2, 'a', 1)
    c.R(4, 13, 24, 1, 'a', 4)
    # 팔걸이(둥글게, 윗면 밝음)
    for xs, lt in ((0, 5), (27, 4)):
        c.R(xs+1, 4, 4, 1, 'a', 5)
        c.R(xs, 5, 5, 3, 'a', 5 if xs == 0 else 4)
        c.R(xs, 8, 5, 5, 'a', 4 if xs == 0 else 3)
        c.R(xs+1, 13, 4, 2, 'a', 3)
    c.R(0, 5, 1, 8, 'a', 5); c.R(31, 5, 1, 8, 'a', 3)
    c.R(0, 12, 5, 1, 'a', 1); c.R(27, 12, 5, 1, 'a', 1)
    c.R(4, 15, 2, 1, 'a', 1); c.R(26, 15, 2, 1, 'b', 1)
    c.R(9, 15, 2, 1, 'a', 1); c.R(21, 15, 2, 1, 'a', 1)
    outline(c, 1, bt=0)
    c.save('sofa_sheet', note='v34-A: 3/4 시점 — 천을 씌운 소파: 등받이 윗면, 등받이 앞면, 앉는 면 윗면(밝음), 앞 가림천 주름, 둥근 팔걸이 윗면. 같은 dust/rot 램프')

def armchair_sheet():
    c = Cv(16, 16, {'a':'dust','b':'rot'})
    top(c, 3, 1, 10, 4, 'a', 3, 5, 5, left=5)
    c.R(3, 5, 10, 2, 'a', 3); c.R(3, 5, 2, 2, 'a', 4); c.R(11, 5, 2, 2, 'a', 2)
    c.R(8, 5, 1, 2, 'a', 1)
    c.R(3, 7, 10, 1, 'a', 0)
    top(c, 3, 8, 10, 3, 'a', 3, 4, 5, left=5)
    c.R(3, 11, 10, 1, 'a', 0)
    c.R(3, 12, 10, 2, 'a', 3)
    for x in (5, 8, 11): c.R(x, 12, 1, 2, 'a', 1)
    for xs in (0, 13):
        c.R(xs, 4, 3, 1, 'a', 5)
        c.R(xs, 5, 3, 3, 'a', 5 if xs == 0 else 3)
        c.R(xs, 8, 3, 5, 'a', 4 if xs == 0 else 3)
    c.R(0, 12, 3, 2, 'a', 3); c.R(13, 12, 3, 2, 'a', 2)
    c.R(1, 14, 2, 1, 'a', 1); c.R(13, 14, 2, 1, 'a', 1)
    c.R(4, 14, 2, 1, 'a', 1); c.R(11, 14, 2, 1, 'b', 1)
    c.R(4, 15, 1, 1, 'a', 0); c.R(11, 15, 2, 1, 'b', 2)
    outline(c, 1, bt=0)
    c.save('armchair_sheet', note='v34-A: 3/4 시점 — 천 씌운 안락의자: 등받이 윗면·등받이 앞면·앉는 면 윗면(밝음)·앞 천·둥근 팔걸이. 같은 dust/rot 램프')

def broken_desk():
    c = Cv(16, 16, {'r':'rot','t':'tin','v':'void','w':'vdwood'})
    # 책상 윗판(한 다리가 부러져 왼쪽이 한 줄 처짐): 윗면 5줄
    top(c, 0, 4, 10, 5, 'r', 3, 5, 6, left=6, right=4)
    c.R(3, 5, 4, 1, 'r', 4); c.R(4, 7, 3, 1, 'r', 4); c.p(6, 6, 'r', 4)   # 칼 낙서
    c.R(0, 9, 10, 1, 'r', 1)                              # 처마 그늘
    c.R(0, 10, 10, 1, 'r', 3)
    # 오른쪽 다리 온전 / 왼쪽 다리 부러져 짧게 + 조각
    c.R(8, 10, 2, 6, 't', 3); c.R(8, 10, 1, 6, 't', 5)
    c.R(0, 11, 2, 3, 't', 3); c.R(0, 11, 1, 3, 't', 5)
    c.R(0, 14, 3, 1, 't', 1); c.R(3, 13, 1, 1, 't', 2)
    c.R(2, 15, 6, 1, 'v', 1)
    # 뒤집힌 의자(바닥이 위로): 밑면 T + 위로 솟은 다리 둘 + 등받이 앞
    c.R(11, 4, 1, 4, 'w', 5); c.R(15, 4, 1, 4, 'w', 4)
    c.R(11, 4, 1, 1, 'w', 6)
    top(c, 10, 8, 6, 4, 'w', 2, 4, 6, left=6, right=3)
    c.R(10, 12, 6, 1, 'w', 1)
    c.R(10, 13, 6, 2, 'w', 4); c.R(10, 13, 6, 1, 'w', 5)
    c.R(10, 15, 6, 1, 'w', 1)
    outline(c, 1, mats={'r','t','w'}, bt=0)
    c.save('broken_desk', note='v34-A: 3/4 시점 — 학생 책상 윗면 5줄(칼 낙서·왼쪽이 처짐) + 앞 두께 + 쇠다리(왼쪽 부러짐), 옆에 뒤집힌 의자(밑면이 윗면으로 보임). 같은 rot/tin/void/vdwood')

for f in (bedside_cabinet, bench_gallery, sofa_sheet, armchair_sheet, broken_desk): f()
