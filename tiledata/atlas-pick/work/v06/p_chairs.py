from lib import *
M = {'m': 'mahog'}
def chair_wood():
    c = Cv(16, 16, M)
    # 등받이 앞면(뒤에 서 있다): 윗 테 + 세로 살
    c.R(3, 1, 10, 1, 'm', 1)                 # 윤곽
    c.R(3, 2, 10, 1, 'm', 5)                 # 윗 테
    c.R(3, 3, 10, 4, 'm', 4)                 # 등판
    c.R(3, 3, 2, 4, 'm', 5); c.R(11, 3, 2, 4, 'm', 3)   # 기둥 좌 밝게/우 어둡게
    c.R(6, 3, 1, 4, 'm', 2); c.R(9, 3, 1, 4, 'm', 2)    # 살 사이 홈
    c.R(7, 3, 2, 4, 'm', 4)
    # 앉는 판 윗면 T 5줄
    c.R(2, 7, 12, 1, 'm', 2)                 # 뒤 모서리(등받이 그늘)
    c.R(2, 8, 12, 3, 'm', 5); c.R(2, 8, 1, 3, 'm', 6)
    c.R(2, 11, 12, 1, 'm', 6)                # 앞 모서리 하이라이트
    c.R(13, 8, 1, 3, 'm', 4)
    # 앞 두께 + 다리
    c.R(2, 12, 12, 1, 'm', 1)                # 처마 그늘
    c.R(2, 13, 12, 1, 'm', 3)                # 앞 띠
    c.R(2, 14, 2, 2, 'm', 4); c.R(12, 14, 2, 2, 'm', 3)
    c.R(2, 15, 2, 1, 'm', 2); c.R(12, 15, 2, 1, 'm', 1)
    outline(c, 1, bt=0)
    c.save('chair_wood', note='v34-A: 3/4 시점 — 앉는 판 윗면 5줄(뒤 그늘·밝은 판·앞 모서리 하이라이트) + 앞 두께 그늘 + 앞다리 둘, 등받이는 앞면. 같은 mahog 3~6단')
def chair_wood_back():
    c = Cv(16, 16, M)
    # 북쪽(탁자)을 보는 의자: 등받이 뒷면이 앞에 크게. 뒷면 판 = 앞면, 윗 테가 윗면 띠
    c.R(2, 0, 12, 1, 'm', 1)
    c.R(2, 1, 12, 4, 'm', 6)                 # 등받이 윗면(두께 위에서 보임) — 가장 밝게
    c.R(13, 1, 1, 4, 'm', 5)
    c.R(2, 5, 12, 1, 'm', 2)                 # 처마 그늘
    c.R(2, 6, 12, 5, 'm', 4)                 # 뒷판 앞면
    c.R(2, 6, 2, 5, 'm', 5); c.R(12, 6, 2, 5, 'm', 3)
    c.R(6, 6, 1, 5, 'm', 3); c.R(9, 6, 1, 5, 'm', 3)   # 세로 살 그림자
    c.R(7, 6, 1, 5, 'm', 5); c.R(10, 6, 1, 5, 'm', 5)
    # 앉는 판 뒤쪽으로 조금: 뒷판 아래 앉는 판 앞 두께 + 다리
    c.R(2, 11, 12, 1, 'm', 6)                # 앉는 판 가장자리(앞 모서리 밝게)
    c.R(2, 12, 12, 1, 'm', 1)
    c.R(2, 13, 12, 1, 'm', 3)
    c.R(2, 14, 2, 2, 'm', 4); c.R(12, 14, 2, 2, 'm', 3)
    c.R(2, 15, 2, 1, 'm', 2); c.R(12, 15, 2, 1, 'm', 1)
    outline(c, 1, bt=0)
    c.save('chair_wood_back', note='v34-A: 3/4 시점 — 등받이 윗면 3줄이 가장 밝고(윗면) 뒷판 앞면·앉는 판 앞 모서리·앞 두께 그늘·다리. 같은 mahog')
chair_wood(); chair_wood_back()
