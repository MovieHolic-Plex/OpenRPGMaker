from lib import *
M = {'m':'mahog','s':'sheet','v':'velv','t':'tarn'}
def bed_manor():
    c = Cv(16, 48, M); Y = 10
    def R(x,y,w,h,m,t): c.R(x,Y+y,w,h,m,t)
    # 머리판(앞면 = 남쪽을 향함): 위 두께 2줄(가장 밝음) + 앞면 6줄
    R(1,0,14,1,'m',1)
    R(0,1,16,2,'m',6)                  # 머리판 윗면(두께)
    R(0,3,16,6,'m',5)                  # 머리판 앞면(밝은 단)
    R(3,4,10,4,'m',4); R(3,4,10,1,'m',3); R(4,5,8,2,'m',3)  # 새긴 판 안쪽 (움푹)
    R(3,7,10,1,'m',6)                  # 판 아래 모서리 하이라이트
    R(0,3,2,6,'m',6); R(14,3,2,6,'m',4)  # 기둥
    R(0,3,1,6,'m',6)
    R(0,9,16,1,'m',1)                  # 머리판 밑 접힘 그늘
    # 옆 난간(위에서 보이는 윗면 띠) 양쪽 2폭
    for y in range(10,28):
        c.p(0,Y+y,'m',6); c.p(1,Y+y,'m',4)
        c.p(15,Y+y,'m',3); c.p(14,Y+y,'m',2)
    # 매트리스 시트 T
    R(2,10,12,10,'s',5)
    R(2,10,12,1,'s',3)                 # 머리판 그늘 밑
    R(2,10,1,10,'s',6)
    R(13,10,1,10,'s',4)
    # 베개
    R(3,11,10,4,'s',6); R(3,11,10,1,'s',4); R(3,14,10,1,'s',3); R(12,11,1,4,'s',4); R(3,11,1,4,'s',6)
    R(4,12,7,1,'s',5)
    # 시트 접은 줄
    R(2,20,12,1,'s',6)
    # 담요(벨벳) 윗면 + 격자
    R(2,21,12,13,'v',3)
    R(2,21,1,13,'v',5); R(13,21,1,13,'v',2)
    R(2,21,12,1,'v',5)
    for yy in (24,28,32):
        for xx in (5,8,11):
            c.p(xx,Y+yy,'v',5); c.p(xx,Y+yy+1,'v',1)
    R(2,33,12,1,'v',2)                 # 발판 밑 접힘(그늘)
    # 발판(앞면 아래): 윗 모서리 하이라이트 + 앞면 + 발
    R(0,28,2,0,'m',4)
    R(0,34,16,1,'m',6)
    R(0,35,16,1,'m',5)
    R(0,36,16,1,'m',1)
    R(0,37,16,1,'m',3)
    R(0,37,2,1,'m',4); R(14,37,2,1,'m',2)
    # 난간 바닥 끝
    for y in range(28,34):
        c.p(0,Y+y,'m',5); c.p(1,Y+y,'m',3); c.p(15,Y+y,'m',3); c.p(14,Y+y,'m',2)
    outline(c,1,bt=0)
    c.save('bed_manor', note='v34-A: 3/4 시점 — 머리판 위 두께(가장 밝음)+앞면, 매트리스 윗면(시트·베개·벨벳 담요)이 크게, 옆 난간 윗면 띠, 발판 앞 모서리 하이라이트+앞면. 같은 mahog/sheet/velv 램프')
bed_manor()
