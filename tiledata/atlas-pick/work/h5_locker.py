from h5_common import *
def body(c):
    # 윗판 2px
    c.hl(1, 1, 14, '6'); c.hl(1, 2, 14, '5'); c.hl(2, 0, 12, '4')
    # 몸통
    c.rect(1, 3, 14, 27, '4'); c.vl(1, 3, 27, '5'); c.vl(14, 3, 27, '2'); c.vl(0, 3, 27, '1') if False else None
    c.hl(1, 29, 14, '1'); c.hl(1, 16, 14, '2')       # 문 사이 이음
    c.hl(1, 15, 14, '3')
    # 발
    c.rect(2, 30, 3, 2, '1'); c.rect(11, 30, 3, 2, '1')
def lower(c):
    c.rect(3, 18, 10, 10, '3'); c.hl(3, 18, 10, '5'); c.vl(3, 18, 10, '4'); c.vl(12, 19, 9, '2'); c.hl(3, 27, 10, '1')
    for y in (20, 22, 24): c.hl(5, y, 6, '1'); c.hl(5, y + 1, 6, '4') if False else None
    c.px(11, 23, '5'); c.px(11, 24, '2')             # 손잡이
    c.vl(4, 19, 0, '1')
def upper_closed(c):
    c.rect(3, 4, 10, 10, '3'); c.hl(3, 4, 10, '5'); c.vl(3, 4, 10, '4'); c.vl(12, 5, 9, '2'); c.hl(3, 13, 10, '1')
    for y in (6, 8, 10): c.hl(5, y, 6, '1')
    c.px(11, 9, '5'); c.px(11, 10, '2')
def rustspots(c, pts, ch='c'):
    for (x, y) in pts: c.px(x, y, ch)

# ---- A : 윗문이 찌그러져 반쯤 열림, 안은 새까맣다
c = C(16, 32); body(c); lower(c)
c.rect(3, 4, 10, 10, '0')                        # 안(새까맘)
c.hl(3, 4, 10, '1'); c.vl(3, 4, 10, '1')
# 문짝은 오른쪽 경첩 → 왼쪽으로 열림? 여기선 왼쪽 경첩, 오른쪽이 떠서 바깥으로
c.vl(3, 4, 10, '2'); c.vl(4, 5, 8, '0') if False else None
# 열린 문짝(원근으로 좁고 비스듬)
for y in range(4, 14):
    x0 = 9 + (y - 4) // 3; c.hl(x0, y, 4 - (y - 4) // 5, '3')
    c.px(x0, y, '5')
c.px(12, 5, '1'); c.px(11, 8, '1'); c.px(11, 11, '1')            # 통풍 줄
c.px(13, 13, '2')
rustspots(c, [(4, 20), (5, 26), (10, 21), (11, 27), (3, 16), (12, 15)], 'c')
rustspots(c, [(10, 22), (6, 27)], 'd')
c.px(6, 21, '6') if False else None
for j in range(4): c.px(6 + j, 22 + j // 2, '5') if False else None
c.vl(8, 19, 4, '6') if False else None
save('broken_locker', 'h5-A', c, L, '쇠 사물함: 윗문이 오른쪽부터 떠서 비스듬히 반쯤 열리고 안이 새까맘, 아랫문은 닫혀 통풍 줄 셋과 손잡이, 녹 점')

# ---- B : 문틈에서 붉은 빛? -> 안쪽에서 새어 나온 창백한 빛 아니라 열린 어둠 + 밝은 왼쪽 위 테두리와 바닥 그림자
c = C(16, 32); body(c); lower(c)
c.rect(3, 4, 10, 10, '0'); c.hl(3, 4, 10, '1'); c.vl(3, 4, 10, '1')
for y in range(4, 14):
    x0 = 9 + (y - 4) // 3; c.hl(x0, y, 4 - (y - 4) // 5, '3'); c.px(x0, y, '6')
c.px(12, 5, '1'); c.px(11, 8, '1'); c.px(11, 11, '1')
c.hl(1, 1, 14, '6'); c.hl(2, 0, 12, '5'); c.vl(1, 3, 12, '6')
c.vl(1, 17, 12, '5'); c.hl(3, 18, 10, '6')
rustspots(c, [(4, 22), (10, 26)], 'c')
c.hl(1, 31, 16, '~') if False else None
for x in range(2, 16): c.px(x, 31, '~')
for x in range(4, 16): c.px(x, 30, '-') if c.g[30][x] == '.' else None
c.px(0, 31, '~') if False else None
save('broken_locker', 'h5-B', c, L, '윗판·왼쪽 모서리가 밝게 치켜 빛나고 아랫문 아래는 눌려 어둡다, 발치 오른쪽으로 반투명 그림자')

# ---- C : 실루엣 — 기울어 쓰러지려는 사물함, 열린 안에서 손 하나가 문틀을 잡음
c = C(16, 32); body(c); lower(c)
c.rect(3, 4, 10, 10, '0'); c.hl(3, 4, 10, '1'); c.vl(3, 4, 10, '1')
# 문은 통째로 떨어져 아랫칸 앞에 비스듬히 기대 서 있는 대신, 문틀 옆에 걸림
for y in range(4, 14): c.px(12, y, '2'); c.px(11, y, '3') if y < 10 else None
# 창백한 손(안에서 문틀을 쥠) — 손가락 넷
for i, (x, y) in enumerate(((5, 11), (7, 10), (9, 10), (11, 11))):
    c.px(x, y, 'e') if False else None
for (x, y, ch) in ((4, 9, 'N'), (5, 9, 'O'), (5, 10, 'N'), (4, 11, 'M'),
                   (6, 8, 'O'), (6, 9, 'P'), (6, 10, 'O'), (7, 8, 'N'), (7, 9, 'O'),
                   (8, 8, 'O'), (8, 9, 'P'), (9, 9, 'O'), (9, 10, 'N'),
                   (5, 11, 'N'), (6, 11, 'M'), (7, 10, 'N'), (7, 11, 'M'), (8, 10, 'O'), (8, 11, 'N')):
    c.px(x, y, ch)
c.hl(3, 12, 6, '0')
rustspots(c, [(4, 21), (9, 25), (11, 20)], 'c')
# 약간 기울임: 위쪽이 오른쪽으로 쏠림
shear(c, lambda y: 1 if y < 10 else (0 if y < 22 else 0))
save('broken_locker', 'h5-C', c, L, '윗칸이 열려 어둠 속에서 창백한 손 하나가 문틀을 붙잡고, 윗부분이 오른쪽으로 살짝 기울어 있다')
