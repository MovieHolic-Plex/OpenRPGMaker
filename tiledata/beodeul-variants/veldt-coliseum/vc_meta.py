def coliseum_walk():
    """외피 26x32칸 통행: '#' 막힘 · '.' 걷기(경기장 모래·정문 문길, 외피 밖 빈 모서리) · 'G' 북쪽 쇠창살 문(지하로 가는 이벤트)."""
    im, _ = VC.coliseum(); A = np.array(im)[:, :, 3]
    rows = []
    cy_c = int(VC.CY // 16)
    for cy in range(VC.H // 16):
        r_ = ''
        for cx in range(VC.W // 16):
            gx, gy = cx * 16 + 8, cy * 16 + 8
            r, th = VC.rho_th(gx, gy)
            tun = cx in (15, 16) and cy >= cy_c and r <= 1.0
            if tun: ch = '.'
            elif A[gy, gx] > 0 or r <= 1.0 and not r < VC.RHO_A - 0.02: ch = '#'
            else: ch = '.'
            r_ += ch
        rows.append(r_)
    g = int((VC.CY - VC.RY * VC.RHO_A) // 16)
    rows[g] = rows[g][:15] + 'GG' + rows[g][17:]
    rows[g + 1] = rows[g + 1][:15] + '..' + rows[g + 1][17:]
    return rows

def _p(kind, ko, desc, rules, brows, **k):
    d = {'kind': kind, 'ko': ko, 'desc': desc, 'rules': rules, 'brows': brows}; d.update(k); return d

