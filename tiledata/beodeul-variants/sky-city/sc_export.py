def export(out):
    pr = B.Parts(out)
    for (name, fn, kind, role, brows, ko, desc, rules) in OBJ:
        pr.add(name, fn(), kind, ko, desc, rules, brows=brows, role=role)
    for (name, fn, ko, desc, rules, kind) in FLOORS:
        pr.add(name, fn(), kind, ko, desc, rules, role='water' if kind == 'liquid' else 'terrain', pad=False)
        if kind == 'liquid': pr.meta[name]['passable'] = False
    for (name, fn, ko, desc, rules) in PATCHES:
        pr.add(name, fn(), 'floor', ko, desc, rules, role='terrain', pad=False)
    for (name, fn, ko, desc, rules) in FACES:
        im = fn(); pr.add(name, im, 'wall', ko, desc, rules, brows=im.height // 16, role='wall', pad=False)
    for (name, fn, layer, role, ko, desc, rules) in AUTOS:
        pr.add(name, fn(), 'autotile', ko, desc, rules, layer=layer, role=role, pad=False)
        if name in ('autotile-cloudbank', 'autotile-cloudgap', 'autotile-cloudfringe'): pr.meta[name]['passable'] = False
    return pr.finish('하늘 도시·부유섬 (sky-city)'), pr
