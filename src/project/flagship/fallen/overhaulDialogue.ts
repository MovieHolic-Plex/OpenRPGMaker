/**
 * 2차: 누락된 번역체·문어체 어미를 부드럽게 다듬는 보조 규칙.
 * 단말(terminal)·석판(sign)·옛 규약 인용문은 건드리지 않는다.
 */
const SOFT_PATTERNS: readonly (readonly [RegExp, string])[] = [
  [/([가-힣]+)로군([.!?])/g, "$1이네$2"],
  [/([가-힣]+)였군([.!?])/g, "$1였네$2"],
  [/([가-힣]+)었군([.!?])/g, "$1었네$2"],
  [/([가-힣]+)았군([.!?])/g, "$1았네$2"],
  [/([가-힣]+)겠군([.!?])/g, "$1겠네$2"],
  [/([가-힣]+)는군([.!?])/g, "$1네$2"],
  [/([가-힣]+)더군([.!?])/g, "$1더라$2"],
  [/([가-힣]+)이구먼([.!?])/g, "$1이네$2"],
  [/([가-힣]+)구먼([.!?])/g, "$1네$2"],
  [/([가-힣]+)일세([.!?])/g, "$1야$2"],
  [/무언가가 그것을/g, "누군가 그걸"],
  [/집에 돌아가고 싶을 뿐이에요/g, "그냥 집에 돌아가고 싶어요"],
  [/등은 맡겨라/g, "뒤는 맡겨"],
];

function polishBody(body: string, style?: string, speaker?: string): string {
  // 단말·비문·석판·고대 기록은 원문 톤을 유지한다.
  if (style === "terminal" || speaker === "단말") return body;
  if (EXACT_REWRITES[body]) return EXACT_REWRITES[body]!;

  // 줄바꿈 조합 중 부분 일치하는 번역체 문구가 있으면 문장 단위로 교체한다.
  let next = body;
  for (const [from, to] of Object.entries(EXACT_REWRITES)) {
    if (next.includes(from)) next = next.split(from).join(to);
  }
  if (next === body) {
    for (const [re, rep] of SOFT_PATTERNS) next = next.replace(re, rep);
  }
  return next;
}

function walkCommands(commands: Command[] | undefined, stats: { touched: number }): void {
  if (!Array.isArray(commands)) return;
  for (const cmd of commands) {
    if (!cmd || typeof cmd !== "object") continue;
    const rec = cmd as unknown as Rec;
    if (rec.kind === "text" && typeof rec.body === "string") {
      const updated = polishBody(rec.body, typeof rec.style === "string" ? rec.style : undefined, typeof rec.speaker === "string" ? rec.speaker : undefined);
      if (updated !== rec.body) {
        rec.body = updated;
        stats.touched += 1;
      }
    }
    for (const key of ["then", "else", "cancelBranch", "commands", "victoryBranch", "defeatBranch", "escapeBranch"]) {
      if (Array.isArray(rec[key])) walkCommands(rec[key] as Command[], stats);
    }
    if (Array.isArray(rec.options)) {
      for (const opt of rec.options as { branch?: Command[] }[]) {
        if (Array.isArray(opt.branch)) walkCommands(opt.branch, stats);
      }
    }
  }
}

export function applyFallenDialogueOverhaul(project: Project): { touched: number } {
  const stats = { touched: 0 };
  for (const map of Object.values(project.maps)) {
    for (const event of map.events) {
      walkCommands(event.commands as Command[] | undefined, stats);
      for (const page of event.pages ?? []) walkCommands(page.commands as Command[] | undefined, stats);
    }
  }
  for (const common of project.commonEvents ?? []) walkCommands(common.commands as Command[] | undefined, stats);
  for (const troop of project.database.troops ?? []) {
    for (const page of troop.battleEventPages ?? []) walkCommands(page.commands as Command[] | undefined, stats);
  }
  for (const ending of project.endings ?? []) {
    const ep = (ending as unknown as { epilogue?: { kind?: string; text?: string; speaker?: string }[] }).epilogue;
    if (!Array.isArray(ep)) continue;
    for (const beat of ep) {
      if (typeof beat.text === "string") {
        const updated = polishBody(beat.text, undefined, beat.speaker);
        if (updated !== beat.text) {
          beat.text = updated;
          stats.touched += 1;
        }
      }
    }
  }
  return stats;
}
