const descriptions = new Map<number, string>();
function put(tile: number, description: string): void {
  if (descriptions.has(tile)) throw new Error(`Duplicate World description: ${tile}`);
  descriptions.set(tile, description);
}
function arrangement(name: string, rows: readonly (readonly number[])[], usage: string): void {
  const layout = rows.map(row => `[${row.join(",")}]`).join(" / ");
  rows.forEach((row, y) => row.forEach((tile, x) => {
    const position = `${y + 1}행 ${x + 1}열`;
    const neighbors = [x > 0 ? `왼쪽 ${row[x - 1]}` : "", x + 1 < row.length ? `오른쪽 ${row[x + 1]}` : "",
      y > 0 ? `위 ${rows[y - 1][x]}` : "", y + 1 < rows.length ? `아래 ${rows[y + 1][x]}` : ""].filter(Boolean);
    put(tile, `World ${name}의 ${position} 조각. ${neighbors.join(" · ")}. 완성 배열 ${layout}. ${usage}`);
  }));
}

