function expandRow(row: string): string {
  if (!row.startsWith("=")) return row;
  let out = "";
  for (const tok of row.slice(1).trim().split(/\s+/)) {
    if (!tok) continue;
    const n = tok.length > 1 ? Number.parseInt(tok.slice(0, -1), 10) : 1;
    const ch = tok[tok.length - 1]!;
    out += ch.repeat(n);
  }
  return out;
}

function buildPalette(vk: string): Record<string, readonly [number, number, number, number]> {
  const pal: Record<string, readonly [number, number, number, number]> = { ...COMMON_HEX };
  const ramp = RAMPS[vk];
  if (ramp) {
    const [body, sec] = ramp;
    body.forEach((c, i) => { pal[String(i + 1)] = hx(c); });
    ["v", "w", "x", "y", "z"].forEach((ch, i) => { if (sec[i]) pal[ch] = hx(sec[i]!); });
  }
  if (vk === "taxi") {
    ["k", "h", "j", "i", "I"].forEach((ch, i) => { if (TAXI_GLASS[i]) pal[ch] = hx(TAXI_GLASS[i]!); });
  }
  return pal;
}

export function renderHandNsFrame(
  kitId: string,
  dir: "up" | "down",
  targetW: number,
  targetH: number,
  phase: number,
  brake: boolean,
): ImageData | null {
  const spec = HAND_NS_GRIDS[`${kitId}:${dir}`];
  if (!spec) return null;
  const pal = buildPalette(spec.vk);
  const bounce = !brake && (phase === 1 || phase === 3) ? 1 : 0;
  const sirenSwap = spec.vk === "police" && (phase & 1) === 1;
  const ox = Math.floor((targetW - spec.w) / 2);
  const oy = targetH - spec.h;
  const out = new ImageData(targetW, targetH);

  for (let y = 0; y < spec.rows.length; y += 1) {
    const row = expandRow(spec.rows[y]!);
    const dy = y < spec.planted ? y + bounce : y;
    const ty = oy + dy;
    if (ty < 0 || ty >= targetH) continue;
    for (let x = 0; x < row.length; x += 1) {
      let ch = row[x]!;
      if (ch === ".") continue;
      if (sirenSwap) {
        if (ch === "P") ch = "Q";
        else if (ch === "Q") ch = "P";
        else if (ch === "p") ch = "q";
        else if (ch === "q") ch = "p";
      }
      let rgba = pal[ch];
      if (!rgba) continue;
      if (brake && (ch === "r" || ch === "R" || ch === "<" || ch === ">")) {
        rgba = [255, 50, 65, 255];
      }
      const tx = ox + x;
      if (tx < 0 || tx >= targetW) continue;
      const idx = (ty * targetW + tx) * 4;
      out.data[idx] = rgba[0];
      out.data[idx + 1] = rgba[1];
      out.data[idx + 2] = rgba[2];
      out.data[idx + 3] = rgba[3];
    }
  }
  return out;
}
