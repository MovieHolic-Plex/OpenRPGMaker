// benchmark/interior/hash.ts
// Deterministic hashing primitives for the interior benchmark.
//
// Pure TypeScript on purpose: `src/` is bundled for the browser, so importing
// node:crypto here would drag a Node builtin into the editor bundle. A
// self-contained sha256 keeps the same digest in Node, the browser and vitest,
// which is exactly the property the reproducibility spine depends on.

