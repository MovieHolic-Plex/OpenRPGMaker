/** program 을 seed 로 다시 지을 때의 변주 — 같은 「백화점」·「레스토랑」이 매번 똑같은 맵으로 나오지 않게(2026-10-18 사용자 지적).
 *  seed 1 은 견본 그대로. seed k(≥2)는 (k-1)%2 로 동↔서 구역 배치를 뒤집고, (k-1)%(palettes+1) 로 바닥·벽면 묶음을 바꾸고,
 *  큰 방(가로 10칸↑·세로 8칸↑)을 0~3칸·0~1칸 넓혀 가구 간격을 바꾼다. palettes 는 방 종류 → [바닥, 벽면].
 *  entrance·above·left 는 그 program 만의 출구 방·위아래 쌍·왼오른 쌍(layout.ts 기본 표보다 무겁게 지킨다 — 전동차 두 칸과 운전실이 한 줄로).
 *  hubs 는 지나다니는 방 종류(layout.ts HUB 표에 더한다), fixed 는 변주 seed 에도 넓히지 않는 방 종류(개찰구 줄·전동차처럼 벽에서 벽까지 꽉 찬 방). */
export interface ModernProgramVariation {
  readonly entrance?: string;
  readonly above?: readonly (readonly [string, string])[];
  readonly left?: readonly (readonly [string, string])[];
  readonly hubs?: readonly string[];
  readonly fixed?: readonly string[];
  readonly palettes: readonly Readonly<Record<string, readonly [string, string]>>[];
  /** 줄 배치(북→남, 줄마다 서→동 방 종류) - 주면 seed 마다 이 줄 배치로 선다(규모 규격 크기, venueScale.ts). 다른 배치는 layout.variant.
   *  `void:N` 은 방 대신 N칸 바깥(건물 밖)을 비워 ㄱ·ㄷ·ㅗ자 평면을 만든다. */
  readonly rows?: readonly (readonly string[])[];
  /** 참이면 줄 안의 방이 줄 높이로 늘지 않고 견본 높이(위쪽 맞춤)를 지킨다 - 짧은 방 아래는 건물 밖으로 들어간 계단형 외곽이 된다. */
  readonly ragged?: boolean;
  /** 방 종류 → 줄 안 높이. 줄 끝 방의 높이를 줄여 그 아래를 건물 밖(ㄱ·ㄴ자 귀퉁이)으로 만든다 - 높이는 견본보다 크지 않다. */
  readonly trim?: Readonly<Record<string, number>>;
  /** 칸막이 없이 넓게 트는 방 쌍(로비↔대기실, 매장↔진열 알코브 등). */
  readonly open?: readonly (readonly [string, string])[];
  /** 붙어 있어도 문을 내지 않는 방 쌍(남탕↔여탕, 로비↔목욕 홀처럼 지나가면 안 되는 이웃). 종류 또는 id. */
  readonly sealed?: readonly (readonly [string, string])[];
  /** 바닥·벽 재질을 시드 화풍 바꿈(remap)·대비 맞춤(contrastPair) 없이 견본 그대로 두는 방 종류 — 옥상 콘크리트처럼 재질이 곧 장소인 곳(2026-10-25: 옥상 데크가 병원 연녹 바닥이 됐다). */
  readonly keepMaterials?: readonly string[];
  /** 줄 사이에 깔린 복도(arch-hall) - rows 에 복도 줄(`arch-hall`)이 있을 때 그 복도의 꾸밈 묶음(archHall.ts). */
  readonly hall?: "school" | "hospital" | "office" | "hotel" | "public";
  /** 참이면 남쪽 외벽 출구 틈을 열지 않는다(2층·3층처럼 계단·엘리베이터로만 오가는 상층). */
  readonly noExteriorExit?: boolean;
}

