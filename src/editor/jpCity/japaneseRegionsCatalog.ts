/** 장면 문법 한 줄. 좌표 x·y 는 맵 폭·높이 비율(0~1), size·step·gap 은 칸. 바닥 재료는 jp_city 타일 그룹 이름(fill_region material). */
export type JpRegionOp =
  /** 사각 영역 바닥. clear:true 면 그 칸에 소품을 놓지 않는다(물·논·광장 중심·운동장). zone 은 표면 구획 힌트. */
  | { readonly op: "area"; readonly mat: string; readonly box: readonly [number, number, number, number]; readonly clear?: boolean; readonly zone?: JpZoneHint }
  /** 맵을 가로지르는 길·물·선로 띠. 늘 비워 둔다(onPath 소품만 위에 선다). span 은 띠 방향 범위 비율. */
  | { readonly op: "band"; readonly mat: string; readonly dir: "h" | "v"; readonly at: number; readonly size: number; readonly span?: readonly [number, number];
      /** 세로 띠(dir v)만: 최대 ±amp(1|2) 칸 S 자로 굽이친다 — 한 번에 1칸, 3~4줄 붙든 뒤 꺾는다(period 는 기록용, 무늬 주기 26줄 고정). keep 은 곧게 둘 세로 범위 비율 — 다리·폭포 자리. 위상은 seed. */
      readonly meander?: { readonly amp: number; readonly period: number; readonly keep?: readonly (readonly [number, number])[] } }
  /** 굴절·연결 거리/산길/데크(A2) - [x,y] 꼭짓점 폴리라인을 따라 폭 size 칸으로 바닥을 깐다. */
  | { readonly op: "street"; readonly mat: string; readonly points: readonly (readonly [number, number])[]; readonly size: number; readonly deadEnd?: boolean }
  /** 지형 단차와 석축(A10) - y 위치에 rg-ishigaki 옹벽을 세우고 stairAt 위치마다 돌계단을 걸친다(계단 위아래로 길을 보장). */
  | { readonly op: "terrace"; readonly y: number; readonly span?: readonly [number, number]; readonly mat?: string; readonly stairAt?: readonly number[]; readonly stairKit?: string }
  /** 랜드마크 하나 - at 은 키트 가운데(foot:true 면 x 가운데·y 는 맨 아랫줄). */
  | { readonly op: "put"; readonly kit: string; readonly at: readonly [number, number]; readonly foot?: boolean; readonly onPath?: boolean }
  /** 도심 밀집 건물·노점 줄 - 아랫줄(발)을 foot 에 맞춰 왼쪽부터 kits 를 중복 없이 세운다. */
  | { readonly op: "row"; readonly kits: readonly string[]; readonly foot: number; readonly span: readonly [number, number]; readonly gap?: number }
  /** 주거·농어촌·온천 택지(lots) - 집마다 여유 대지(집 폭 + 2~3칸), 담장/생울타리, 문 앞 트임·진입로(apron), 마당 소품을 함께 짓는다. */
  | { readonly op: "lots"; readonly kits: readonly string[]; readonly foot: number; readonly span: readonly [number, number]; readonly fence?: "block" | "hedge" | "tsuiji" | "bamboo" | "none"; readonly yard?: "lawn" | "gravel" | "pave" }
  /** 같은 키트를 선 위에 step 칸마다(가로등·도리이 터널·지장 행렬·방파제 블록). at 은 선의 가로(h)·세로(v) 위치 비율 = 키트 가운데. */
  | { readonly op: "line"; readonly kit: string; readonly dir: "h" | "v"; readonly at: number; readonly span: readonly [number, number]; readonly step: number; readonly onPath?: boolean }
  /** 상자 안에 n 개 흩뿌림(나무·바위·벤치) - 푸아송 최소 간격으로 겹치지 않게 놓는다. */
  | { readonly op: "scatter"; readonly kits: readonly string[]; readonly n: number; readonly box: readonly [number, number, number, number]; readonly onPath?: boolean };

export type JpRegionEngine =
  | { readonly kind: "scene"; readonly ground: string; readonly ops: readonly JpRegionOp[]; readonly junction?: boolean }
  | { readonly kind: "street"; readonly style: "shopping" | "residential" | "shitamachi" | "shotengai" };

export interface JpRegion {
  readonly no: number;
  readonly id: string;
  readonly category: JpRegionCategory;
  readonly ko: string;
  readonly ja: string;
  readonly en: string;
  /** 무엇을 보여 주는 장면인가 - 조수가 사용자에게 설명할 때 쓴다. */
  readonly pitch: string;
  /** 요청 문장에서 이 지역을 고르는 낱말. */
  readonly keywords: readonly string[];
  /** 팔레트 계약(paletteContract.ts)의 주조 재료 - 화면 넓이 순. */
  readonly palette: readonly string[];
  readonly harmony: readonly JpPaletteFamilyId[];
  /** 권장 계절·시간대(팔레트 JP_SEASON_RULES·JP_TIME_OF_DAY_RULES 의 id). */
  readonly season: "spring" | "summer" | "autumn" | "winter";
  readonly timeOfDay: "dawn" | "day" | "dusk" | "night";
  /** 권장 맵 크기(칸). 40×28 이상이면 비율대로 펴진다. */
  readonly size: readonly [number, number];
  /** 다른 번들 칩셋으로 짓는 변형(jp_city 밖). */
  readonly alsoWith?: string;
  /** 아키타입 기본 허용표 외에 이 지역에서 추가로 허용할 키트 ID 목록(A9). */
  readonly extraKits?: readonly string[];
  /** 이 지역에서 명시적으로 금지할 키트 ID 목록(A9). */
  readonly forbidKits?: readonly string[];
  readonly engine: JpRegionEngine;
}

