// Preset-specific questions approved in the new-project interview report.
import type { GamePresetId, GameDesignAnswers, GameBriefSlot } from "@/project/gameDesignBrief";

export interface ProjectInterviewQuestion { slot: GameBriefSlot; label: string; title: string; choices: readonly string[]; hint: string }

/** The slot order is shared; the wording and consequential fourth question belong to each preset. */
export function projectInterviewQuestions(presetId: GamePresetId, answers: GameDesignAnswers): readonly ProjectInterviewQuestion[] {
  const questions = [...PROJECT_INTERVIEW_QUESTIONS[presetId]];
  const experience = answers.experience?.text;
  const followup = (label: string, title: string, choices: readonly string[], hint: string): void => {
    questions[3] = { slot: "detail", label, title, choices, hint };
  };
  if (presetId === "monster-collect") {
    if (experience === "공포") followup("공포의 원인", "수집 여정의 공포는 어디서 생기나요?", ["포획할수록 마을이 이상해짐", "파트너가 낯설게 변함", "도감 기록과 현실이 다름", "괴물이 된 옛 동료의 흔적"], "공포를 선택했으므로, 수집 행동과 공포를 연결해 봅니다. 포획·육성 시스템은 유지합니다.");
    else if (experience === "미스터리") followup("수수께끼", "무엇을 조사하며 수집하게 되나요?", ["사라진 종의 흔적", "잘못된 도감 기록", "특정 마을의 실종 사건", "파트너의 출처"], "수집과 조사를 하나의 흐름으로 연결합니다.");
    else if (experience === "따뜻한 교감") followup("관계의 변화", "몬스터와 가까워지는 계기는 무엇인가요?", ["구조하고 돌보기", "함께 여행하며 어려움 극복", "서식지를 회복하기", "신뢰를 얻은 뒤 동행 선택"], "교감을 선택했으므로 관계가 달라지는 사건을 정합니다.");
    else if (experience && !questions[0]!.choices.includes(experience)) followup("분위기와 사건", "말씀하신 분위기는 수집 과정의 어떤 사건으로 드러나나요?", ["처음 발견하는 종의 비밀", "포획 뒤에 생기는 변화", "파트너와 겪는 사건", "도감 기록과 연결된 마을의 사연"], "직접 적은 분위기를 유지하면서 수집 행동과 사건을 연결합니다. 원하는 사건을 직접 적어도 좋아요.");
  } else if (presetId === "horror-gallery") {
    if (experience === "동행자를 믿을 수 없는 불안") followup("불신의 계기", "동료를 의심하게 만드는 일은 무엇인가요?", ["그림과 동료의 설명이 다름", "위기 때마다 동료가 사라짐", "다른 생존자가 상반된 증언", "내 기억과 동료의 기억이 다름"], "동행자에 대한 불안을 선택했으므로 정보와 신뢰의 갈등을 정합니다.");
    else if (experience === "쫓기고 숨는 긴장") followup("위협의 규칙", "추격은 무엇을 계기로 시작하나요?", ["금지된 작품을 만지면 시작", "불빛이 꺼지면 시작", "단서를 가져가면 시작", "같은 방에 오래 머물면 시작"], "추격 공포를 선택했으므로 위협의 시작 조건을 정합니다.");
    else if (experience === "조금 무섭지만 따뜻한 이야기") followup("안전과 온기", "무서운 순간 사이에 무엇이 안심을 주나요?", ["함께 기다려 주는 동료", "다시 돌아갈 수 있는 안전한 방", "전시물에 남은 따뜻한 기억", "구한 존재의 도움"], "긴장 뒤에 회복할 순간을 정합니다.");
    else if (experience && !questions[0]!.choices.includes(experience)) followup("공포와 사건", "말씀하신 무서움은 어떤 사건에서 시작하나요?", ["그림을 조사한 뒤", "다시 찾은 방에서", "동료와 대화하다가", "탈출을 시도할 때"], "직접 적은 공포의 방향을 유지하면서 사건의 계기를 정합니다. 원하는 계기를 직접 적어도 좋아요.");
  }
  return questions;
}

