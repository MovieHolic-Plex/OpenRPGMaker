def strip3(make):
    """줄 공통 기물 장면: 세 줄(A1 B1 C1) 방을 옆으로. make(line) → 방 Cv."""
    rooms = [make(ln) for ln in LINES]
    out = Cv(sum(r.w for r in rooms) + 8 * (len(rooms) - 1), max(r.h for r in rooms))
    x = 0
    for r in rooms:
        out.paste(r, x, 0)
        x += r.w + 8
    return out


def common_scene(placer, grid_rows=ROOM, actor_at=(5, 4)):
    def make(line):
        cv = room(grid_rows, line)
        placer(cv)
        if actor_at:
            put_actor(cv, *actor_at)
        return cv
    return strip3(make)


