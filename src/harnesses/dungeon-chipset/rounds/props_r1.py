MAGIC_HALF = [r + r[::-1] for r in MAGIC_Q]
MAGIC_ROWS = MAGIC_HALF + MAGIC_HALF[::-1]
MAGIC_PULSE = str.maketrans({'O': 'Q', 'N': 'O', 'P': 'R', 'Q': 'R'})   # 장면 2: 한 단씩 밝아짐(맥동)


def magic(k):
    return g(MAGIC_ROWS if k == 0 else [r.translate(MAGIC_PULSE) for r in MAGIC_ROWS])


