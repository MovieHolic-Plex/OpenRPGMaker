def room(g, line, k=0):
    """g: '#' 바위 · '.' 흙바닥 · 's' 돌바닥 · 'w' 물. 그 줄 cave-r1 1번 천장·앞면·흙바닥·돌바닥 + edges-r1 물 1번."""
    wat = ER.water(line, 1)[k % 4] if any('w' in r for r in g) else None
    cv = dot.render_cave(g, CR.part(line, 1, 'ceil'), CR.part(line, 1, 'face'), CR.part(line, 1, 'floor'), water=wat)
    if any('s' in r for r in g):
        st = CR.part(line, 1, 'stone')
        for y, row in enumerate(g):
            for x, ch in enumerate(row):
                if ch == 's':
                    cv.a[y * T:(y + 1) * T, x * T:(x + 1) * T] = st.tile_at(dot.mask_at(g, x, y, lambda c, X, Y: c == 's'), x, y).a
    return cv


def actor():
    return dot.Cv.of(dot.actor1_frame(1, 0, 0))


def put_actor(cv, cx, cy):
    cv.paste(actor(), cx * T - 4, cy * T - 14)


