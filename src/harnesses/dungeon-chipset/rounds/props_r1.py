def hcat(*cvs, gap=0):
    out = Cv(sum(c.w for c in cvs) + gap * (len(cvs) - 1), max(c.h for c in cvs))
    x = 0
    for c in cvs:
        out.paste(c, x, out.h - c.h)
        x += c.w + gap
    return out


def mirror_h(rows):
    return [r[::-1] for r in rows]


