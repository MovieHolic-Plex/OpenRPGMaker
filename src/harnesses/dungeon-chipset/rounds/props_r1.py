def layer(base_rows, *over, leg=None, w=None, h=None):
    """바탕 행 위에 덧칠 행들을 얹는다('.' 은 바탕 유지). 덧칠은 손으로 적은 행 묶음 (rows, x, y)."""
    cv = grid(base_rows, leg or LEG, w, h)
