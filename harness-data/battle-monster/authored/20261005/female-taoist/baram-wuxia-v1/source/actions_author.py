from pathlib import Path

ROOT = Path(__file__).parent

def save(name, spec):
    canvas = [list('.' * 64) for _ in range(64)]
    for y, runs in spec.items():
        for x, literal in runs:
            canvas[y][x:x + len(literal)] = literal
    (ROOT / 'actions' / (name + '.pxgrid')).write_text(
        '\n'.join(''.join(row) for row in canvas) + '\n')

(ROOT / 'actions').mkdir(exist_ok=True)

