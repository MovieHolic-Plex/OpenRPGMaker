def rows(text):
    canvas=[list('.'*64) for _ in range(64)]
    for line in text.strip().splitlines():
        y, rest=line.split(':',1)
        for run in rest.split(';'):
            x, pixels=run.strip().split()
            x=int(x); y=int(y)
            canvas[y][x:x+len(pixels)]=list(pixels)
    return [''.join(r) for r in canvas]
def save(name,text,action=False):
    grid=rows(text)
    assert len(grid)==64 and all(len(r)==64 for r in grid)
    assert all(c=='.' or c in PALETTE for r in grid for c in r)
    assert set(grid[0]+grid[61]+grid[62]+grid[63])=={'.'}
    assert all(r[0]==r[63]=='.' for r in grid)
    folder=ROOT/('actions' if action else 'poses')
    (folder/(name+'.pxgrid')).write_text('\n'.join(grid)+'\n')
    return grid

def decode(grid):
    im=Image.new('RGBA',(64,64))
    px=im.load()
    for y,row in enumerate(grid):
        for x,c in enumerate(row):
            if c!='.': px[x,y]=tuple(bytes.fromhex(PALETTE[c][1:]))+(255,)
    return im

