from pathlib import Path
import json
from PIL import Image, ImageDraw
ROOT = Path(__file__).resolve().parents[1]
PALETTE = json.loads((ROOT/'palette.json').read_text())

def author(name, category, literal_runs):
    rows = [list('.'*64) for _ in range(64)]
    for line in literal_runs.strip().splitlines():
        y, x, pixels = line.split()
        y, x = int(y), int(x)
        if not (1 <= y <= 60 and 1 <= x and x+len(pixels) <= 63):
            raise ValueError((name, line))
        for c in pixels:
            if c != '.' and c not in PALETTE: raise ValueError(c)
        rows[y][x:x+len(pixels)] = list(pixels)
    text = '\n'.join(''.join(row) for row in rows)+'\n'
    (ROOT/category/f'{name}.pxgrid').write_text(text)

def decode(path):
    rows=path.read_text().splitlines()
    if len(rows)!=64 or any(len(r)!=64 for r in rows): raise ValueError(path)
    im=Image.new('RGBA',(64,64))
    for y,row in enumerate(rows):
        for x,c in enumerate(row):
            if c!='.':
                rgb=PALETTE[c]
                im.putpixel((x,y),tuple(bytes.fromhex(rgb[1:]))+(255,))
    return im

def inspect():
    paths=list((ROOT/'poses').glob('*.pxgrid'))+list((ROOT/'actions').glob('*.pxgrid'))
    if (ROOT/'poses/idle_a.pxgrid').exists():
        idle=decode(ROOT/'poses/idle_a.pxgrid')
        idle.save(ROOT/'progress/idle.png')
        idle.resize((512,512),Image.Resampling.NEAREST).save(ROOT/'progress/idle-8x.png')
        idle.crop((23,7,44,36)).resize((168,232),Image.Resampling.NEAREST).save(ROOT/'progress/face.png')
    order=['idle_a','idle_b','idle_c','windup','move','attack','recover','hit','dead','skill_a','skill_b','skill_c','poison_a','poison_b','stun_a','stun_b','sleep_a','sleep_b']
    paths=sorted(paths,key=lambda p:order.index(p.stem))
    sheet=Image.new('RGB',(840,((len(paths)+2)//3)*240),'#d9d9d2')
    d=ImageDraw.Draw(sheet)
    native=Image.new('RGB',(3*80,((len(paths)+2)//3)*84),'#d9d9d2')
    nd=ImageDraw.Draw(native)
    for j,p in enumerate(paths):
        im=decode(p)
        xx=(j%3)*280; yy=(j//3)*240
        d.text((xx+10,yy+6),p.stem,fill='#292b38')
        sheet.paste(im.resize((192,192),Image.Resampling.NEAREST),(xx+10,yy+30),im.resize((192,192),Image.Resampling.NEAREST))
        nx=(j%3)*80; ny=(j//3)*84
        nd.text((nx,ny),p.stem,fill='#292b38')
        native.paste(im,(nx,ny+18),im)
    sheet.save(ROOT/'progress/suite-3x.png')
    native.save(ROOT/'progress/suite-native.png')

