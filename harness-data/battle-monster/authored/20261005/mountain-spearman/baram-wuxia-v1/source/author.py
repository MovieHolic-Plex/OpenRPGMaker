def frame(name, rows, patches=()):
    grid=[list('.'*64) for _ in range(64)]
    for y,x,ink in rows+list(patches):
        assert 0<=y<64 and 0<=x and x+len(ink)<=64,(name,y,x,ink)
        for dx,ch in enumerate(ink): grid[y][x+dx]=ch
    result=[''.join(row) for row in grid]
    assert all(len(row)==64 for row in result)
    assert set(''.join(result))<=set(PAL)|{'.'}
    assert all(ch=='.' for ch in result[0]+result[61]+result[62]+result[63])
    assert all(row[0]==row[63]=='.' for row in result)
    folder='actions' if name in ['skill_a','skill_b','skill_c','poison_a','poison_b','stun_a','stun_b','sleep_a','sleep_b'] else 'poses'
    (ROOT/folder/f'{name}.pxgrid').write_text('\n'.join(result)+'\n')
    return result
