"""Chosen pixel runs for six independently drawn status bodies.

Only writes the literal runs below onto a blank 64x64 canvas.
No body construction, transforms, interpolation, or automatic shading.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent

def write_frame(name, runs):
    rows = [list('.' * 64) for _ in range(64)]
    for line in runs.strip().splitlines():
        x, y, pixels = line.split()
        x, y = int(x), int(y)
        rows[y][x:x + len(pixels)] = list(pixels)
    (ROOT / 'actions' / (name + '.pxgrid')).write_text(
        '\n'.join(''.join(row) for row in rows) + '\n')


