from pathlib import Path
import json
from PIL import Image, ImageDraw
ROOT=Path(__file__).resolve().parent

def frame(folder,name,y,block):
    rows=block.strip('\n').splitlines()
    assert all(len(r)<=64 for r in rows), [(n,len(r)) for n,r in enumerate(rows) if len(r)>64]
    canvas=['.'*64 for _ in range(64)]
    for n,row in enumerate(rows):
        canvas[y+n]=row.ljust(64,'.')
    (ROOT/folder/f'{name}.pxgrid').write_text('\n'.join(canvas)+'\n')

def render(path):
    pal=json.loads((ROOT/'palette.json').read_text())
    rows=path.read_text().splitlines()
    assert len(rows)==64 and all(len(r)==64 for r in rows),path
    im=Image.new('RGBA',(64,64))
    for y,row in enumerate(rows):
        for x,c in enumerate(row):
            if c!='.':
                assert c in pal,(path,c)
                assert 1<=x<=62 and 1<=y<=60,(path,x,y)
                im.putpixel((x,y),tuple(bytes.fromhex(pal[c][1:]))+(255,))
    return im

