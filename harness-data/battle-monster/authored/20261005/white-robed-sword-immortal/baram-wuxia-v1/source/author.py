def patch(folder,name,changes):
    path=ROOT/folder/f'{name}.pxgrid'
    rows=path.read_text().splitlines()
    for y,x,pixels in changes:
        rows[y]=rows[y][:x]+pixels+rows[y][x+len(pixels):]
    path.write_text('\n'.join(rows)+'\n')

