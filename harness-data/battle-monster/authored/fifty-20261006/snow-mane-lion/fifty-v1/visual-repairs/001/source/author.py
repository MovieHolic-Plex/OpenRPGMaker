def paint(canvas, runs):
    for line in runs.strip().splitlines():
        if not line.strip(): continue
        y,x,pixels=line.split()
        y,x=int(y),int(x)
        assert 0<=x and x+len(pixels)<=128,(y,x,len(pixels))
        assert set(pixels)<=set(PALETTE)|{'.'},line
        canvas[y][x:x+len(pixels)]=pixels
    return canvas

def blank(): return [list('.'*128) for _ in range(128)]
def save(name,canvas,kind='poses'):
    (ROOT/kind).mkdir(exist_ok=True)
    (ROOT/kind/f'{name}.pxgrid').write_text('\n'.join(''.join(r) for r in canvas)+'\n')

