FRAMES={}
def rows(name, start, literal):
    ink=literal.strip('\n').splitlines()
    if any(len(s)>64 for s in ink):
        raise ValueError((name,[(start+i,len(s)) for i,s in enumerate(ink) if len(s)>64]))
    canvas=['.'*64 for _ in range(64)]
    for y,s in enumerate(ink,start):
        canvas[y]=s.ljust(64,'.')
    FRAMES[name]=canvas
    target=ROOT/('poses' if name in BASE else 'actions')/(name+'.pxgrid')
    target.write_text('\n'.join(canvas)+'\n',encoding='ascii')
