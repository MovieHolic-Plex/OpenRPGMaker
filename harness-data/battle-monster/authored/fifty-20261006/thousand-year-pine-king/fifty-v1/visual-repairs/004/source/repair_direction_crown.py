def repair_awake():
    # Each header and following literal lines is authored independently for
    # that pose. No offsets or pixels are taken from any other frame.
    blocks={}
    for line in (ROOT/'awake_face_rows.txt').read_text().splitlines():
        if line.startswith('#') or not line:continue
        if line.startswith('['):
            dest,x,y=line[1:-1].split()
            folder,name=dest.split('/')
            key=(folder,name,int(x),int(y))
            blocks[key]=[]
        else:blocks[key].append(line)
    for (folder,name,x,y),literal in blocks.items():
        a=load(folder,name)
        patch(a,x,y,'\n'.join(literal))
        save(folder,name,a)


