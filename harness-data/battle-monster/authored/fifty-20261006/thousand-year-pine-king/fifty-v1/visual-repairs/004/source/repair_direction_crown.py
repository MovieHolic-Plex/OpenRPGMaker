"""Native review corrections: only explicitly written coordinate/string patches.
No frame movement, geometry generation, pixel extraction or shading synthesis.
"""
from pathlib import Path
import shutil
ROOT = Path(__file__).resolve().parent

def load(folder, name):
    return [list(r) for r in (ROOT/folder/(name+'.pxgrid')).read_text().splitlines()]

def patch(a, x, y, literal):
    for dy, row in enumerate(literal.strip('\n').splitlines()):
        a[y+dy][x:x+len(row)] = list(row)

def save(folder, name, a):
    (ROOT/folder/(name+'.pxgrid')).write_text('\n'.join(''.join(r) for r in a)+'\n')

def archive():
    for folder in ['poses', 'actions']:
        for p in (ROOT/folder).glob('*.pxgrid'):
            dest=ROOT/'history'/'before-direction-crown'/folder/p.name
            dest.parent.mkdir(parents=True,exist_ok=True)
            if not dest.exists():shutil.copyfile(p,dest)


def overlay(a, x, y, literal):
    # Dots mean leave that already authored pixel alone, never fill a gap.
    for dy, row in enumerate(literal.strip('\n').splitlines()):
        for dx, c in enumerate(row):
            if c != '.':a[y+dy][x+dx]=c


