from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parent

def read(name, folder):
    return [list(r) for r in (ROOT / folder / (name + '.pxgrid')).read_text().splitlines()]

def rows(a, x, y, literal):
    for dy, row in enumerate(literal.strip('\n').splitlines()):
        a[y + dy][x:x + len(row)] = list(row)

def ink(a, x, y, literal):
    # Literal overlapping foliage; dots do not remove the original crown below.
    for dy, row in enumerate(literal.strip('\n').splitlines()):
        for dx, c in enumerate(row):
            if c != '.':
                a[y + dy][x + dx] = c

def clear(a, x, y, width, height):
    # Removal only; it does not construct ink or fill connectivity.
    for yy in range(y, y + height):
        a[yy][x:x + width] = list('.' * width)

def save(a, name, folder):
    (ROOT / folder / (name + '.pxgrid')).write_text('\n'.join(''.join(r) for r in a) + '\n')

