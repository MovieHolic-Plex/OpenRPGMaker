def apply():
    grids = {}
    for name, chosen in [*PATCHES.items(), *REFINEMENTS.items()]:
        if name not in grids:
            baseline = ROOT / 'original-before-repair' / (name + '.pxgrid')
            grids[name] = [list(row) for row in baseline.read_text().splitlines()]
        rows = grids[name]
        for line in chosen.strip().splitlines():
            xs, ys, pixels = line.split()
            x, y = int(xs), int(ys)
            rows[y][x:x + len(pixels)] = pixels
    for name, rows in grids.items():
        (ROOT / (name + '.pxgrid')).write_text(
            '\n'.join(''.join(row) for row in rows) + '\n')
    print('Applied six bounded, individually authored pose repairs.')


if __name__ == '__main__':
    apply()
