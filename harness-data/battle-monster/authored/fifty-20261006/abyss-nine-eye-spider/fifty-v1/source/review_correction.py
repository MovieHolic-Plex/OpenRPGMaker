def apply():
    for name, runs in PATCHES.items():
        path = ROOT / (name + '.pxgrid')
        rows = [list(row) for row in (ROOT/'before-review-correction'/(name+'.pxgrid')).read_text().splitlines()]
        for line in runs.strip().splitlines():
            xs, ys, pixels = line.split()
            x, y = int(xs), int(ys)
            rows[y][x:x+len(pixels)] = pixels
        path.write_text('\n'.join(''.join(row) for row in rows)+'\n')
    print('Applied individually selected review-correction runs.')

if __name__ == '__main__':
    apply()
