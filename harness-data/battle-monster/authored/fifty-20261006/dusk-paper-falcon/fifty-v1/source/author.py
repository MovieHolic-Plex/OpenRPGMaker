"""Literal pixel row authoring. No generated shapes or pose transforms.
Each block is an independently chosen native row sequence, placed at its stated anchor.
Only transparent canvas padding is automatic. render.py reads the resulting full grids.
"""
from pathlib import Path
import json
ROOT = Path(__file__).resolve().parent
PALETTE = {'K':'#171D2A','D':'#30394A','S':'#59616E','M':'#899099','P':'#C5C6BC','L':'#EEEBD8','W':'#FFF5DC','R':'#782E37','V':'#B44D42','C':'#E77953','H':'#F3AE79','G':'#A66B2E','Y':'#EFBB54','F':'#FFE699','T':'#74885B','B':'#B7C778'}
(ROOT/'palette.json').write_text(json.dumps(PALETTE,indent=2)+'\n')
def frame(name, x, y, rows, details=()):
    canvas = [list('.'*96) for _ in range(96)]
    for j,row in enumerate(rows.strip('\n').splitlines()):
        assert x+len(row)<=95,(name,j,len(row))
        for i,c in enumerate(row):
            assert c=='.' or c in PALETTE,(name,c)
            canvas[y+j][x+i]=c
    for yy,xx,row in details:
        assert xx+len(row)<=95,(name,yy,len(row))
        for i,c in enumerate(row):
            assert c=='.' or c in PALETTE,(name,c)
            canvas[yy][xx+i]=c
    sub = 'actions' if name.startswith(('skill','poison','stun','sleep')) else 'poses'
    (ROOT/sub/(name+'.pxgrid')).write_text('\n'.join(''.join(row) for row in canvas)+'\n')

