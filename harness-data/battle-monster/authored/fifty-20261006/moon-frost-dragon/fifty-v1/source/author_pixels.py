def block(canvas,spec):
    x,y,rows=spec
    for dy,row in enumerate(rows.splitlines()):
        for dx,symbol in enumerate(row):
            if not 0 <= x+dx <128 or not 0<=y+dy<128: raise ValueError((x+dx,y+dy))
            if symbol!='.' and symbol not in PALETTE: raise ValueError(symbol)
            if symbol != '.': canvas[y+dy][x+dx]=symbol

def blank(): return [list('.'*128) for _ in range(128)]
def save(name,canvas):
    folder=ROOT/('actions' if name.startswith(('skill','poison','stun','sleep')) else 'poses')
    folder.mkdir(exist_ok=True)
    (folder/(name+'.pxgrid')).write_text('\n'.join(''.join(row) for row in canvas)+'\n')

def idle():
    c=blank()
    for spec in (COIL,NECK_IDLE,HEAD_IDLE,FAR_ARM_IDLE,ARM_IDLE): block(c,spec)
    return c

