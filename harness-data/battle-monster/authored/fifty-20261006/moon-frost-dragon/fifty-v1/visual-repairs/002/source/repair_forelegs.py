def main():
    BEFORE.mkdir(exist_ok=True)
    for name in NAMES:
        folder = 'poses' if name in NAMES[:9] else 'actions'
        old = BEFORE / folder / (name+'.pxgrid')
        if not old.exists():
            old.parent.mkdir(exist_ok=True)
            shutil.copy2(ROOT / folder / old.name, old)
    if not (BEFORE/'palette.json').exists():
        shutil.copy2(ROOT/'palette.json', BEFORE/'palette.json')
    for name, blocks in BLOCKS.items():
        folder = 'poses' if name in NAMES[:9] else 'actions'
        rows = list((BEFORE/folder/(name+'.pxgrid')).read_text().splitlines())
        for x, y, right, literal in blocks:
            for dy, ink in enumerate(literal.splitlines()):
                if len(ink)>right-x or y+dy>124:
                    raise ValueError((name,x,y+dy,len(ink)))
                rows[y+dy] = rows[y+dy][:x] + ink.ljust(right-x,'.') + rows[y+dy][right:]
        (ROOT/folder/(name+'.pxgrid')).write_text('\n'.join(rows)+'\n')
        print(name, 'explicit rows written')

if __name__ == '__main__':
    main()
