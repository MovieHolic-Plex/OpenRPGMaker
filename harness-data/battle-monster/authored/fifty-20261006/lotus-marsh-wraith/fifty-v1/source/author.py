def revise(name, parent, text, action=False):
    """Keep unchanged authored clusters; replace only explicitly hand-selected rows.
    Each line is a complete replacement row with transparent left/right padding.
    No frame translation, morphing or rule-generated pixel changes.
    """
    src=ROOT/('poses' if (ROOT/'poses'/(parent+'.pxgrid')).exists() else 'actions')/(parent+'.pxgrid')
    rows=src.read_text().splitlines()
    for line in text.strip().splitlines():
        y,x,pixels=line.split();y,x=int(y),int(x)
        if x+len(pixels)>96: raise ValueError(line)
        rows[y]='.'*x+pixels+'.'*(96-x-len(pixels))
    (ROOT/('actions' if action else 'poses')/(name+'.pxgrid')).write_text('\n'.join(rows)+'\n')

