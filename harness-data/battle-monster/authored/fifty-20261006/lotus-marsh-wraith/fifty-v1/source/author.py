def pixels(name,text,action=False):
    """Only the exact literal coordinate spans listed here are painted."""
    path=ROOT/('actions' if action else 'poses')/(name+'.pxgrid')
    rows=[list(r) for r in path.read_text().splitlines()]
    for line in text.strip().splitlines():
        y,x,span=line.split();y,x=int(y),int(x)
        if x+len(span)>96: raise ValueError(line)
        rows[y][x:x+len(span)]=span
    path.write_text('\n'.join(''.join(r) for r in rows)+'\n')

