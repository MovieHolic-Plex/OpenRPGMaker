def write(name, text, action=False):
    canvas=[list('.'*96) for _ in range(96)]
    for line in text.strip().splitlines():
        y,x,pixels=line.split()
        y,x=int(y),int(x)
        if not 0<=y<96 or x<0 or x+len(pixels)>96: raise ValueError(line)
        canvas[y][x:x+len(pixels)]=list(pixels)
    (ROOT/('actions' if action else 'poses')/(name+'.pxgrid')).write_text('\n'.join(''.join(r) for r in canvas)+'\n')

