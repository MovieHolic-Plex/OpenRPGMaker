"""Literal native row authoring. No geometry, shade synthesis, or frame transform.
Blocks contain y-start followed by x|literal-row. Reusing unchanged anatomy is
explicit; changed regions are complete hand-chosen rows. Output is full 96² ASCII.
"""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parent
PAL=json.loads((ROOT/'palette.json').read_text())

def block(y, text):
    return [(y+i,int(line.split('|')[0]),line.split('|')[1])
            for i,line in enumerate(text.strip().splitlines())]

def write(name, parts, action=False):
    g=[list('.'*96) for _ in range(96)]
    for part in parts:
        for y,x,s in part:
            if not (0<=y<96 and 0<=x and x+len(s)<=96):
                raise ValueError((name,y,x,s))
            for j,ch in enumerate(s):
                if ch!='.' and ch not in PAL: raise ValueError(ch)
                g[y][x+j]=ch
    (ROOT/('actions' if action else 'poses')/(name+'.pxgrid')).write_text(
        '\n'.join(''.join(row) for row in g)+'\n')

