def write_frames():
    (ROOT/'palette.json').write_text(json.dumps(PALETTE, indent=2)+'\n')
    for name, (top, block) in FRAMES.items():
        lines=block.strip('\n').splitlines()
        if top+len(lines)>64: raise ValueError((name,top,len(lines)))
        if any(len(row)>64 for row in lines): raise ValueError(name+' row too long')
        if set(''.join(lines))-set(PALETTE)-{'.'}: raise ValueError(name+' palette')
        rows=['.'*64 for _ in range(top)] + [row.ljust(64,'.') for row in lines]
        rows += ['.'*64 for _ in range(64-len(rows))]
        folder='poses' if name in {'idle_a','idle_b','idle_c','windup','move','attack','recover','hit','dead'} else 'actions'
        (ROOT/folder).mkdir(exist_ok=True)
        (ROOT/folder/(name+'.pxgrid')).write_text('\n'.join(rows)+'\n')

