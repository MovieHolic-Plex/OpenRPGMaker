def put(canvas, records):
    for record in records.strip().splitlines():
        if not record.strip(): continue
        y, x, pixels = record.split()
        y, x = int(y), int(x)
        if not (0 <= y < 128 and 0 <= x and x+len(pixels) <= 128):
            raise ValueError(record)
        if set(pixels)-set(PALETTE)-{'.'}: raise ValueError(record)
        canvas[y][x:x+len(pixels)] = pixels

def save(name, records, resting=False):
    canvas = [list('.'*128) for _ in range(128)]
    put(canvas, REST_SHELL if resting else SHELL)
    if not resting: put(canvas, DOME)
    put(canvas, records)
    folder = ROOT / ('poses' if name in POSES else 'actions')
    folder.mkdir(exist_ok=True)
    (folder / (name+'.pxgrid')).write_text('\n'.join(''.join(row) for row in canvas)+'\n')

