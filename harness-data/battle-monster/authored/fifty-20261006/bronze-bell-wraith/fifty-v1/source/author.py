def blank():
    return [list('.' * SIZE) for _ in range(SIZE)]

def export(name, canvas, action=False):
    path = ROOT / ('actions' if action else 'poses') / (name + '.pxgrid')
    path.parent.mkdir(exist_ok=True)
    path.write_text('\n'.join(''.join(row) for row in canvas) + '\n')

def main():
    base = blank()
    inscribe(base, BASE)
    inscribe(base, BODY_FINISH)
    inscribe(base, DETAIL_FINISH)
    export('idle_a', base)
    for name, patches in [('idle_b',IDLE_B),('idle_c',IDLE_C)]:
        canvas = [row[:] for row in base]
        inscribe(canvas,LOWER_CLEAR)
        inscribe(canvas,patches)
        export(name,canvas)
    canvas=blank()
    inscribe(canvas,WINDUP)
    export('windup',canvas)
    canvas=blank()
    inscribe(canvas,ATTACK)
    inscribe(canvas,LOWER_CLEAR)
    inscribe(canvas,ATTACK_CONTACT_FINISH)
    export('attack',canvas)
    # Move keeps its independently inscribed pre-contact hand and clapper rows.
    canvas=blank()
    inscribe(canvas,ATTACK)
    inscribe(canvas,MOVE_PATCH)
    inscribe(canvas,LOWER_CLEAR)
    inscribe(canvas,MOVE_FINISH)
    inscribe(canvas,MOVE_EDGE_FIX)
    export('move',canvas)
    canvas=[row[:] for row in base]
    inscribe(canvas,LOWER_CLEAR)
    inscribe(canvas,RECOVER)
    export('recover',canvas)
    canvas=[row[:] for row in base]
    inscribe(canvas,LOWER_CLEAR)
    inscribe(canvas,HIT_PATCH)
    inscribe(canvas,HIT_EDGE_FIX)
    inscribe(canvas,HIT_CROWN_FINISH)
    export('hit',canvas)
    canvas=blank()
    inscribe(canvas,DEAD)
    inscribe(canvas,DEAD_NECK_FINISH)
    export('dead',canvas)
    for name, patches in [('skill_a',SKILL_A),('skill_b',SKILL_B),('skill_c',SKILL_C)]:
        canvas=[row[:] for row in base]
        inscribe(canvas,LOWER_CLEAR)
        inscribe(canvas,patches)
        export(name,canvas,action=True)
    canvas=[row[:] for row in base]
    inscribe(canvas,LOWER_CLEAR)
    inscribe(canvas,POISON_A)
    inscribe(canvas,POISON_SHOULDER_FINISH)
    export('poison_a',canvas,action=True)
    inscribe(canvas,POISON_B)
    export('poison_b',canvas,action=True)
    canvas=blank()
    inscribe(canvas,STUN_A)
    export('stun_a',canvas,action=True)
    inscribe(canvas,STUN_B)
    export('stun_b',canvas,action=True)
    canvas=blank()
    inscribe(canvas,SLEEP_A)
    export('sleep_a',canvas,action=True)
    inscribe(canvas,SLEEP_B)
    export('sleep_b',canvas,action=True)

if __name__ == '__main__':
    main()
