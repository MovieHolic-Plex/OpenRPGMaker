SIZE = 96

def inscribe(canvas, rows):
    for x, y, pixels in rows:
        if not (0 <= x and x + len(pixels) <= SIZE and 0 <= y < SIZE):
            raise ValueError((x,y,len(pixels)))
        canvas[y][x:x+len(pixels)] = list(pixels)

