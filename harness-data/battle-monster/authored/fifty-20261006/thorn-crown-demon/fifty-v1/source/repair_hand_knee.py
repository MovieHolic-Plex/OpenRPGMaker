def apply():
    for name, text in SPANS.items():
        folder = 'actions' if name.startswith('sleep') else 'poses'
        path = ROOT / folder / (name + '.pxgrid')
        rows = [list(row) for row in path.read_text().splitlines()]
        for line in text.strip().splitlines():
            y, x, pixels = line.split()
            y, x = int(y), int(x)
            for dx, symbol in enumerate(pixels):
                rows[y][x + dx] = symbol
        path.write_text('\n'.join(''.join(row) for row in rows) + '\n')
        # Retain the same literal patches in the original row-span record.
        record = ROOT / 'authored_rows.txt'
        content = record.read_text()
        start = content.index('[' + name + ']\n') + len(name) + 3
        end = content.find('\n[', start)
        if end == -1:
            end = len(content)
        prior_patch = content.find('\n# hand-knee repair\n', start, end)
        if prior_patch != -1:
            content = content[:prior_patch] + content[end:]
            end = prior_patch
        content = content[:end] + '\n# hand-knee repair\n' + text.strip() + '\n' + content[end:]
        record.write_text(content)

if __name__ == '__main__':
    apply()
