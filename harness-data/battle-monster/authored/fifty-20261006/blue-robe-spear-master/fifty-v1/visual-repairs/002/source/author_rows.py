def export():
    palette = json.loads((ROOT/'palette.json').read_text())
    for name, rows in FRAMES.items():
        canvas = [['.']*64 for _ in range(64)]
        for y,x,run in rows:
            if x < 1 or x+len(run)>63 or not 1<=y<=60:
                raise ValueError((name,y,x,len(run)))
            for dx,symbol in enumerate(run):
                if symbol!='.' and symbol not in palette: raise ValueError(symbol)
                if canvas[y][x+dx]!='.': raise ValueError(('overlap',name,y,x+dx))
                canvas[y][x+dx] = symbol
        directory = 'poses' if name in ('idle_a','idle_b','idle_c','windup','move','attack','recover','hit','dead') else 'actions'
        (ROOT/directory/(name+'.pxgrid')).write_text('\n'.join(''.join(row) for row in canvas)+'\n')


