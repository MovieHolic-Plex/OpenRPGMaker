def frame(name, literal):
    rows=[list('.'*64) for _ in range(64)]
    for entry in literal.strip().splitlines():
        y,x,pixels=entry.split()
        y,x=int(y),int(x)
        for dx,p in enumerate(pixels):
            rows[y][x+dx]=p
    group='poses' if name in {'idle_a','idle_b','idle_c','windup','move','attack','recover','hit','dead'} else 'actions'
    (ROOT/group/(name+'.pxgrid')).write_text('\n'.join(''.join(r) for r in rows)+'\n')

