def write(name, runs, folder='poses'):
    a=[list('.'*64) for _ in range(64)]
    for y,x,s in runs:
        if x<0 or y<0 or x+len(s)>64 or y>=64: raise ValueError((name,y,x,s))
        a[y][x:x+len(s)]=s
    (ROOT/folder).mkdir(exist_ok=True)
    (ROOT/folder/f'{name}.pxgrid').write_text('\n'.join(''.join(r) for r in a)+'\n')

def patch(name, parent, edits, folder='poses', parent_folder='poses'):
    a=[list(s) for s in (ROOT/parent_folder/f'{parent}.pxgrid').read_text().splitlines()]
    for y,x,s in edits: a[y][x:x+len(s)]=s
    (ROOT/folder/f'{name}.pxgrid').write_text('\n'.join(''.join(r) for r in a)+'\n')

