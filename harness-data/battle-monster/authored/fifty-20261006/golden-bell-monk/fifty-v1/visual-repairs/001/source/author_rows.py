def write_grids():
    for name, (start_y, start_x, literal) in ART.items():
        canvas = [['.'] * 64 for _ in range(64)]
        rows = literal.strip('\n').splitlines()
        for offset, pixels in enumerate(rows):
            y = start_y + offset
            if y >= 64 or start_x + len(pixels) > 64:
                raise ValueError((name, y, len(pixels)))
            for dx, symbol in enumerate(pixels):
                canvas[y][start_x + dx] = symbol
        subdir = 'poses' if name in ('idle_a','idle_b','idle_c','windup','move','attack','recover','hit','dead') else 'actions'
        folder = ROOT / subdir
        folder.mkdir(exist_ok=True)
        (folder / (name + '.pxgrid')).write_text('\n'.join(''.join(row) for row in canvas) + '\n')

if __name__ == '__main__':
    write_grids()
