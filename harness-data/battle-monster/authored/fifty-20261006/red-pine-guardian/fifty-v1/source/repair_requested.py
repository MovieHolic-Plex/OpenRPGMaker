def apply(selected=None):
    for (group, name), block in PATCHES.items():
        if selected is not None and name not in selected:
            continue
        path = ROOT / group / (name + '.pxgrid')
        rows = [list(row) for row in path.read_text(encoding='ascii').splitlines()]
        for record in block.strip().splitlines():
            ys, xs, pixels = record.split()
            y, x = int(ys), int(xs)
            rows[y][x:x + len(pixels)] = list(pixels)
        path.write_text('\n'.join(''.join(row) for row in rows) + '\n', encoding='ascii')


