"""Explicit native row repairs. Only literal ink strings; no pose transforms.

The archived grids preserve the draft. Each frame has its own authored edits.
Run this after author.py only if reconstructing the draft and this repair.
"""
from pathlib import Path
R = Path(__file__).parent
frames = {}
for kind in ('poses', 'actions'):
    for p in (R/'original-before-repair'/kind).glob('*.pxgrid'):
        frames[p.stem] = [list(row) for row in p.read_text().splitlines()]

def ink(name, y, text):
    """Each line is literal x + a literal ASCII run, on consecutive native rows."""
    for dy, line in enumerate(text.strip().splitlines()):
        x, row = line.split(' ', 1)
        x = int(x)
        frames[name][y+dy][x:x+len(row)] = list(row)

