def apply():
    for name, table in REPAIRS.items():
        folder = 'poses' if name in {'idle_a','idle_b','idle_c','windup','move','attack','recover','hit','dead'} else 'actions'
        path = ROOT / folder / (name + '.pxgrid')
        original = ROOT / 'original-before-three-quarter-repair' / folder / (name + '.pxgrid')
        rows = [list(row) for row in original.read_text().splitlines()]
        for line in table.strip().splitlines():
            y, x, pixels = line.split()
            y, x = int(y), int(x)
            if x < 1 or x + len(pixels) > 64 or y < 1 or y > 60:
                raise ValueError((name, y, x, pixels))
            rows[y][x:x + len(pixels)] = pixels
        path.write_text('\n'.join(''.join(row) for row in rows) + '\n')

if __name__ == '__main__':
    apply()
