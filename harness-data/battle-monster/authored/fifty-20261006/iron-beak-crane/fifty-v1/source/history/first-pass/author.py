def write():
    (ROOT / 'palette.json').write_text(json.dumps(PALETTE, indent=2)+'\n')
    for name, packet in FRAMES.items():
        canvas = [['.']*64 for _ in range(64)]
        for entry in packet.strip().splitlines():
            ys, xs, pixels = entry.split()
            y,x = int(ys), int(xs)
            if x < 1 or x+len(pixels)>63 or not 1<=y<=60:
                raise ValueError((name,y,x,len(pixels)))
            for i,c in enumerate(pixels):
                if c!='.' and c not in PALETTE:
                    raise ValueError((name,c))
                canvas[y][x+i] = c
        folder = 'poses' if name in ['idle_a','idle_b','idle_c','windup','move','attack','recover','hit','dead'] else 'actions'
        (ROOT / folder).mkdir(exist_ok=True)
        (ROOT / folder / (name+'.pxgrid')).write_text('\n'.join(''.join(row) for row in canvas)+'\n')

