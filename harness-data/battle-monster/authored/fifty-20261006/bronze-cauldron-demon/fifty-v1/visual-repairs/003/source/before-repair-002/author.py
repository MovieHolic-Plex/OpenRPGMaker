"""Literal native clusters. No geometry, shading synthesis or frame transforms.
Rows are copied to explicitly named positions; padding is transparent only.
The .pxgrid files are the complete final native source.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent
CELL = 128

def canvas():
    return [list('.' * CELL) for _ in range(CELL)]

def rows(grid, x, y, text):
    for dy, line in enumerate(text.strip('\n').splitlines()):
        line = line.strip()
        assert 0 <= x and x + len(line) <= CELL, (x, y+dy, len(line))
        for dx, c in enumerate(line):
            if c != '.':
                grid[y+dy][x+dx] = c

def patch(grid, specs):
    for x, y, pixels in specs:
        rows(grid, x, y, pixels)

def save(name, grid, action=False):
    folder = ROOT / ('actions' if action else 'poses')
    folder.mkdir(exist_ok=True)
    (folder / (name+'.pxgrid')).write_text('\n'.join(''.join(r) for r in grid)+'\n')

