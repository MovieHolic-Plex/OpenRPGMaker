from pathlib import Path
ROOT = Path(__file__).resolve().parent

def frame(name, rows):
    canvas = [list('.' * 64) for _ in range(64)]
    for y, x, pixels in rows:
        if not (0 <= y < 64 and 0 <= x and x + len(pixels) <= 64):
            raise ValueError((name, y, x, len(pixels)))
        canvas[y][x:x+len(pixels)] = pixels
    path = ROOT / (name + '.pxgrid')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(''.join(row) for row in canvas) + '\n')

