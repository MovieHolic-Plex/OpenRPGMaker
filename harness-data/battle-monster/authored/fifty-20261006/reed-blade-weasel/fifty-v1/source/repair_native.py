def apply_rows(rows, data):
    records = [r.split() for r in data.strip().splitlines()]
    for y in {int(r[0]) for r in records}:
        rows[y] = list('.'*64)
    for sy, sx, run in records:
        y, x = int(sy), int(sx)
        if x < 0 or x+len(run) > 64:
            raise ValueError((y,x,run))
        rows[y][x:x+len(run)] = list(run)

def main():
    for name, data in REVISED.items():
        group = 'poses' if (ROOT/'original'/'poses'/f'{name}.pxgrid').exists() else 'actions'
        rows = [list(r) for r in (ROOT/'original'/group/f'{name}.pxgrid').read_text().splitlines()]
        apply_rows(rows, data)
        if name in DETAILS:
            apply_rows(rows, DETAILS[name])
        (ROOT/group/f'{name}.pxgrid').write_text('\n'.join(''.join(r) for r in rows)+'\n')

if __name__ == '__main__':
    main()
