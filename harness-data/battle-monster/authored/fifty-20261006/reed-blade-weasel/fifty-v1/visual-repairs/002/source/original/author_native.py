def write_grids():
    (ROOT/'palette.json').write_text(json.dumps(PALETTE, indent=2)+'\n')
    for name, data in FRAMES.items():
        canvas = [list('.'*64) for _ in range(64)]
        occupied = set()
        for record in data.strip().splitlines():
            ystr, xstr, run = record.split()
            y,x = int(ystr),int(xstr)
            if not (0<=y<64 and 0<=x and x+len(run)<=64):
                raise ValueError((name,y,x,len(run)))
            for dx,symbol in enumerate(run):
                if symbol!='.' and (x+dx,y) in occupied:
                    raise ValueError(('overlapping ink', name,x+dx,y))
                if symbol!='.': occupied.add((x+dx,y))
                if symbol!='.' and symbol not in PALETTE: raise ValueError(symbol)
                if symbol!='.': canvas[y][x+dx]=symbol
