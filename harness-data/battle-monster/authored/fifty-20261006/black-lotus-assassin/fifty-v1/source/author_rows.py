def write_frames():
    ROOT.joinpath('palette.json').write_text(json.dumps(PALETTE, indent=2) + '\n')
    for name, blocks in FRAMES.items():
        canvas = [list('.' * 64) for _ in range(64)]
        for x, y, rows in blocks:
            for dy, row in enumerate(rows.strip('\n').splitlines()):
                if x + len(row) > 64 or y + dy > 63:
                    raise ValueError((name, x, y + dy, len(row)))
                for dx, char in enumerate(row):
                    if char != '.' and char not in PALETTE:
                        raise ValueError((name, char))
                    if char != '.':
                        canvas[y + dy][x + dx] = char
        folder = 'actions' if name.startswith(('skill_', 'poison_', 'stun_', 'sleep_')) else 'poses'
        ROOT.joinpath(folder, name + '.pxgrid').write_text('\n'.join(''.join(r) for r in canvas) + '\n')

if __name__ == '__main__':
    write_frames()
