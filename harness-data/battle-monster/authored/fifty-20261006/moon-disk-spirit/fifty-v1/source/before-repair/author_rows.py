"""Authored native pixel strings. Only literal row writes and blank padding.
No drawing primitives, geometry, transforms, interpolation or shading code.
Each delta is a chosen row replacement at its own native location.
"""
from pathlib import Path
ROOT = Path(__file__).resolve().parent

def rows(canvas, block):
    for line in block.strip().splitlines():
        y, x, ink = line.split()
        y, x = int(y), int(x)
        if not 0 <= x < 96 or x + len(ink) > 96:
            raise ValueError((y, x, len(ink)))
        canvas[y][x:x+len(ink)] = list(ink)

def blank():
    return [list('.' * 96) for _ in range(96)]

def save(name, canvas, action=False):
    path = ROOT / ('actions' if action else 'poses') / (name + '.pxgrid')
    path.write_text('\n'.join(''.join(row) for row in canvas) + '\n')

