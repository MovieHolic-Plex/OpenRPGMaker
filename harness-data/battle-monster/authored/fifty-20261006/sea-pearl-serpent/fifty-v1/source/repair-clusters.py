def apply():
    palette = set(json.loads((ROOT / 'palette.json').read_text())) | {'.'}
    changes = {}
    for name, patches in PATCHES.items():
        path = ROOT / 'poses' / (name + '.pxgrid')
        rows = path.read_text().splitlines()
        old = rows.copy()
        sketch = '\n# Native literal correction: released coil / bite tip.\n'
        for x, y, pixels, clear in patches:
            assert set(pixels) <= palette and x + len(pixels) <= 127
            tail = '.' * (128 - x - len(pixels)) if clear else rows[y][x + len(pixels):]
            rows[y] = rows[y][:x] + pixels + tail
            sketch += f'@ {x} {y}\n' + pixels + ('.' * (128 - x - len(pixels)) if clear else '') + '\n'
        path.write_text('\n'.join(rows) + '\n')
        with (ROOT / 'sketches' / (name + '.txt')).open('a') as stream:
            stream.write(sketch)
        changes[name] = sum(a != b for ar, br in zip(old, rows) for a, b in zip(ar, br))
    (ROOT / 'repair-clusters.json').write_text(json.dumps(PATCHES, indent=2) + '\n')
    print(json.dumps(changes))

if __name__ == '__main__':
    apply()
