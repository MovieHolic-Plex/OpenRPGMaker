def apply_patches(frames):
    for choices in (PATCHES, REFINEMENTS):
        for name, literal in choices.items():
            rows = frames[name]
            for entry in literal.strip().splitlines():
                y, x, pixels = entry.split()
                y, x = int(y), int(x)
                rows[y] = rows[y][:x] + pixels + rows[y][x + len(pixels):]


def save_repair():
    checkpoint = ROOT / 'checkpoints' / 'anatomy-before'
    checkpoint.mkdir(exist_ok=True)
    frames = {}
    paths = {}
    for name in PATCHES:
        path = ROOT / ('poses' if name in POSES else 'actions') / (name + '.pxgrid')
        original = path.read_text()
        saved = checkpoint / path.name
        if not saved.exists():
            saved.write_text(original)
        frames[name] = original.splitlines()
        paths[name] = path
    apply_patches(frames)
    for name, rows in frames.items():
        paths[name].write_text('\n'.join(rows) + '\n')


if __name__ == '__main__':
    save_repair()
