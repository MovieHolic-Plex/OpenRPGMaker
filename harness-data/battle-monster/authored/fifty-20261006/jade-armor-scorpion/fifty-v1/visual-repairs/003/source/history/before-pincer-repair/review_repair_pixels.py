"""Native row spans chosen after the supplied rework observations.
Each pose has its own literal edits. No propagation, geometry or frame transforms.
Run after the older authoring stages, before render_source.py.
"""
from pathlib import Path
ROOT = Path(__file__).resolve().parent

def revise(group, name, block):
    p = ROOT / group / (name + '.pxgrid')
    rows = [list(r) for r in p.read_text().splitlines()]
    for line in block.strip().splitlines():
        y, x, ink = line.split()
        y, x = int(y), int(x)
        if not (0 <= x and x + len(ink) <= 128):
            raise ValueError((name, y, x, ink))
        rows[y][x:x + len(ink)] = ink
    p.write_text('\n'.join(''.join(r) for r in rows) + '\n')

