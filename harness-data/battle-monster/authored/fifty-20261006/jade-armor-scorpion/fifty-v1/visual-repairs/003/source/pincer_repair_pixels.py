"""Explicit native row spans, independently chosen for each pincer pose.
Only literal palette strings are written. No geometry or inter-frame transforms.
"""
from pathlib import Path
ROOT=Path(__file__).resolve().parent

def edit(group,name,block):
    path=ROOT/group/(name+'.pxgrid')
    rows=path.read_text().splitlines()
    for line in block.strip().splitlines():
        y,x,ink=line.split();y=int(y);x=int(x)
        if x+len(ink)>127:raise ValueError((name,y,x,len(ink)))
        rows[y]=rows[y][:x]+ink+rows[y][x+len(ink):]
    path.write_text('\n'.join(rows)+'\n')

