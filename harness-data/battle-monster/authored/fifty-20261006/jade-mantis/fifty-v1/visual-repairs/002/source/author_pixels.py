def write_frame(name, block):
    rows = [list('.'*64) for _ in range(64)]
    used = set()
    for line in block.strip().splitlines():
        y, x, pixels = line.split()
        y, x = int(y), int(x)
        if y in used:
            raise ValueError(f'duplicate authored row: {name} {y}')
        used.add(y)
        if x < 1 or x + len(pixels) > 63 or not 1 <= y <= 60:
            raise ValueError(f'out of bounds: {name} {y} {x} {len(pixels)}')
        for i, symbol in enumerate(pixels):
            if symbol != '.' and symbol not in PALETTE:
                raise ValueError((name, symbol))
            rows[y][x+i] = symbol
    folder = ROOT / ('poses' if name in {'idle_a','idle_b','idle_c','windup','move','attack','recover','hit','dead'} else 'actions')
    folder.mkdir(exist_ok=True)
    (folder/f'{name}.pxgrid').write_text('\n'.join(''.join(r) for r in rows)+'\n', encoding='ascii')


