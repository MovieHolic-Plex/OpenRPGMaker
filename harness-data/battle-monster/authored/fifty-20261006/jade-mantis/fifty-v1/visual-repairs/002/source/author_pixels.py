def chosen_clusters(name, block):
    # Existing explicit rows are decoded only to write specified coordinates.
    canvas = [list('.'*64) for _ in range(64)]
    for line in FRAMES[name].strip().splitlines():
        y,x,pixels=line.split();y=int(y);x=int(x)
        canvas[y][x:x+len(pixels)] = list(pixels)
    for line in block.strip().splitlines():
        if not line.strip(): continue
        y,x,pixels=line.split();y=int(y);x=int(x)
        if x<1 or x+len(pixels)>63 or not 1<=y<=60: raise ValueError((name,line))
        canvas[y][x:x+len(pixels)] = list(pixels)
    # The resulting source retains full literal ASCII rows including blank rows.
    folder=ROOT/('poses' if name in {'idle_a','idle_b','idle_c','windup','move','attack','recover','hit','dead'} else 'actions')
    folder.mkdir(exist_ok=True)
    (folder/f'{name}.pxgrid').write_text('\n'.join(''.join(r) for r in canvas)+'\n',encoding='ascii')


