def blank(): return [list('.'*128) for _ in range(128)]
def block(g,x,y,s):
    for dy,row in enumerate(s.strip('\n').splitlines()):
        assert 0<=y+dy<128
        assert 0<=x and x+len(row)<=128,(x,y+dy,len(row))
        assert set(row)<=set(PAL)|{'.'},set(row)-set(PAL)-{'.'}
        g[y+dy][x:x+len(row)]=row

def runs(g,items):
    for x,y,row in items: block(g,x,y,row)
def save(g,name,action=False):
    rows=[''.join(r) for r in g]
    assert len(rows)==128 and all(len(r)==128 for r in rows)
    assert all(r[0]==r[-1]=='.' for r in rows)
    assert set(rows[0]+''.join(rows[125:]))=={'.'}
    (ROOT/('actions' if action else 'poses')/(name+'.pxgrid')).write_text('\n'.join(rows)+'\n')
def decode(g):
    im=Image.new('RGBA',(128,128))
    for y,row in enumerate(g):
        for x,c in enumerate(row):
            if c!='.': im.putpixel((x,y),tuple(bytes.fromhex(PAL[c][1:]))+(255,))
    return im
