from pathlib import Path
import json
from PIL import Image
ROOT=Path(__file__).resolve().parent
PALETTE=json.loads((ROOT/'palette.json').read_text())

def blank(): return [list('.'*96) for _ in range(96)]
def runs(grid, entries):
    for y,x,ink in entries:
        assert 0<=y<96 and 0<=x and x+len(ink)<=96, (y,x,len(ink))
        assert set(ink)<=set(PALETTE)|{'.'}, (y,x,ink)
        grid[y][x:x+len(ink)]=list(ink)
    return grid

def save(grid, folder, name):
    (ROOT/folder/f'{name}.pxgrid').write_text('\n'.join(''.join(r) for r in grid)+'\n')

def decode(path, output):
    rows=path.read_text().splitlines()
    assert len(rows)==96 and all(len(r)==96 for r in rows), path
    im=Image.new('RGBA',(96,96))
    colors={c:tuple(bytes.fromhex(v[1:]))+(255,) for c,v in PALETTE.items()}
    im.putdata([colors.get(c,(0,0,0,0)) for r in rows for c in r])
    im.save(output)
    return im

