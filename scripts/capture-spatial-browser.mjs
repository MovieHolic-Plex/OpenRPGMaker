import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
await mkdir('output/evidence/spatial-browser', { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('pageerror', e => console.log('PAGEERROR',e.message));
try {
await page.addInitScript(() => { localStorage.setItem('oprn:editor-welcome-dismissed','1'); localStorage.setItem('rpg-zzu:editor-ui-mode','expert'); });
await page.goto(`${process.argv[2] ?? 'http://127.0.0.1:9999'}/?blankProject=1&aiBridge=0`, { timeout: 120000, waitUntil: 'domcontentloaded' });
await page.getByTestId('toolbar-database').waitFor({ timeout: 120000 });
await page.getByTestId('toolbar-database').click();
const group = page.getByTestId('db-tab-group-world');
if (await group.getAttribute('aria-expanded') === 'false') await group.click();
await page.getByTestId('db-tab-spatial-objects').click();
await page.getByTestId('spatial-browser-search').fill('침대');
assert.ok(await page.locator('.asset-browser-card').count() > 0);
await page.screenshot({ path: 'output/evidence/spatial-browser/objects.png' });
await page.locator('.asset-browser-card').first().click();
await page.getByTestId('spatial-object-copy').click();
await page.getByTestId('structure-kit-tile-browser').click();
await page.getByTestId('tile-browser-grid').waitFor();
await page.screenshot({ path: 'output/evidence/spatial-browser/tile-browser.png' });
await page.getByTestId('tile-browser-search').fill('54');
await page.getByTestId('tile-browser-tile-54').click();
await page.getByTestId('tile-browser-use').click();
await page.getByTestId('structure-kit-editor-close').click();
await page.evaluate(async () => {
 const {store}=await import('/src/project/store.ts');
 const {spaceCompilerFixture,spaceDesign}=await import('/test/support/spatialSpaceCompilerFixture.ts');
 const {clearAuthoringSession}=await import('/src/editor/panels/spatialAuthoringAccess.ts');
 const {setSpatialTab,selectSpatialDesign}=await import('/src/editor/panels/spatialAuthoringSession.ts');
 const {librarySpaceCardId}=await import('/src/editor/panels/spatialSpaceDraft.ts');
 const fixture=structuredClone(spaceCompilerFixture());
 fixture.spatialAuthoring.library.spaces[spaceDesign].name='내 작업실';
 fixture.spatialAuthoring.library.spaces[spaceDesign].objectSlots=[];
 fixture.spatialAuthoring.library.objects['bed-design'].name='침대';
 clearAuthoringSession(); store.replace(fixture,{preserveEventDrafts:false});
 setSpatialTab('spaces'); selectSpatialDesign(librarySpaceCardId(spaceDesign));
});
await page.getByTestId('db-tab-spatial-spaces').click();
await page.getByTestId('space-object-search').fill('침대');
await page.getByTestId('spatial-object-bed-design').click();
const board=page.getByTestId('spatial-space-board');
await board.click({position:{x: 4*24+10,y: 3*24+10}});
assert.equal(await page.evaluate(async () => { const {visibleAuthoringProject}=await import('/src/editor/panels/spatialAuthoringAccess.ts'); return visibleAuthoringProject().spatialAuthoring.library.spaces['room-design'].objectSlots.length; }),1);
await page.getByTestId('spatial-preview').click(); await page.getByTestId('spatial-apply').click();
assert.equal(await page.evaluate(async () => { const {store}=await import('/src/project/store.ts'); return store.getCurrent().spatialAuthoring.library.spaces['room-design'].objectSlots.length; }),1);
await page.getByTestId('spatial-object-bed-design').dragTo(board, { targetPosition: { x: 8*24+10, y: 5*24+10 } });
assert.equal(await page.evaluate(async () => { const {visibleAuthoringProject}=await import('/src/editor/panels/spatialAuthoringAccess.ts'); return visibleAuthoringProject().spatialAuthoring.library.spaces['room-design'].objectSlots.length; }),2);
await page.getByTestId('spatial-preview').click(); await page.getByTestId('spatial-apply').click();
await page.getByTestId('spatial-undo').click();
assert.equal(await page.evaluate(async () => { const {store}=await import('/src/project/store.ts'); return store.getCurrent().spatialAuthoring.library.spaces['room-design'].objectSlots.length; }),1);
await page.locator('.spatial-space-slot-art').click();
await board.focus(); await page.keyboard.press('ArrowRight');
assert.equal(await page.evaluate(async () => { const {visibleAuthoringProject}=await import('/src/editor/panels/spatialAuthoringAccess.ts'); return visibleAuthoringProject().spatialAuthoring.library.spaces['room-design'].objectSlots[0].placement.x; }),5);
await page.getByTestId('spatial-preview').click(); await page.getByTestId('spatial-apply').click();
await page.screenshot({ path: 'output/evidence/spatial-browser/space-composition.png' });
await page.setViewportSize({width:1024,height:768});
await page.screenshot({ path: 'output/evidence/spatial-browser/space-composition-1024.png' });
console.log('PASS: separate object browser, tile browser selection, and object placement in a space');
} catch(e) { await page.screenshot({path:'output/evidence/spatial-browser/failure.png'}).catch(()=>{}); throw e; }
finally { await browser.close(); }
