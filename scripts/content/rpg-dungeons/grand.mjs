// One large multi-section dungeon (80×64, the scale of 비취 대계곡): 「잊힌 수문 유적」.
//   A  entrance cavern (dirt, south)   — the adventurers' camp, the hub every route returns to
//   B  sluice waterway (grey stone, west) — a long canal with narrow banks, two bridges, the sluice-keeper's room
//   C  antechamber + boss hall (red rock, north) — carpet to the dais; a sealed treasure vault off the east
//   D  collapsed hall (cut stone, east) — the floor fell into a chasm round an island; plank bridge to the key
// Loop: A → B → (sluice portcullis) → C → D → A. Shortcut: A ↔ C straight north through a barred rock gate.
// Puzzle spots (terrain only, events later): the lever in the sluice room lifts the portcullis between B and C;
// the key on the chasm island opens the vault gate north of D.
import { grid } from "./kit.mjs";

export function grandPlans() {
  return [sluiceRuins()];
}

/** Replace only `from` cells inside a box with `to` (a bridge laid over just the chasm it crosses). */
function over(art, x0, y0, x1, y1, from, to) {
  const rows = art.split("\n");
  for (let y = y0; y <= y1; y++) {
    const r = [...rows[y + 1]]; // art starts with a newline
    for (let x = x0; x <= x1; x++) if (r[x] === from) r[x] = to;
    rows[y + 1] = r.join("");
  }
  return rows.join("\n");
}

