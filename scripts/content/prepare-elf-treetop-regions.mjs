// Publish the elf treetop village under 장소 from the reloaded canonical export. No host writes.
// Writes public/assets/region-references/elf-treetop-village.{png,oprn.json}, src/project/regionReferences/elf-treetop.json
// and src/project/elfTreetopPlaceReferences.ts.
// Usage: node scripts/content/prepare-elf-treetop-regions.mjs output/evidence/elf-treetop/reloaded.json
import fs from "node:fs";
import assert from "node:assert/strict";
const [input] = process.argv.slice(2);
if (!input) throw Error("Usage: prepare-elf-treetop-regions.mjs reloaded-project.json");
const project = JSON.parse(fs.readFileSync(input));
const c = JSON.parse(fs.readFileSync("tiledata/elf-treetop/catalog.json"));
const proof = JSON.parse(fs.readFileSync("tiledata/elf-treetop/storage-proof.json"));
const references = JSON.parse(fs.readFileSync("src/assets/sharedElfTreetopReferences.json"));
const plan = c.plan, map = project.maps[plan.id];
assert.deepEqual(map.lowerTiles, c.map.lowerTiles);
assert.deepEqual(map.upperTiles, c.map.upperTiles);
const tileset = project.tilesets[map.tilesetId];
const exported = structuredClone(project);
exported.meta.title = plan.name;
// Only the guidance about these parts travels with the download (the full forest_harmony shelf is large).
exported.tilesets = { [tileset.id]: { ...tileset, referenceDocuments: (tileset.referenceDocuments ?? []).filter((k) => /^(elf-treetop|diverse-villages)/.test(k.id)) } };
fs.writeFileSync(`public/assets/region-references/${plan.id}.oprn.json`, JSON.stringify(exported) + "\n");
fs.copyFileSync(`tiledata/elf-treetop/images/${plan.id}.png`, `public/assets/region-references/${plan.id}.png`);
const { id, image, tileSize, tilesPerRow, count, passability, priority, terrain } = tileset;
fs.writeFileSync("src/project/regionReferences/elf-treetop.json",
  JSON.stringify({ maps: { [map.id]: map }, tilesets: { [id]: { id, image, tileSize, tilesPerRow, count, passability, priority, terrain } } }) + "\n");
const category = references.forest_harmony;
const entry = {
  id: `${plan.id}-${map.width}x${map.height}`,
  name: plan.name,
  kind: "completed-place",
  placeKind: "settlement",
  revision: 1,
  x: 0, y: 0, width: map.width, height: map.height,
  tilesetId: map.tilesetId,
  preview: `/assets/region-references/${plan.id}.png`,
  tilesetPreview: "/assets/elf-treetop/treetop-parts.png",
  projectDownload: `/assets/region-references/${plan.id}.oprn.json`,
  sourceProjectId: proof.projectId,
  sourceMapId: map.id,
  snapshotProjectId: `oprn-place-${plan.id}-v1`,
  rules: [
    plan.note + ".",
    `출구: ${plan.exits.map((e) => `${{ south: "남", east: "동", west: "서", north: "북" }[e.side]}쪽 (${e.x},${e.y}) → ${e.meets}`).join(", ")}.`,
    `줄기 집 ${plan.doors.length}채: ${plan.doors.map((d) => `${d.house} 문 (${d.x},${d.y})`).join(", ")}. 문 앞 칸은 비워 두었다.`,
    `숲마을 타일셋에 나무 위 마을 칸(${3131}~${3310}: 데크 오토타일·밧줄 다리·줄기 집·사다리·요정 등불·깊은 숲)을 이식해 그렸다. 새 프로젝트와 기존 프로젝트 모두 불러올 때 이 칸이 생긴다.`,
    "사다리 아래 입구에서 모든 문 앞·출구까지 런타임 이동 규칙으로 닿는 것을 확인했다.",
    `공용 AI 문서 「${category.name}」에 조립 순서·번호·전체 배열·사용 타일 사전이 있다.`,
  ],
  limitations: "지형·마을 외관 참고 사례. 문 이동·NPC·이벤트는 포함하지 않는다. 자동 생성 프리셋이 아니다.",
};
fs.writeFileSync("src/project/elfTreetopPlaceReferences.ts", `// Generated by scripts/content/prepare-elf-treetop-regions.mjs from a canonical reload.
// The elf treetop village under 장소; snapshot in regionReferences/elf-treetop.json.
export const ELF_TREETOP_PLACE_REFERENCES = ${JSON.stringify([entry], null, 2)} as const;
`);
console.log(entry.id, { snapshotBytes: fs.statSync("src/project/regionReferences/elf-treetop.json").size });
