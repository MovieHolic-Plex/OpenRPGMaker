// Publish the RPG dungeons under 장소 from the reloaded canonical export. No host writes.
// Usage: node scripts/content/prepare-rpg-dungeons-regions.mjs output/evidence/rpg-dungeons/reloaded.json
import fs from "node:fs";
import assert from "node:assert/strict";
const [input] = process.argv.slice(2);
if (!input) throw Error("Usage: prepare-rpg-dungeons-regions.mjs reloaded-project.json");
const project = JSON.parse(fs.readFileSync(input));
const c = JSON.parse(fs.readFileSync("tiledata/rpg-dungeons/catalog.json"));
const proof = JSON.parse(fs.readFileSync("tiledata/rpg-dungeons/storage-proof.json"));
const guidance = JSON.parse(fs.readFileSync("src/assets/sharedRpgDungeonReferences.json")).easyrpg_chipset_dungeon;
const NATURAL = new Set(["cave", "mine", "ice", "lava", "sea", "lair"]);
const categoryName = (p) => guidance.find((k) => k.id === (p.series === "grand" ? "rpg-dungeons-grand-v1" : p.series === "sunken" ? "rpg-dungeons-sunken-temple-v2" : NATURAL.has(p.series) ? "rpg-dungeons-natural-v2" : "rpg-dungeons-built-v1")).name;
const SHEET = {
  oprn_dungeon_stone: "/assets/easyrpg-chipset-dungeon-transparent.png",
  oprn_dungeon_desert: "/assets/rpg-dungeons/desert-chipset.png",
  oprn_dungeon_sea: "/assets/rpg-dungeons/sea-chipset.png",
  oprn_dungeon_lair: "/assets/rpg-dungeons/lair-chipset.png",
  oprn_dungeon_cave: "/assets/rpg-dungeons/cave-chipset.png",
};
const entries = [], snapshotMaps = {}, snapshotTilesets = {};
for (const plan of c.plans) {
  const map = project.maps[plan.id];
  assert.deepEqual(map.lowerTiles, c.maps[plan.id].lowerTiles, plan.id);
  assert.deepEqual(map.upperTiles, c.maps[plan.id].upperTiles, plan.id);
  const tileset = project.tilesets[map.tilesetId];
  const exported = structuredClone(project);
  exported.meta.title = plan.name;
  exported.maps = { [map.id]: map };
  exported.mapTree = { mapId: map.id, children: [] };
  exported.startMapId = map.id;
  exported.startPos = { x: plan.entry[0], y: plan.entry[1] };
  exported.tilesets = { [tileset.id]: tileset };
  fs.writeFileSync(`public/assets/region-references/${plan.id}.oprn.json`, JSON.stringify(exported) + "\n");
  fs.copyFileSync(`tiledata/rpg-dungeons/images/${plan.id}.png`, `public/assets/region-references/${plan.id}.png`);
  snapshotMaps[map.id] = map;
  // readRegionReference only reads walkability/priority/terrain and the sheet identity.
  const { id, image, tileSize, tilesPerRow, count, passability, priority, terrain, tileGrafts } = tileset;
  snapshotTilesets[id] = { id, image, tileSize, tilesPerRow, count, passability, priority, terrain, ...(tileGrafts?.length ? { tileGrafts } : {}) };
  const exits = (plan.exits ?? []).map((e) => `(${e.at.join(",")}) → ${e.to}${e.arrive ? ` (${e.arrive.join(",")})` : ""}`);
  entries.push({
    id: `${plan.id}-${map.width}x${map.height}`,
    name: plan.name,
    kind: "completed-place",
    placeKind: NATURAL.has(plan.series) ? "natural" : "facility",
    revision: 1,
    x: 0,
    y: 0,
    width: map.width,
    height: map.height,
    tilesetId: map.tilesetId,
    preview: `/assets/region-references/${plan.id}.png`,
    tilesetPreview: SHEET[map.tilesetId],
    projectDownload: `/assets/region-references/${plan.id}.oprn.json`,
    sourceProjectId: proof.projectId,
    sourceMapId: map.id,
    snapshotProjectId: `oprn-place-${plan.id}-v1`,
    rules: [
      plan.note + ".",
      `입구 (${plan.entry.join(",")})에서 ${plan.targets.map((t) => "(" + t.join(",") + ")").join("·")}까지 런타임 이동 규칙으로 닿는 것을 확인했다.${plan.sealed ? " 닫힌 곳: " + plan.sealed + "." : ""}`,
      ...(exits.length ? [`출구 자리: ${exits.join(" · ")}. 이동 이벤트는 없다.`] : []),
      `공용 AI 문서 「${categoryName(plan)}」에 벽 문법·채움 규칙·놓은 소품 좌표·전체 배열·사용 타일 사전이 있다.`,
    ],
    limitations: "지형·배치 참고 사례. 이동 이벤트·적·함정 동작·레버/열쇠 이벤트는 포함하지 않는다. 자동 생성 프리셋이 아니다.",
  });
}
fs.writeFileSync("src/project/regionReferences/rpg-dungeons.json", JSON.stringify({ maps: snapshotMaps, tilesets: snapshotTilesets }) + "\n");
fs.writeFileSync("src/project/rpgDungeonPlaceReferences.ts", "// Generated by scripts/content/prepare-rpg-dungeons-regions.mjs from a canonical reload.\n// RPG dungeons (caves, mine, catacomb, waterway, temple, tower, demon castle, climate caves, pyramid, lair, the large sluice ruins) under 장소; snapshots in regionReferences/rpg-dungeons.json.\nexport const RPG_DUNGEON_PLACE_REFERENCES = " + JSON.stringify(entries, null, 2) + " as const;\n");
console.log({ places: entries.length, snapshotBytes: fs.statSync("src/project/regionReferences/rpg-dungeons.json").size });
