// Only this school's records are replaced, through the running host's API.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {connectHostBridge} from '../lib/hostBridgeClient.mjs';
const [host,out,basisDir]=process.argv.slice(2);
if(!host||!out||!basisDir)throw Error('Usage: <host URL> <private authoring output> <canonical source directory>');
const hash=v=>createHash('sha256').update(JSON.stringify(v)??'undefined').digest('hex');
const basis=JSON.parse(await readFile(`${basisDir}/source-proof.json`,'utf8'));
const originalText=await readFile(`${basisDir}/current-portable.json`,'utf8');
if(createHash('sha256').update(originalText).digest('hex')!==basis.portableSha256)throw Error('Canonical source receipt mismatch');
const original=JSON.parse(originalText);
const authored=JSON.parse(await readFile(`${out}/authored.json`,'utf8'));
const bridge=await connectHostBridge(host),rpc=bridge.call;
const status=await rpc('oprn:project.status');
if(status.projectId!==basis.projectId||status.projectDir!==basis.projectDir)throw Error('Canonical target changed');
let loaded=await rpc('oprn:project.load');
const current=JSON.parse(loaded.serialized),beforeSha=loaded.sha256;loaded=null;
const ids=[1,2,3,4].map(n=>'paw-school-floor-'+n),tsId='paw-school-four-composed',assetId='paw-school-four-atlas';
const check=(a,b,label)=>{if(hash(a)!==hash(b))throw Error('Concurrent edit: '+label);};
for(const id of [...ids,'paw_city'])check(current.maps[id],original.maps[id],id);
check(current.tilesets[tsId],original.tilesets[tsId],tsId);
for(const id of ids)check(current.spatialAuthoring.library.spaces[id+'-design'],original.spatialAuthoring.library.spaces[id+'-design'],id+'-design');
check(current.spatialAuthoring.library.places['paw-school-building-design'],original.spatialAuthoring.library.places['paw-school-building-design'],'school place');
const untouched=Object.fromEntries(Object.entries(current.maps).filter(([id])=>!ids.includes(id)&&id!=='paw_city').map(([id,m])=>[id,hash(m)]));
// This revision keeps the same map IDs/tree; broader replacements need their own merge.
check(authored.mapTree,original.mapTree,'authoring changed map tree');
await rpc('oprn:project.backup',{projectDir:status.projectDir});
const asset=authored.assets.uploaded[assetId],bytes=asset.dataUrl.split(',')[1];
const put=await rpc('oprn:assets.put',{projectDir:status.projectDir,bytes,mime:'image/png',extension:'png',originalName:asset.name,kind:asset.kind});
const storedAsset={...asset,ref:put.ref};delete storedAsset.dataUrl;
current.assets.uploaded[assetId]=storedAsset;current.tilesets[tsId]=authored.tilesets[tsId];
for(const id of ids){current.maps[id]=authored.maps[id];current.spatialAuthoring.library.spaces[id+'-design']=authored.spatialAuthoring.library.spaces[id+'-design'];}
current.maps.paw_city=authored.maps.paw_city;
current.spatialAuthoring.library.places['paw-school-building-design']=authored.spatialAuthoring.library.places['paw-school-building-design'];
const expected={maps:hash(current.maps),spatial:hash(current.spatialAuthoring),tileset:hash(current.tilesets[tsId]),mapTree:hash(current.mapTree)};
const saved=await rpc('oprn:project.save',{projectDir:status.projectDir,serialized:JSON.stringify(current),expectedSha:beforeSha});
if(saved.kind!=='saved')throw Error('Canonical CAS rejected: '+saved.kind);
loaded=await rpc('oprn:project.load');const after=JSON.parse(loaded.serialized);
if(hash(after.maps)!==expected.maps||hash(after.spatialAuthoring)!==expected.spatial||hash(after.tilesets[tsId])!==expected.tileset||hash(after.mapTree)!==expected.mapTree)throw Error('Canonical reload differs');
for(const[id,h]of Object.entries(untouched))if(hash(after.maps[id])!==h)throw Error('Unrelated map changed '+id);
if(!Buffer.from(await rpc('oprn:assets.read',{projectDir:status.projectDir,sha256:put.ref.sha256}),'base64').equals(Buffer.from(bytes,'base64')))throw Error('Atlas bytes differ');
await writeFile(`${out}/canonical-reloaded.json`,loaded.serialized);
const proof={projectId:status.projectId,projectDir:status.projectDir,host,revision:loaded.revision,sha256:loaded.sha256,reloadedThroughHost:true,unchangedOtherMaps:Object.keys(untouched).length,schoolMaps:ids.length,atlasBytesVerified:true,requests:bridge.requests};
await writeFile(`${out}/storage-proof.json`,JSON.stringify(proof,null,2));console.log(proof);
