// Publish the fantasy places under 장소 from the reloaded canonical export. No host writes.
// Usage: node scripts/content/prepare-rpg-places-regions.mjs output/evidence/rpg-places/reloaded.json
import fs from "node:fs";
import assert from "node:assert/strict";
const [input] = process.argv.slice(2);
if (!input) throw Error("Usage: prepare-rpg-places-regions.mjs reloaded-project.json");
const project = JSON.parse(fs.readFileSync(input));
const c = JSON.parse(fs.readFileSync("tiledata/rpg-places/catalog.json"));
const proof = JSON.parse(fs.readFileSync("tiledata/rpg-places/storage-proof.json"));
const references = JSON.parse(fs.readFileSync("src/assets/sharedRpgPlaceReferences.json"));
const PLACE_KIND = { exterior: "settlement" };
const SHEET = { tibo_interior_expanded: "/assets/tibo-interior/interior-expanded.png", easyrpg_chipset_dungeon: "/assets/easyrpg-chipset-dungeon-transparent.png" };
const entries = [], snapshotMaps = {}, snapshotTilesets = {};
for (const plan of c.plans) {
  const map = project.maps[plan.id];
  assert.deepEqual(map.lowerTiles, c.maps[plan.id].lowerTiles, plan.id);
  assert.deepEqual(map.upperTiles, c.maps[plan.id].upperTiles, plan.id);
  const tileset = project.tilesets[map.tilesetId];
  const exported = structuredClone(project);
  exported.meta.title = plan.name;
  exported.maps = { [map.id]: map };
  exported.mapTree = { mapId: map.id, children: [] };
  exported.startMapId = map.id;
  exported.startPos = { x: plan.entry[0], y: plan.entry[1] };
  exported.tilesets = { [tileset.id]: tileset };
  fs.writeFileSync(`public/assets/region-references/${plan.id}.oprn.json`, JSON.stringify(exported) + "\n");
  fs.copyFileSync(`tiledata/rpg-places/images/${plan.id}.png`, `public/assets/region-references/${plan.id}.png`);
  snapshotMaps[map.id] = map;
  // readRegionReference only reads walkability/priority/terrain and the sheet identity.
  const { id, image, tileSize, tilesPerRow, count, passability, priority, terrain, tileGrafts } = tileset;
  snapshotTilesets[id] = { id, image, tileSize, tilesPerRow, count, passability, priority, terrain, ...(tileGrafts?.length ? { tileGrafts } : {}) };
  const category = references[map.tilesetId];
  entries.push({
    id: `${plan.id}-${map.width}x${map.height}`,
    name: plan.name,
    kind: "completed-place",
    placeKind: PLACE_KIND[plan.series] ?? "facility",
    revision: 1,
    x: 0,
    y: 0,
    width: map.width,
    height: map.height,
    tilesetId: map.tilesetId,
    preview: `/assets/region-references/${plan.id}.png`,
    ...(SHEET[map.tilesetId] ? { tilesetPreview: SHEET[map.tilesetId] } : {}),
    projectDownload: `/assets/region-references/${plan.id}.oprn.json`,
    sourceProjectId: proof.projectId,
    sourceMapId: map.id,
    snapshotProjectId: `oprn-place-${plan.id}-v1`,
    rules: [
      plan.note + ".",
      `입구 (${plan.entry.join(",")})에서 ${plan.targets.map((t) => "(" + t.join(",") + ")").join("·")}까지 런타임 이동 규칙으로 닿는 것을 확인했다.`,
      `공용 AI 문서 「${category.name}」에 배치 규칙·놓은 소품 좌표·전체 배열·사용 타일 사전이 있다.`,
    ],
    limitations: "지형·배치 참고 사례. 문 이동·상인 NPC·상점 이벤트는 포함하지 않는다. 자동 생성 프리셋이 아니다.",
  });
}
fs.writeFileSync("src/project/regionReferences/fantasy-places.json", JSON.stringify({ maps: snapshotMaps, tilesets: snapshotTilesets }) + "\n");
fs.writeFileSync("src/project/fantasyPlaceReferences.ts", "// Generated by scripts/content/prepare-rpg-places-regions.mjs from a canonical reload.\n// Fantasy shops, castle rooms, demon castle, wizard tower and ruin under 장소; snapshots in regionReferences/fantasy-places.json.\nexport const FANTASY_PLACE_REFERENCES = " + JSON.stringify(entries, null, 2) + " as const;\n");
console.log({ places: entries.map((e) => e.id), snapshotBytes: fs.statSync("src/project/regionReferences/fantasy-places.json").size });
