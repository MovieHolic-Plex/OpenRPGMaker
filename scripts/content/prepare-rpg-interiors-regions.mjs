// Publish the RPG interiors under 장소 from the reloaded canonical export. No host writes.
// Usage: node scripts/content/prepare-rpg-interiors-regions.mjs output/evidence/rpg-interiors/reloaded.json
import fs from "node:fs";
import assert from "node:assert/strict";
const [input] = process.argv.slice(2);
if (!input) throw Error("Usage: prepare-rpg-interiors-regions.mjs reloaded-project.json");
const project = JSON.parse(fs.readFileSync(input));
const c = JSON.parse(fs.readFileSync("tiledata/rpg-interiors/catalog.json"));
const proof = JSON.parse(fs.readFileSync("tiledata/rpg-interiors/storage-proof.json"));
const shipped = JSON.parse(fs.readFileSync("src/assets/sharedRpgInteriorReferences.json"));
const CATEGORY = { "inn-homes": "rpg-interiors-inn-homes-v1", civic: "rpg-interiors-civic-v1", castle: "rpg-interiors-castle-v1", leisure: "rpg-interiors-leisure-v1", ship: "rpg-interiors-ship-v1", climate: "rpg-interiors-climate-v1", staples: "rpg-interiors-staples-v1", sewer: "rpg-interiors-sewer-prison-v1" };
const SHEET = { tibo_interior_expanded: "/assets/tibo-interior/interior-expanded.png", easyrpg_chipset_ship: "/assets/easyrpg-chipset-ship-transparent.png", oprn_dungeon_stone: "/assets/easyrpg-chipset-dungeon-transparent.png" };
const entries = [], snapshotMaps = {}, snapshotTilesets = {};
for (const plan of c.plans) {
  const map = project.maps[plan.id];
  assert.deepEqual(map.lowerTiles, c.maps[plan.id].lowerTiles, plan.id);
  assert.deepEqual(map.upperTiles, c.maps[plan.id].upperTiles, plan.id);
  const tileset = project.tilesets[map.tilesetId];
  const exported = structuredClone(project);
  exported.meta.title = plan.name;
  exported.maps = { [map.id]: map };
  exported.mapTree = { mapId: map.id, children: [] };
  exported.startMapId = map.id;
  exported.startPos = { x: plan.entry[0], y: plan.entry[1] };
  exported.tilesets = { [tileset.id]: tileset };
  fs.writeFileSync(`public/assets/region-references/${plan.id}.oprn.json`, JSON.stringify(exported) + "\n");
  fs.copyFileSync(`tiledata/rpg-interiors/images/${plan.id}.png`, `public/assets/region-references/${plan.id}.png`);
  snapshotMaps[map.id] = map;
  // readRegionReference only reads walkability/priority/terrain and the sheet identity.
  const { id, image, tileSize, tilesPerRow, count, passability, priority, terrain, tileGrafts, transparentColor } = tileset;
  snapshotTilesets[id] = { id, image, tileSize, tilesPerRow, count, passability, priority, terrain, ...(tileGrafts?.length ? { tileGrafts } : {}), ...(transparentColor ? { transparentColor } : {}) };
  const category = shipped.find((s) => s.category.id === CATEGORY[plan.group]).category;
  entries.push({
    id: `${plan.id}-${map.width}x${map.height}`,
    name: plan.name,
    kind: "completed-place",
    placeKind: "facility",
    revision: 1,
    x: 0,
    y: 0,
    width: map.width,
    height: map.height,
    tilesetId: map.tilesetId,
    preview: `/assets/region-references/${plan.id}.png`,
    tilesetPreview: SHEET[map.tilesetId],
    projectDownload: `/assets/region-references/${plan.id}.oprn.json`,
    sourceProjectId: proof.projectId,
    sourceMapId: map.id,
    snapshotProjectId: `oprn-place-${plan.id}-v1`,
    rules: [
      plan.use + ".",
      plan.note + ".",
      `입구 (${plan.entry.join(",")})에서 ${plan.targets.map((t) => "(" + t.join(",") + ")").join("·")}까지 런타임 이동 규칙으로 닿고, 입구에서 못 가는 맨바닥이 없음을 확인했다.`,
      ...(plan.replaces ? [`기후 마을 집 안으로 숲마을 실내 「${c.plans.find((q) => q.id === plan.replaces)?.name ?? (plan.replaces === "fantasy-smithy" ? "대장간" : plan.replaces)}」 대신 쓴다.`] : []),
      `공용 AI 문서 「${category.name}」에 배치 규칙·놓은 소품 좌표·전체 배열·사용 타일 사전이 있다.`,
    ],
    limitations: "지형·배치 참고 사례. 문 이동·NPC·상점·대사 이벤트는 포함하지 않는다. 자동 생성 프리셋이 아니다.",
  });
}
fs.writeFileSync("src/project/regionReferences/rpg-interiors.json", JSON.stringify({ maps: snapshotMaps, tilesets: snapshotTilesets }) + "\n");
fs.writeFileSync("src/project/rpgInteriorPlaceReferences.ts", "// Generated by scripts/content/prepare-rpg-interiors-regions.mjs from a canonical reload.\n// Inn, homes, church, guild, magic trades, library, classroom, castle rooms, ship below decks, arena, casino, auction\n// the desert, snow and volcano houses, lighthouse, barn, clinic and sewer prison\n// under 장소; snapshots in regionReferences/rpg-interiors.json.\nexport const RPG_INTERIOR_PLACE_REFERENCES = " + JSON.stringify(entries, null, 2) + " as const;\n");
console.log({ places: entries.length, snapshotBytes: fs.statSync("src/project/regionReferences/rpg-interiors.json").size });
