#!/usr/bin/env node
// Generates src/editor/script/tsLibSources.generated.ts — the ES2022 TypeScript lib .d.ts files the script
// compiler type-checks against, inlined as strings so the editor (Vite), the headless tools (Bun, including the
// compiled assistant worker that has no node_modules) and tests all load them the same way.
// Re-run after changing the typescript5 version or the script target:  node scripts/content/generate-script-ts-libs.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const packageJson = require.resolve("typescript5/package.json");
const version = JSON.parse(readFileSync(packageJson, "utf8")).version;
const libDir = join(dirname(packageJson), "lib");
const entry = "lib.es2022.d.ts";

const seen = [];
const stack = [entry];
while (stack.length) {
  const file = stack.pop();
  if (seen.includes(file)) continue;
  seen.push(file);
  const text = readFileSync(join(libDir, file), "utf8");
  for (const match of text.matchAll(/\/\/\/ <reference lib="([^"]+)" \/>/gu)) stack.push(`lib.${match[1]}.d.ts`);
}
seen.sort();

const lines = [
  "// GENERATED by scripts/content/generate-script-ts-libs.mjs — do not edit.",
  `// TypeScript ${version} lib files (reference closure of ${entry}). Copyright Microsoft Corporation, Apache-2.0.`,
  "/* eslint-disable */",
  `export const SCRIPT_TS_VERSION = ${JSON.stringify(version)};`,
  `export const SCRIPT_TS_LIB_ENTRY = ${JSON.stringify(entry)};`,
  "export const SCRIPT_TS_LIB_SOURCES: Readonly<Record<string, string>> = {",
  ...seen.map((file) => `  ${JSON.stringify(file)}: ${JSON.stringify(readFileSync(join(libDir, file), "utf8"))},`),
  "};",
  "",
];
const out = "src/editor/script/tsLibSources.generated.ts";
writeFileSync(out, lines.join("\n"));
console.log(`${out}: ${seen.length} files, TypeScript ${version}`);
