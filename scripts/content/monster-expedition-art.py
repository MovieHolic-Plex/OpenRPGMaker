def mix(color, target, amount):
    """Authoring palette interpolation only; pixels never interpolate."""
    left = tuple(int(color[i:i+2], 16) for i in (1, 3, 5))
    right = tuple(int(target[i:i+2], 16) for i in (1, 3, 5))
    return '#'+''.join(f'{round(a+(b-a)*amount):02x}' for a,b in zip(left,right))


class Art:
    """Rasterize the existing 80-unit design grid directly into native 64px.

    Stage proportions are applied to coordinates BEFORE drawing; there is no
    sprite resize, filtered compositing, palette tint pass or antialiasing.
    Outlines are one native pixel, including smaller species. The drawings below
    own silhouette, joint, material and evolution details independently.
    """
    def __init__(self, palette, rear=False, stage=3):
        self.im = Image.new('RGBA', (64, 64))
        self.d = ImageDraw.Draw(self.im)
        self.c, self.h, self.s, self.a = palette
        self.ink = mix(self.s, '#302b40', .48)
        self.al = mix(self.a, WHITE, .48)
        self.ad = mix(self.a, self.s, .48)
        self.rear, self.stage = rear, stage
        self.factor = .77 * [0.83, 0.93, 1][stage-1]

    def xy(self, point):
        x,y = point
        return round(32+(x-40)*self.factor), round(60+(y-76)*self.factor)

    def color(self, color):
        return self.ink if color == INK else color

    def _polygon(self, pts, fill):
        self.d.polygon([self.xy(p) for p in pts], fill=self.color(fill))

    def volume(self, pts, fill, head=False):
        """Three flat authored tone regions clipped to the native polygon."""
        native = [self.xy(p) for p in pts]
        x0,y0,x1,y1 = min(x for x,y in native),min(y for x,y in native),max(x for x,y in native),max(y for x,y in native)
        w,h = x1-x0,y1-y0
        mask = Image.new('1', self.im.size)
        ImageDraw.Draw(mask).polygon(native, fill=1)
        tones = Image.new('RGBA', self.im.size)
        d = ImageDraw.Draw(tones)
        d.polygon([(x0,y0),(x1,y0),(x1,y1),(x0,y1)], fill=fill)
        # Light falls from upper left; the highlight does not cover the entire face.
        d.polygon([(x0,y0),(x0+w*3//4,y0),(x0+w//2,y0+h//3),(x0+w//4,y0+h*2//3),(x0,y0+h//2)], fill=self.h)
        d.polygon([(x1,y0+h//3),(x1,y1),(x0+w//3,y1),(x0+w//2,y1-h//5),(x1-w//5,y0+h//2)], fill=self.s)
        if head:
            d.line([(x0+w//4,y0+1),(x0+w//2,y0+1)], fill=self.h)
        self.im.paste(tones,(0,0),mask)

    def p(self, pts, fill=None, outline=True):
        if fill is None or fill == self.c:
            self.volume(pts,self.c)
        else:
            self._polygon(pts,fill)
        if outline:
            self.l(pts+[pts[0]],self.ink)

    def e(self, box, fill=None, outline=True):
        first,last = self.xy(box[:2]),self.xy(box[2:])
        self.d.ellipse((*first,*last), fill=self.color(fill or self.c), outline=self.ink if outline else None)

    def r(self, box, fill=None):
        first,last = self.xy(box[:2]),self.xy(box[2:])
        self.d.rectangle((*first,*last), fill=self.color(fill or self.c))

    def l(self, pts, fill=None, width=1):
        self.d.line([self.xy(p) for p in pts], fill=self.color(fill or self.ink), width=max(1,round(width*self.factor)))

    def eye(self, x, y, size=3):
        if self.rear:
            return
        # Young eyes have a light cheek-side edge; mature lids angle inward.
        self.p([(x-1,y),(x+size,y-1),(x+size+1,y+size),(x,y+size+1)],WHITE,False)
        self.r((x+1,y,x+size,y+size),self.ink)
        self.r((x+1,y,x+1,y),WHITE)
        if self.stage>=2:
            self.l([(x-1,y-1),(x+size,y)],self.ink)

    def gem(self, x, y, color=None):
        self.p([(x,y-4),(x+3,y),(x,y+4),(x-3,y)],color or self.a)
        self.p([(x,y),(x+2,y),(x,y+3)],self.ad,False)
        self.l([(x-1,y-2),(x+1,y-1)],WHITE)

    def leaf(self, x, y, dx, dy):
        self.p([(x,y),(x+dx//2-4,y+dy//2-2),(x+dx,y+dy),(x+dx//2+4,y+dy//2+2)],self.a)
        self.p([(x,y),(x+dx,y+dy),(x+dx//2+4,y+dy//2+2)],self.ad,False)
        self.l([(x,y),(x+dx,y+dy)],self.s)
        self.l([(x+dx//3,y+dy//3-1),(x+dx*2//3,y+dy*2//3-1)],self.al)

    def foot(self, x, y, w=10):
        self.p([(x,y-5),(x+w-3,y-5),(x+w,y),(x-2,y+1)],self.s)
        self.p([(x,y-4),(x+w-4,y-4),(x+w-1,y-1),(x,y-1)],self.c,False)
        for toe in [x+2,x+w-4]: self.l([(toe,y-1),(toe+1,y+1)],self.h)

    def face(self, pts):
        self.volume(pts,self.c,True)
        self.l(pts+[pts[0]],self.ink)

    def joint(self, x, y, radius=3):
        self.e((x-radius,y-radius,x+radius,y+radius),self.s)
        self.l([(x-radius+1,y-1),(x,y-2)],self.h)

    def feather(self, pts):
        self.p(pts,self.h)
        self.l([pts[0],pts[-2]],self.s)

    def tuft(self, x, y, wide=8, color=None):
        self.p([(x,y),(x+2,y+4),(x+wide//2,y+2),(x+wide,y+5),(x+wide-2,y-1)],color or self.h,False)

    def align(self):
        """Integer translation only: stable battle/party ground baseline."""
        box=self.im.getbbox()
        if box:
            moved=Image.new('RGBA',self.im.size)
            moved.paste(self.im,(0,62-box[3]))
            self.im=moved
            self.d=ImageDraw.Draw(self.im)


