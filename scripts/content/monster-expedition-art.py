def sprite_record(painter,slug,side,size,art):
    path=OUT/f'{slug}-{side}.png'
    painter.im.save(path,optimize=True)
    raw=path.read_bytes()
    resource_id=f'mx_art_{slug}_{side}'
    art[resource_id]={
        'id':resource_id,'name':f'{slug} {side}','kind':'monster',
        'dataUrl':'data:image/png;base64,'+base64.b64encode(raw).decode(),
        'meta':{'width':size,'height':size},
    }
    colors=sorted({f'#{r:02x}{g:02x}{b:02x}' for count,(r,g,b,alpha) in painter.im.getcolors(4096) if alpha})
    return {'resourceId':resource_id,'file':path.name,'sha256':hashlib.sha256(raw).hexdigest(),
            'bytes':len(raw),'bbox':painter.im.getbbox(),'dimensions':[size,size],
            'opaquePalette':colors,'opaqueColors':len(colors)}


def review_grid(catalog,indices,path,scale=3,columns=3):
    """Enlargement is exclusively for review; emitted resources stay native."""
    rows=(len(indices)+columns-1)//columns
    cw,ch=64*scale*2+24,64*scale+38
    sheet=Image.new('RGB',(cw*columns,ch*rows),'#edf0e4')
    d=ImageDraw.Draw(sheet)
    for cell,index in enumerate(indices):
        entry=catalog[index];x=cell%columns*cw;y=cell//columns*ch
        d.text((x+8,y+6),entry['id'].replace('mx_species_',''),fill=INK)
        for j,side in enumerate(['front','back']):
            im=Image.open(OUT/entry[side]['file'])
            if scale>1:im=im.resize((64*scale,64*scale),Image.Resampling.NEAREST)
            sheet.paste(im,(x+8+j*(64*scale+4),y+26),im)
    sheet.save(path,optimize=True)


