// Publish read-only regions from an already saved/reloaded canonical export. No host writes.
import fs from "node:fs";
import assert from "node:assert/strict";
import { catalog, validateVillageStudy } from "./validate-diverse-villages.mjs";
const [input, projectId] = process.argv.slice(2);
if (!input || !projectId) throw Error("Usage: prepare-diverse-village-regions.mjs reloaded-project.json canonical-project-id");
const project = JSON.parse(fs.readFileSync(input));
const references = JSON.parse(fs.readFileSync("src/assets/sharedDiverseVillageReferences.json"));
const entries = [];
for (const plan of catalog.plans) {
  const result = await validateVillageStudy(project, plan.id);
  assert(result.valid, JSON.stringify(result));
  const map = project.maps[plan.id];
  const tileset = structuredClone(project.tilesets[map.tilesetId]);
  delete tileset.referenceDocuments;
  fs.writeFileSync(`src/project/regionReferences/${plan.id}.json`, JSON.stringify({ map, tileset }) + "\n");
  const exported = structuredClone(project);
  exported.meta.title = plan.name;
  exported.maps = { [map.id]: map };
  exported.mapTree = { mapId: map.id, children: [] };
  exported.startMapId = map.id;
  exported.startPos = plan.start;
  exported.tilesets = { [tileset.id]: { ...tileset, referenceDocuments: references } };
  fs.writeFileSync(`public/assets/region-references/${plan.id}.oprn.json`, JSON.stringify(exported) + "\n");
  fs.copyFileSync(`tiledata/forest-villages/diverse/images/${plan.id}.png`, `public/assets/region-references/${plan.id}.png`);
  entries.push({
    id: `${plan.id}-${map.width}x${map.height}`,
    name: plan.name,
    kind: "completed-map",
    regionKind: "settlement",
    revision: 3,
    width: map.width,
    height: map.height,
    tilesetId: map.tilesetId,
    preview: `/assets/region-references/${plan.id}.png`,
    projectDownload: `/assets/region-references/${plan.id}.oprn.json`,
    sourceProjectId: projectId,
    sourceMapId: map.id,
    snapshotProjectId: `oprn-region-${plan.id}-v3`,
    rules: [
      plan.note + ".",
      `집 ${plan.houses.length}채의 문 앞과 계단 ${plan.stairs.length}곳을 시작점에서 연결한다.`,
      "숲마을 · 거리별 잔디 기반. 검수한 집과 3행 숲 몸통을 재사용하고 지형·길·집 원점은 새로 설계했다.",
      "큰 폭포 아래 마을처럼 윗선·반복 암벽 면·밑단을 연결하고 좌우 사선을 구분한다.",
      "기본 바닥240을 유지하고 색 맞춤504/505 사선과498/499/528/529 모서리를 사용한다. 다운로드의 tileGrafts와 통행 정보를 함께 사용한다.",
      "공용 AI 문서 「다양한 마을 · 산촌·절벽·포구 (잔디 경계 개정3)」에 원본 좌표·모든 배열·조립 순서·정상/오류 비교와 검증 명령이 있다."
    ],
    limitations: "새로 저작한 외관·타일 통행 참고 사례. 실내·NPC·문 전이 이벤트는 포함하지 않는다. 자동 생성 프리셋이 아니다."
  });
}
fs.writeFileSync("src/project/diverseVillageReferences.ts", "// Generated by scripts/content/prepare-diverse-village-regions.mjs from a canonical reload.\nexport const DIVERSE_VILLAGE_REGIONS = " + JSON.stringify(entries, null, 2) + " as const;\n");
console.log({ regions: entries.map((e) => e.id), sourceProjectId: projectId });
