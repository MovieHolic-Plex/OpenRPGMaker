// Publish the climate villages under 장소 from the reloaded canonical export. No host writes.
// Usage: node scripts/content/prepare-climate-regions.mjs output/evidence/climate-villages/reloaded.json
import fs from "node:fs";
import assert from "node:assert/strict";
const [input] = process.argv.slice(2);
if (!input) throw Error("Usage: prepare-climate-regions.mjs reloaded-project.json");
const project = JSON.parse(fs.readFileSync(input));
const c = JSON.parse(fs.readFileSync("tiledata/climate-villages/catalog.json"));
const proof = JSON.parse(fs.readFileSync("tiledata/climate-villages/storage-proof.json"));
const references = JSON.parse(fs.readFileSync("src/assets/sharedClimateVillageReferences.json"));
const SHEET = Object.fromEntries(["snow", "volcano", "desert", "autumn"].map((k) => [`forest_harmony_${k}`, `/assets/climate-villages/${k}-chipset.png`]));
const entries = [], snapshotMaps = {}, snapshotTilesets = {};
for (const plan of c.plans) {
  const map = project.maps[plan.id];
  assert.deepEqual(map.lowerTiles, c.maps[plan.id].lowerTiles, plan.id);
  assert.deepEqual(map.upperTiles, c.maps[plan.id].upperTiles, plan.id);
  const tileset = project.tilesets[map.tilesetId];
  const exported = structuredClone(project);
  exported.meta.title = plan.name;
  exported.maps = { [map.id]: map };
  exported.mapTree = { mapId: map.id, children: [] };
  exported.startMapId = map.id;
  exported.startPos = { x: plan.entry[0], y: plan.entry[1] };
  exported.tilesets = { [tileset.id]: tileset };
  fs.writeFileSync(`public/assets/region-references/${plan.id}.oprn.json`, JSON.stringify(exported) + "\n");
  fs.copyFileSync(`tiledata/climate-villages/images/${plan.id}.png`, `public/assets/region-references/${plan.id}.png`);
  snapshotMaps[map.id] = map;
  // readRegionReference only reads walkability/priority/terrain and the sheet identity.
  const { id, image, tileSize, tilesPerRow, count, passability, priority, terrain } = tileset;
  snapshotTilesets[id] = { id, image, tileSize, tilesPerRow, count, passability, priority, terrain };
  const category = references[map.tilesetId];
  entries.push({
    id: `${plan.id}-${map.width}x${map.height}`,
    name: plan.name,
    kind: "completed-place",
    placeKind: "settlement",
    revision: 2,
    x: 0,
    y: 0,
    width: map.width,
    height: map.height,
    tilesetId: map.tilesetId,
    preview: `/assets/region-references/${plan.id}.png`,
    tilesetPreview: SHEET[map.tilesetId],
    projectDownload: `/assets/region-references/${plan.id}.oprn.json`,
    sourceProjectId: proof.projectId,
    sourceMapId: map.id,
    snapshotProjectId: `oprn-place-${plan.id}-v1`,
    rules: [
      plan.note + ".",
      `숲마을 「${plan.from}」과 칸 번호가 같은 기후 시트(${map.tilesetId})에 그렸다. 기후 편집: ${[...new Set(plan.edits.map((e) => e.kind).filter((k) => k !== "desert-plant"))].join(", ") || "없음(시트만)"}.`,
      `입구 (${plan.entry.join(",")})에서 집 문 앞 ${plan.houses.length}곳${plan.freeze ? "과 얼음판" : ""}까지 런타임 이동 규칙으로 닿는 것을 확인했다.`,
      `공용 AI 문서 「${category.name}」에 기후 규칙·전체 배열·사용 타일 사전이 있다.`,
    ],
    limitations: "지형·배치 참고 사례. 문 이동·NPC·이벤트는 포함하지 않는다. 자동 생성 프리셋이 아니다.",
  });
}
fs.writeFileSync("src/project/regionReferences/climate-villages.json", JSON.stringify({ maps: snapshotMaps, tilesets: snapshotTilesets }) + "\n");
fs.writeFileSync("src/project/climateVillagePlaceReferences.ts", "// Generated by scripts/content/prepare-climate-regions.mjs from a canonical reload.\n// Snow and volcano villages under 장소; snapshots in regionReferences/climate-villages.json.\nexport const CLIMATE_VILLAGE_PLACE_REFERENCES = " + JSON.stringify(entries, null, 2) + " as const;\n");
console.log({ places: entries.map((e) => e.id), snapshotBytes: fs.statSync("src/project/regionReferences/climate-villages.json").size });
