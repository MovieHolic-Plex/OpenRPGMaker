"""첫사랑 옥상 배경 — 밤 도시 스카이라인 480x270 (코드 손 도트, 외부 그림 없음).

실행: python3 scripts/content/first-love/skyline.py  → /tmp/flfix/skyline.png 와
src/project/flagship/firstLoveSkylineAsset.ts(data URL) 를 쓴다.
"""
import base64, random, struct, zlib, sys, os

W, H = 480, 270
rnd = random.Random(1017)
px = [[(0, 0, 0)] * W for _ in range(H)]

def lerp(a, b, t):
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))

# 하늘: 위 남색 → 아래 보랏빛 도시 불빛. 8단 계단식 그라디언트(도트 느낌).
TOP, MID, BOT = (10, 14, 38), (28, 28, 66), (74, 52, 98)
BANDS = 14
for y in range(H):
    t = y / (H - 1)
    band = min(BANDS - 1, int(t * BANDS)) / (BANDS - 1)
    c = lerp(TOP, MID, band * 2) if band < 0.5 else lerp(MID, BOT, (band - 0.5) * 2)
    for x in range(W):
        px[y][x] = c

# 별
for _ in range(95):
    x, y = rnd.randrange(W), rnd.randrange(0, 150)
    v = rnd.choice([(150, 154, 190), (200, 204, 230), (110, 114, 160)])
    px[y][x] = v
    if rnd.random() < 0.12 and 0 < x < W - 1:
        px[y][x - 1] = px[y][x + 1] = lerp(px[y][x - 1], v, 0.45)

# 달(오른쪽 위) — 3단 후광 + 본체 + 크레이터
def disc(cx, cy, r, col):
    for y in range(cy - r, cy + r + 1):
        for x in range(cx - r, cx + r + 1):
            if (x - cx) ** 2 + (y - cy) ** 2 <= r * r and 0 <= x < W and 0 <= y < H:
                px[y][x] = col
disc(396, 44, 17, lerp(px[44][396], (96, 96, 150), 0.28))
disc(396, 44, 13, lerp(px[44][396], (150, 150, 196), 0.5))
disc(396, 44, 10, (232, 228, 210))
disc(393, 41, 2, (208, 204, 188)); disc(399, 47, 2, (212, 208, 192)); disc(400, 40, 1, (208, 204, 188))

# 스카이라인 3겹: 먼 것은 보랏빛에 묻히고, 가까운 것은 어둡다. 창은 따뜻한 불빛 몇 개만.
def layer(base_col, win_col, win_density, hmin, hmax, wmin, wmax, ground, edge_boost):
    x = -4
    while x < W:
        bw = rnd.randrange(wmin, wmax)
        # 가장자리(옥상 방 양옆으로 보이는 곳)는 더 높게 — 방 뒤로 가려지는 가운데는 낮아도 된다.
        mid = abs((x + bw / 2) - W / 2) / (W / 2)
        bh = rnd.randrange(hmin, hmax) + int(mid * edge_boost)
        top = ground - bh
        for yy in range(max(top, 0), H):
            for xx in range(max(x, 0), min(x + bw, W)):
                px[yy][xx] = base_col
        # 옥상 설비: 안테나·물탱크 실루엣
        r = rnd.random()
        if r < 0.35 and 0 <= x + bw // 2 < W:
            ax = x + bw // 2
            for yy in range(max(top - 12, 0), top):
                px[yy][ax] = base_col
            if top - 12 >= 0:
                px[top - 12][ax] = (210, 70, 70)  # 항공장애등
        elif r < 0.55:
            for yy in range(max(top - 4, 0), top):
                for xx in range(max(x + 2, 0), min(x + 2 + bw // 3, W)):
                    px[yy][xx] = base_col
        # 창
        for wy in range(top + 4, H - 2, 6):
            for wx in range(x + 3, x + bw - 3, 5):
                if 0 <= wx < W - 1 and rnd.random() < win_density:
                    px[wy][wx] = win_col
                    px[wy][wx + 1] = win_col
                    px[wy + 1][wx] = win_col
                    px[wy + 1][wx + 1] = win_col
        x += bw + rnd.randrange(0, 3)

layer((54, 44, 88), (150, 120, 120), 0.10, 36, 74, 22, 44, 214, 56)
layer((36, 30, 66), (214, 170, 96), 0.18, 30, 66, 26, 52, 236, 70)
layer((20, 18, 40), (246, 204, 120), 0.22, 22, 52, 30, 60, 262, 84)

# PNG 인코딩(표준 라이브러리만)
raw = b"".join(b"\x00" + b"".join(bytes(p) for p in row) for row in px)
def chunk(t, d):
    c = struct.pack(">I", len(d)) + t + d
    return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
os.makedirs("/tmp/flfix", exist_ok=True)
open("/tmp/flfix/skyline.png", "wb").write(png)
b64 = base64.b64encode(png).decode()
out = os.path.join(os.path.dirname(__file__), "../../../src/project/flagship/firstLoveSkylineAsset.ts")
open(out, "w").write(
    "// Auto-generated by scripts/content/first-love/skyline.py — 옥상 밤 도시 스카이라인(480x270, 코드 손 도트).\n"
    "export const FIRST_LOVE_SKYLINE_ID = \"first-love-skyline-night\" as const;\n"
    f"export const FIRST_LOVE_SKYLINE_DATA_URL = \"data:image/png;base64,{b64}\";\n")
print(len(png), "bytes png")
