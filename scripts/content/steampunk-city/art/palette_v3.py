def hexrgb(h):
    h = h.lstrip('#'); return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


ALL = {hexrgb(c) for t in RAMPS.values() for c in t}
_REMAP_RGB = {role: {hexrgb(a): hexrgb(b) for a, b in t.items()} for role, t in REMAP.items()}


def role_of(group, id_):
    """바닥 묶음과 실내 바닥 넷은 GROUND, 그 밖은 STRUCTURE(+ACCENT)."""
    return 'ground' if group == 'terrain' or id_ in GROUND_INTERIOR else 'structure'


def remap(img, role):
    """옛 팔레트로 그린 RGBA → v3 (표에 없는 색은 KeyError — 옛 팔레트 밖 색이 있다는 뜻)."""
    a = np.array(img.convert('RGBA')); t = _REMAP_RGB[role]
    for y in range(a.shape[0]):
        for x in range(a.shape[1]):
            if a[y, x, 3]: a[y, x, :3] = t[tuple(int(v) for v in a[y, x, :3])]
    return Image.fromarray(a, 'RGBA')


def _oklab(rgb):
    c = np.asarray(rgb, float) / 255.0
    c = np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)
    l = 0.4122214708 * c[..., 0] + 0.5363325363 * c[..., 1] + 0.0514459929 * c[..., 2]
    m = 0.2119034982 * c[..., 0] + 0.6806995451 * c[..., 1] + 0.1073969566 * c[..., 2]
    s = 0.0883024619 * c[..., 0] + 0.2817188376 * c[..., 1] + 0.6299787005 * c[..., 2]
    l, m, s = np.cbrt(l), np.cbrt(m), np.cbrt(s)
    return np.stack([0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s, 1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s, 0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s], -1)


def snap(img, role, extra=()):
    """아무 RGBA → 그 역할 램프(+extra 램프)의 가장 가까운 색(OKLab, 디더링 없음). 새 그림을 들일 때 쓴다."""
    cols = sorted({hexrgb(c) for t in ROLES[role].values() for c in t} | {hexrgb(c) for r in extra for c in RAMPS[r]})
    lab = _oklab(np.array(cols)); a = np.array(img.convert('RGBA')); cache = {}
    for y in range(a.shape[0]):
        for x in range(a.shape[1]):
            if a[y, x, 3] < 128: a[y, x] = 0; continue
            k = tuple(int(v) for v in a[y, x, :3])
            if k not in cache: cache[k] = cols[int(((lab - _oklab(np.array(k))) ** 2).sum(-1).argmin())]
            a[y, x, :3] = cache[k]; a[y, x, 3] = 255
    return Image.fromarray(a, 'RGBA')


def check_palette(img):
    """RGBA 그림에서 v3 밖 불투명 색 목록(빈 목록이면 통과). 반투명 화소도 위반."""
    a = np.asarray(img.convert('RGBA')); bad = set()
    for px in a.reshape(-1, 4):
        if px[3] == 0: continue
        if px[3] != 255: bad.add(('alpha', int(px[3]))); continue
        c = (int(px[0]), int(px[1]), int(px[2]))
        if c not in ALL: bad.add(c)
    return sorted(bad, key=str)
