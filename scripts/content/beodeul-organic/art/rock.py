def step(rows, y, x0, x1):
    """raise the bottom rim 1px over x0..x1: row y becomes shadow there, row y-1 becomes rim."""
    g = [list(r) for r in rows]
    for x in range(x0, x1 + 1):
        if g[y][x] not in ".sS": g[y][x] = "S"
        if g[y-1][x] not in ".sS": g[y-1][x] = "1"
    return ["".join(r) for r in g]
