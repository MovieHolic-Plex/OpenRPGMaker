def build(mask, seed, top, cracks=(), dx=2, sr=2, ox=0):
    m = [("."*ox + r)[:len(r)] for r in mask] if ox else mask
    return rows(shadow(shade(m, seed, top, cracks=cracks), dx, sr))

def pebbles():
    W = H = 16
    g = [["."]*W for _ in range(H)]
    def stone(x, y, pat):
        for dy, r in enumerate(pat):
            for dx, c in enumerate(r):
                if c != ".": g[y+dy][x+dx] = c
    stone(1, 6, ["..ooo.", ".ohlno", "olnmdo", "omddko", ".oooo."])
    stone(9, 5, [".oooo.", "ohhlno", "olnmmo", "omdkko", ".oooo."])
    stone(5, 11, [".ooo", "olno", "omko", ".oo."])
    stone(11, 11, [".oo.", "olmo", ".oo."])
    for x, y in ((3,11),(4,11),(5,11),(11,10),(12,10),(13,10),(7,15),(8,14),(13,14),(14,13)):
        if g[y][x] == ".": g[y][x] = "s"
    return ["".join(r) for r in g]

