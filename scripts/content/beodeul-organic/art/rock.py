def reprofile(rows, prof):
    """prof: {x: bottom y} hand-chosen per column; rim '1' at bottom, '2' above, S/s pool under."""
    g = [list(r) for r in rows]; H = len(g)
    for x, by in prof.items():
        top = min(y for y in range(H) if g[y][x] not in ".sS")
        for y in range(H):
            if y > by: g[y][x] = "."
            elif y >= top and g[y][x] in ".sS": g[y][x] = "2"
        g[by][x] = "1"
        if g[by-1][x] in "345": g[by-1][x] = "2"
        if by + 1 < H: g[by+1][x] = "S"
        if by + 2 < H and 6 < x < 28: g[by+2][x] = "s"
    return ["".join(r) for r in g]
