def facet(rows, marks):
    g = [list(r) for r in rows]
    for x, y, pat in marks:
        for dy, pr in enumerate(pat):
            for dx, c in enumerate(pr):
                if c != "." and g[y+dy][x+dx] not in ".sS": g[y+dy][x+dx] = c
    return ["".join(r) for r in g]

