def rebase(rows, cut):
    """cut: per-column digit string, pixels to remove from the bottom of the body (hand-chosen bumps).
    The new lowest body pixel becomes rim tone 1; freed pixels become ground shadow."""
    g = [list(r) for r in rows]; H = len(g)
    for x, c in enumerate(cut):
        n = int(c) if c.isdigit() else 0
        ys = [y for y in range(H) if g[y][x] not in ".sS"]
        if not ys or n == 0: continue
        b = ys[-1]
        for k in range(n):
            if b - k > ys[0] + 2: g[b - k][x] = "S" if k == 0 else "s"
        nb = b - n
        if nb > ys[0] + 2: g[nb][x] = "1"
    return ["".join(r) for r in g]

