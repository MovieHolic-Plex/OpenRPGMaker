def check_palette(img):
    """RGBA 그림에서 팔레트 밖 불투명 색 목록(빈 목록이면 통과). 반투명 화소도 위반."""
    import numpy as np
    a = np.asarray(img.convert('RGBA'))
    bad = set()
    for px in a.reshape(-1, 4):
        if px[3] == 0: continue
        if px[3] != 255: bad.add(('alpha', int(px[3]))); continue
        c = (int(px[0]), int(px[1]), int(px[2]))
        if c not in ALL: bad.add(c)
    return sorted(bad, key=str)
