// Browser observations on isolated tool drafts; no live project writes or LLM calls.
import { chromium } from 'playwright';
import { writeFileSync, mkdirSync } from 'node:fs';
mkdirSync('output/evidence/ai-forest-default',{recursive:true});
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1050}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route('**/rest/v1/**',r=>r.fulfill({json:[]}));
await page.goto(`${process.env.BASE ?? 'http://127.0.0.1:9816'}/?devProject=1&marketTown=1`,{waitUntil:'domcontentloaded',timeout:120000});
const guest=page.getByTestId('login-guest');
await page.getByTestId('ai-input').or(guest).first().waitFor({timeout:120000});
if(await guest.isVisible()) await guest.click();
await page.getByTestId('ai-input').waitFor({timeout:120000});
const result = await page.evaluate(async()=>{
 const {createEmptyToolProject}=await import('/src/editor/tools/emptyProject.ts');
 const {createCreationChoice}=await import('/src/editor/panels/aiCreationChoice.ts');
 const {runTool}=await import('/src/editor/tools/toolRunner.ts');
 const {runAuthorVillage}=await import('/src/editor/tools/authorVillageTool.ts');
 const {drawMapTileLayers,loadTilesetImage}=await import('/src/editor/mapTileDraw.ts');
 const project=createEmptyToolProject('Default chipset browser inspection');
 const choice=createCreationChoice(project,'마을');
 const host=document.createElement('div');host.id='forest-choice-evidence';host.style.cssText='position:fixed;inset:20px;z-index:100000;background:#f7f3ea;overflow:auto;padding:24px';
 host.append(choice.root);document.body.append(host);
 window.forestChoice=choice;
 const ctx={project};
 const blank=runTool(ctx,'create_map',{id:'blank',name:'초기 바닥',width:20,height:15});
 const generated=runTool(ctx,'generate_map',{id:'generated',theme:'forest',width:20,height:18,seed:7});
 const built=runAuthorVillage(ctx,{target:{kind:'new',mapId:'village',name:'숲마을 시공 확인',width:50,height:50},houseCount:2,countPolicy:'exact',interior:false,seed:7});
 const legacy=runAuthorVillage(ctx,{target:{kind:'new',mapId:'legacy',name:'Explicit legacy',width:50,height:50,tilesetId:'easyrpg_chipset_combined_town'},houseCount:2,countPolicy:'exact',interior:false,seed:7});
 const cave=runTool(ctx,'generate_map',{id:'cave',theme:'cave',width:20,height:18,entrance:{x:1,y:9},pois:[{x:18,y:9}],seed:7});
 const hills=runAuthorVillage(ctx,{target:{kind:'new',mapId:'hills',name:'Forest hills',width:74,height:52},morphology:'green',relief:'hills',houseCount:4,countPolicy:'best-effort',interior:false,seed:7});
 const map=ctx.project.maps.village;
 if(map){
  const ts=ctx.project.tilesets[map.tilesetId];const atlas=await loadTilesetImage(ts);
  const c=document.createElement('canvas');c.id='forest-map-evidence';c.width=map.width*16;c.height=map.height*16;
  drawMapTileLayers(c.getContext('2d'),atlas,map,ts,1);window.forestMapCanvas=c;
 }
 return {legacy:{ok:legacy.ok,tilesetId:ctx.project.maps.legacy?.tilesetId,summary:legacy.summary},cave:{ok:cave.ok,tilesetId:ctx.project.maps.cave?.tilesetId,summary:cave.summary},hills:{ok:hills.ok,tilesetId:ctx.project.maps.hills?.tilesetId,summary:hills.summary,issues:hills.issues},blank:{ok:blank.ok,tilesetId:ctx.project.maps.blank?.tilesetId,grass:ctx.project.maps.blank?.lowerTiles.every(t=>t===240)},generated:{ok:generated.ok,summary:generated.summary,issues:generated.issues,tilesetId:ctx.project.maps.generated?.tilesetId},built:{ok:built.ok,summary:built.summary,issues:built.issues,tilesetId:map?.tilesetId,village:built.data.village},contentPersistence:'none — isolated in-memory code QA'};
});
await page.getByTestId('ai-creation-select-0').click({timeout:120000});
await page.waitForFunction(()=>!document.querySelector('[data-testid="ai-creation-start"]').disabled,{timeout:120000});
result.selected=await page.getByTestId('ai-creation-tileset').inputValue();
await page.screenshot({path:'output/evidence/ai-forest-default/01-choice.png'});
await page.evaluate(()=>{document.getElementById('forest-choice-evidence').replaceChildren(window.forestMapCanvas??document.createTextNode('No map'));});
await page.screenshot({path:'output/evidence/ai-forest-default/02-map.png'});
result.errors=errors;
writeFileSync('output/evidence/ai-forest-default/report.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
await browser.close();
