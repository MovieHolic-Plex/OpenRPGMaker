// 내장 타운 칩셋 PNG를 디코드해 "투명 픽셀을 가진 타일" 목록을 생성한다.
// 투명 배경 칩(벤치·사선 지붕·나무 등 스프라이트형)은 하위 레이어에 깔리면
// 아래에 지형이 없어 검게 보이므로, 상위 레이어 전용으로 분류하는 근거 데이터다.
//
// 재생성: node scripts/generateChipsetTransparency.mjs
// 출력: src/project/defaults/generatedChipsetTransparency.ts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { inflateSync } from "node:zlib";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_PNG = join(ROOT, "public/assets/easyrpg-chipset-combined-town-transparent.png");
const OUTPUT_TS = join(ROOT, "src/project/defaults/generatedChipsetTransparency.ts");
const CELL_SIZE = 16;
const TILES_PER_ROW = 30;

const PNG_SIGNATURE = [137, 80, 78, 71, 13, 10, 26, 10];

function decodePngRgba(bytes) {
  for (let i = 0; i < PNG_SIGNATURE.length; i += 1) {
    if (bytes[i] !== PNG_SIGNATURE[i]) throw new Error("PNG 시그니처가 아닙니다");
  }
  let offset = 8;
  let width = 0;
  let height = 0;
  let bitDepth = 0;
  let colorType = -1;
  let interlace = 0;
  const idatParts = [];
  while (offset + 8 <= bytes.length) {
    const length = bytes.readUInt32BE(offset);
    const type = bytes.toString("ascii", offset + 4, offset + 8);
    const data = bytes.subarray(offset + 8, offset + 8 + length);
    if (type === "IHDR") {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      bitDepth = data[8];
      colorType = data[9];
      interlace = data[12];
    } else if (type === "IDAT") {
      idatParts.push(data);
    } else if (type === "IEND") {
      break;
    }
    offset += 12 + length;
  }
  if (bitDepth !== 8 || colorType !== 6 || interlace !== 0) {
    throw new Error(`지원하지 않는 PNG 형식: bitDepth=${bitDepth} colorType=${colorType} interlace=${interlace} (8비트 RGBA 비인터레이스만 지원)`);
  }
  const raw = inflateSync(Buffer.concat(idatParts));
  const stride = width * 4;
  const rgba = Buffer.alloc(width * height * 4);
  for (let y = 0; y < height; y += 1) {
    const filter = raw[y * (stride + 1)];
    const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    const out = rgba.subarray(y * stride, (y + 1) * stride);
    const prev = y > 0 ? rgba.subarray((y - 1) * stride, y * stride) : null;
    for (let x = 0; x < stride; x += 1) {
      const left = x >= 4 ? out[x - 4] : 0;
      const up = prev ? prev[x] : 0;
      const upLeft = prev && x >= 4 ? prev[x - 4] : 0;
      let value = line[x];
      if (filter === 1) value += left;
      else if (filter === 2) value += up;
      else if (filter === 3) value += (left + up) >> 1;
      else if (filter === 4) value += paeth(left, up, upLeft);
      else if (filter !== 0) throw new Error(`알 수 없는 스캔라인 필터: ${filter}`);
      out[x] = value & 0xff;
    }
  }
  return { width, height, rgba };
}

function paeth(a, b, c) {
  const p = a + b - c;
  const pa = Math.abs(p - a);
  const pb = Math.abs(p - b);
  const pc = Math.abs(p - c);
  if (pa <= pb && pa <= pc) return a;
  return pb <= pc ? b : c;
}

const { width, height, rgba } = decodePngRgba(readFileSync(SOURCE_PNG));
if (width !== TILES_PER_ROW * CELL_SIZE) {
  throw new Error(`칩셋 폭이 예상과 다릅니다: ${width} (expected ${TILES_PER_ROW * CELL_SIZE})`);
}
const rows = Math.floor(height / CELL_SIZE);
const transparentTiles = [];
// 완전 통명 타일 = 파노라마 창(특수 타일). 이 칸에서만 맵 배경이 보인다.
const fullyTransparentTiles = [];
for (let tile = 0; tile < TILES_PER_ROW * rows; tile += 1) {
  const originX = (tile % TILES_PER_ROW) * CELL_SIZE;
  const originY = Math.floor(tile / TILES_PER_ROW) * CELL_SIZE;
  let transparent = 0;
  for (let dy = 0; dy < CELL_SIZE; dy += 1) {
    for (let dx = 0; dx < CELL_SIZE; dx += 1) {
      if (rgba[((originY + dy) * width + originX + dx) * 4 + 3] === 0) transparent += 1;
    }
  }
  if (transparent > 0) transparentTiles.push({ tile, transparent });
  if (transparent === CELL_SIZE * CELL_SIZE) fullyTransparentTiles.push(tile);
}

// 회귀 가드: 알려진 스프라이트형 칩은 반드시 포함, 지면 칩은 반드시 제외.
const tileSet = new Set(transparentTiles.map((entry) => entry.tile));
for (const mustHave of [290, 357, 385, 378]) {
  if (!tileSet.has(mustHave)) throw new Error(`투명 타일 목록에 ${mustHave}가 없습니다 — 칩셋 이미지가 바뀌었는지 확인하세요`);
}
for (const mustNotHave of [0, 16, 240, 374, 342]) {
  if (tileSet.has(mustNotHave)) throw new Error(`불투명이어야 할 타일 ${mustNotHave}가 투명 목록에 있습니다 — 칩셋 이미지가 바뀌었는지 확인하세요`);
}

const lines = [];
lines.push("// AUTO-GENERATED by scripts/generateChipsetTransparency.mjs — 직접 수정하지 마세요.");
lines.push("// 내장 타운 칩셋에서 투명 픽셀을 1개 이상 가진 타일 목록.");
lines.push("// 이런 칩은 하위 레이어에 깔리면 투명 부분 아래가 검게 보이므로 상위 레이어 전용이다.");
lines.push("// 재생성: node scripts/generateChipsetTransparency.mjs");
lines.push("export const COMBINED_TOWN_TRANSPARENT_TILES: readonly number[] = [");
for (let i = 0; i < transparentTiles.length; i += 12) {
  lines.push(`  ${transparentTiles.slice(i, i + 12).map((entry) => entry.tile).join(", ")},`);
}
lines.push("];");
lines.push("");
lines.push("// 완전 통명 타일(알파가 모든 픽셀에서 0) = 파노라마 창. 이 칸에서만 맵 배경이 보인다.");
lines.push("// RM2K 방식: 배경은 레이어 뒤에 있고, 창을 낸 칸에서만 비친다.");
lines.push("export const COMBINED_TOWN_PANORAMA_WINDOW_TILES: readonly number[] = [");
lines.push("  " + fullyTransparentTiles.join(", ") + ",");
lines.push("];");
lines.push("");
writeFileSync(OUTPUT_TS, lines.join("\n"));
console.log(`generated ${OUTPUT_TS} — ${transparentTiles.length} transparent tiles, ${fullyTransparentTiles.length} panorama windows`);
