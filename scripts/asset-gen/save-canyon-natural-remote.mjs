import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { configFromEnv, loadCurrentJson } from '../supabase-resource-root/supabaseRest.mjs';

const out='output/evidence/canyon-natural';
const projectId='oprn-hill-forest-harmony-20260918-a4e1', mapId='map_cliff_forest_bridge';
const local=JSON.parse(fs.readFileSync(out+'/editor-saved-project.json'));
const evidence=JSON.parse(fs.readFileSync(out+'/editor-proof.json'));
assert.equal(evidence.reloaded,true);
assert.equal(evidence.houses.length,2);assert.ok(evidence.houses.every(h=>h.reachable&&h.onPlateau));
assert.ok(evidence.bridge.onlyCrossing&&evidence.bridge.exitReachable);assert.equal(evidence.bridge.railLeaks,0);
assert.equal(evidence.badAutotiles+evidence.badTrunks,0);
const c={...await configFromEnv(),projectId};
const headers={apikey:c.anonKey,Authorization:`Bearer ${c.anonKey}`};
const q=new URLSearchParams({project_id:`eq.${projectId}`,select:'current_json,current_sha256'});
const response=await fetch(`${c.url}/rest/v1/projects?${q}`,{headers:{...headers,'Accept-Profile':'rpg_zzu'}});
assert.ok(response.ok);const [row]=await response.json(),p=row.current_json,before=structuredClone(p);
assert.deepEqual(p.maps[mapId],JSON.parse(fs.readFileSync(out+'/remote-before.json')).maps[mapId],'Concurrent map edit');
const map=local.maps[mapId],tileset=local.tilesets[map.tilesetId];
assert.deepEqual(p.tilesets[tileset.id],tileset,'The shared approved tileset must remain unchanged');
assert.ok(p.assets.uploaded[tileset.image.id]);
const image=p.assets.uploaded[tileset.image.id];
const localRef=local.assets.uploaded[tileset.image.id].ref;
assert.equal(createHash('sha256').update(Buffer.from(image.dataUrl.split(',')[1],'base64')).digest('hex'),localRef.sha256);
p.maps[mapId]=map;
assert.ok(p.mapTree?.children);

const sha=createHash('sha256').update(JSON.stringify(p)).digest('hex');
const match=new URLSearchParams({project_id:`eq.${projectId}`,current_sha256:`eq.${row.current_sha256}`});
const saved=await fetch(`${c.url}/rest/v1/projects?${match}`,{method:'PATCH',headers:{...headers,'Content-Profile':'rpg_zzu','Content-Type':'application/json',Prefer:'return=representation'},body:JSON.stringify({current_json:p,current_sha256:sha,map_count:Object.keys(p.maps).length,tileset_count:Object.keys(p.tilesets).length})});
assert.ok(saved.ok,`Save status ${saved.status}`);assert.equal((await saved.json()).length,1,'Concurrent change; nothing replaced');
const reloaded=await loadCurrentJson(c);
assert.deepEqual(reloaded.maps[mapId],map);assert.deepEqual(reloaded.tilesets[tileset.id],tileset);
for(const[id,m]of Object.entries(before.maps))if(id!==mapId)assert.deepEqual(reloaded.maps[id],m);
for(const[id,t]of Object.entries(before.tilesets))assert.deepEqual(reloaded.tilesets[id],t);
assert.deepEqual(reloaded.assets,before.assets);
fs.writeFileSync(out+'/remote-reloaded.json',JSON.stringify(reloaded));
const proof={projectId,mapId,tilesetId:tileset.id,saved:true,reloaded:true,otherMapsUnchanged:true,existingTilesetsUnchanged:true,atlasUnchanged:true,sha256:sha,houseCount:2,bridge:evidence.bridge,cliffHeight:evidence.cliffHeight};
fs.writeFileSync(out+'/remote-proof.json',JSON.stringify(proof,null,2));console.log(JSON.stringify(proof));
