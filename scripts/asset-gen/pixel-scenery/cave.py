def stalactite(c,x,y,w,h,colors):
    dark,base,light = colors
    c.stamp([(0,0),(w,0),(w-2,h//3),(w*2//3,h//2),
             (w//2+1,h),(w//2-1,h),(w//3,h//2),(2,h//3)],x,y,dark)
    c.stamp([(2,0),(w//2+1,0),(w//2,h-3),(w//3,h//2),(3,h//3)],x,y,base)
    c.stamp([(3,0),(w//3+1,0),(w//3,h//3),(w//2-1,h*2//3),
             (w//3-1,h//2)],x,y,light)


def crystal(c,x,y,height,lean=0):
    c.stamp([(-4,0),(-6,-height+5),(lean,-height),(5,-height+5),(5,0)],x,y,16)
    c.stamp([(-3,-1),(-4,-height+6),(lean,-height+1),(1,-height+5),(1,-2)],x,y,18)
    c.stamp([(1,-height+5),(lean,-height+1),(4,-height+5),(4,-1),(1,-2)],x,y,17)
    c.line([(x-3,y-height+6),(x+lean,y-height+2)],19,2)


