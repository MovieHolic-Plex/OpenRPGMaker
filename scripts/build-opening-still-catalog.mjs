#!/usr/bin/env node
// scripts/build-opening-still-catalog.mjs
// 오프닝 스틸 팩 스테이징 manifest.json → 카탈로그 갱신.
//
//   src/assets/openingStillPackRuntime.ts — id 와 파일명. 플레이어 URL 조립 최소 정보(전체 재생성).
//   src/assets/openingStillMoods.ts      — 팩 무드 구역만 마커 사이에 갱신. 레포 분(수동 무드)은 보존.
//
// 스테이징 manifest.json 형식(tibo 생성기가 만든다):
//   { "stills": [ { "id": "oprn-pack-still-...", "fileName": "....jpg",
//                   "name": "한글 이름", "tags": ["설원","밤"], "prompt": "..." } ] }
//
// BGM 카탈로그 빌더와 같은 원칙: 원본 manifest 가 유일한 진실이고 이 스크립트로만 재생성한다.
// 플레이어 번들에 검색어가 실리지 않게 런타임/에디터 파일을 나눈다.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const REPO_ROOT = path.resolve(import.meta.dirname, "..");
const OUT_RUNTIME = path.join(REPO_ROOT, "src", "assets", "openingStillPackRuntime.ts");
const OUT_MOODS = path.join(REPO_ROOT, "src", "assets", "openingStillMoods.ts");
const MOODS_BEGIN = "// BEGIN generated pack stills — 이 줄과 END 사이는 생성 영역이다.";
const MOODS_END = "// END generated pack stills";

function parseArgs(argv) {
  const args = { staging: path.join(process.env.HOME || ".", "rpg-zzu-still-staging") };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--staging") args.staging = argv[++i] ?? args.staging;
  }
  return args;
}

const ID = /^oprn-pack-still-[a-z0-9]+(?:-[a-z0-9]+)*$/;
const FILE = /^[a-z0-9][a-z0-9_-]*\.(?:jpg|webp|png)$/;

function fail(message) { throw new Error(message); }

const args = parseArgs(process.argv.slice(2));
const manifest = JSON.parse(await readFile(path.join(args.staging, "manifest.json"), "utf8"));
const stills = manifest.stills;
if (!Array.isArray(stills) || stills.length === 0) fail("stills 배열이 비어 있다");

const seenIds = new Set();
const seenFiles = new Set();
const validated = stills.map((still) => {
  if (!ID.test(still.id)) fail("잘못된 id: " + JSON.stringify(still.id));
  if (!FILE.test(still.fileName)) fail("잘못된 파일명: " + JSON.stringify(still.fileName));
  if (!Array.isArray(still.tags) || still.tags.length === 0 || still.tags.some((tag) => typeof tag !== "string" || tag.trim() === "")) fail("태그 누락: " + still.id);
  if (typeof still.name !== "string" || still.name.trim() === "") fail("이름 누락: " + still.id);
  if (seenIds.has(still.id)) fail("id 중복: " + still.id);
  if (seenFiles.has(still.fileName)) fail("파일명 중복: " + still.fileName);
  seenIds.add(still.id);
  seenFiles.add(still.fileName);
  return {
    id: still.id,
    fileName: still.fileName,
    name: still.name.trim(),
    tags: still.tags.map((tag) => tag.trim()),
    prompt: typeof still.prompt === "string" ? still.prompt : "",
  };
});
validated.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const q = JSON.stringify;
const runtimeBody = validated.map((still) => "  [" + q(still.id) + ", { fileName: " + q(still.fileName) + " }],").join("\n");

const runtimeTs = [
  "// Generated by scripts/build-opening-still-catalog.mjs. Do not edit by hand.",
  "// 오프닝 스틸 릴리스 팩 — 런타임(게임) 전용 최소 정보. 검색어는 openingStillMoods.ts 가 담는다.",
  "// 팩 그림은 레포에 없다. Release 태그 tar 를 설치기가 public/assets/stills/pack/ 에 푼다.",
  "",
  "/** 재생(표시)에 필요한 최소 정보. */",
  "export type OpeningStillPackEntry = {",
  "  readonly fileName: string;",
  "};",
  "",
  "const OPENING_STILL_PACK_ENTRIES: readonly (readonly [string, OpeningStillPackEntry])[] = [",
  runtimeBody,
  "];",
  "",
  "export const OPENING_STILL_PACK_COUNT = OPENING_STILL_PACK_ENTRIES.length;",
  "",
  "const OPENING_STILL_PACK_INDEX: ReadonlyMap<string, OpeningStillPackEntry> = new Map(",
  "  OPENING_STILL_PACK_ENTRIES,",
  ");",
  "",
  "/** 팩 소속이 아니면 undefined — 해석기가 다음 후보로 넘어간다. */",
  "export function findOpeningStillPackEntry(resourceId: string): OpeningStillPackEntry | undefined {",
  "  return OPENING_STILL_PACK_INDEX.get(resourceId);",
  "}",
  "",
  "export function listOpeningStillPackIds(): readonly string[] {",
  "  return OPENING_STILL_PACK_ENTRIES.map(([id]) => id);",
  "}",
  "",
].join("\n");

await writeFile(OUT_RUNTIME, runtimeTs);

// moods 파일의 마커 사이만 교체 — 레포 분(수동 무드)과 파일 상단 라이선스·타입은 보존한다.
const moodsSource = await readFile(OUT_MOODS, "utf8");
const begin = moodsSource.indexOf(MOODS_BEGIN);
const end = moodsSource.indexOf(MOODS_END);
if (begin === -1 || end === -1 || end < begin) fail("openingStillMoods.ts 에 생성 마커가 없다 — 파일을 먼저 세팅해야 한다");

const moodBody = validated.map((still) => {
  const lines = [
    "  {",
    "    id: " + q(still.id) + ",",
    "    name: " + q(still.name) + ",",
    "    tags: [" + still.tags.map((tag) => q(tag)).join(", ") + "],",
  ];
  if (still.prompt) lines.push("    // prompt: " + still.prompt.slice(0, 140));
  lines.push("  },");
  return lines.join("\n");
});

const packSection = [
  MOODS_BEGIN,
  moodBody.join("\n"),
  MOODS_END,
].join("\n");

await writeFile(OUT_MOODS, moodsSource.slice(0, begin) + packSection + moodsSource.slice(end + MOODS_END.length));

console.log("카탈로그 갱신 완료: 팩 스틸 " + validated.length + "장");

