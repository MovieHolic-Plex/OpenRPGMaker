#!/usr/bin/env node
// scripts/build-bgm-catalog.mjs
// 스테이징의 catalog.raw.json → 번들 카탈로그 두 파일.
//
//   src/assets/bgmCatalogRuntime.ts — id → 파일명/루프. 플레이어(게임)가 재생에 쓰는 최소 정보.
//   src/assets/bgmCatalog.ts        — 제목·카테고리·BPM·태그·기획 의도. 에디터 검색/피커 전용.
//
// 왜 둘로 쪼개는가: 메타데이터까지 한 파일에 담으면 245KB 가 되고, 리소스 해석기를 타고
// **플레이어 번들에도** 그대로 실린다. 게임은 파일명만 알면 되므로 런타임 모듈을 따로 둬서
// 에디터 메타데이터가 트리셰이킹으로 빠지게 한다.
//
// 왜 생성 파일인가: 281곡을 손으로 적으면 sha256/러닝타임/BPM 이 원본과 어긋난다.
// 원본(manus 리뷰 카탈로그)을 유일한 진실로 두고 이 스크립트로만 재생성한다.
//
//   node scripts/build-bgm-catalog.mjs --staging <fetch-bgm-catalog 출력 디렉터리>
//
// 번들에 넣지 않는 것: 영문 생성 프롬프트(곡당 ~400자, 281곡 = 112KB).
// 그건 openwiki 문서/스테이징 JSON 에만 남긴다. 검색에 쓰이는 건 태그와 기획 의도다.

import { readFile, writeFile, stat } from "node:fs/promises";
import path from "node:path";

const REPO_ROOT = path.resolve(import.meta.dirname, "..");
const OUT_TS = path.join(REPO_ROOT, "src", "assets", "bgmCatalog.ts");
const OUT_RUNTIME_TS = path.join(REPO_ROOT, "src", "assets", "bgmCatalogRuntime.ts");

function parseArgs(argv) {
  const args = {
    staging: path.join(process.env.LOCALAPPDATA || process.env.HOME || ".", "rpg-zzu-bgm-staging"),
  };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--staging") args.staging = argv[++i] ?? args.staging;
  }
  return args;
}

/** trackCode(RTP-FLD-001) → 리소스 id. 기존 CC0 BGM 과 같은 `cc0-bgm-` 접두사를 쓴다. */
function resourceIdFor(trackCode) {
  return `cc0-bgm-${trackCode.toLowerCase()}`;
}

/** 카테고리 문자열("필드 · 마을")을 검색 태그로 쪼갠다. */
function categoryTags(category) {
  return category
    .split(/[·,/]/)
    .map((part) => part.trim())
    .filter((part) => part.length > 0);
}

/**
 * 검색 태그 집계. 리소스 검색(resourceSearch.ts)은 라벨과 태그만 본다 —
 * 여기서 빠진 낱말은 에디터에서 영원히 찾을 수 없다. 그래서 카테고리·감정·악기·영문 제목을 모두 넣는다.
 */
function tagsFor(track) {
  const tags = new Set(["bgm", "cc0"]);
  for (const tag of categoryTags(track.category)) tags.add(tag);
  for (const emotion of track.metadata?.emotions ?? []) tags.add(String(emotion));
  for (const instrument of track.metadata?.instruments ?? []) tags.add(String(instrument));
  if (track.titleEn) {
    for (const word of String(track.titleEn).toLowerCase().split(/\s+/)) {
      if (word.length > 2) tags.add(word);
    }
  }
  if (track.musicalKey) tags.add(String(track.musicalKey));
  // 정규화: 언더스코어 토큰(late_2000s_rich)은 사람이 칠 수 없다 — 공백으로 풀어 준다.
  return [...tags].map((tag) => tag.replaceAll("_", " ").trim()).filter((tag) => tag.length > 0);
}

function tsString(value) {
  return JSON.stringify(String(value ?? ""));
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const rawPath = path.join(args.staging, "catalog.raw.json");
  const tracks = JSON.parse(await readFile(rawPath, "utf8"));
  if (!Array.isArray(tracks) || tracks.length === 0) throw new Error(`빈 카탈로그: ${rawPath}`);

  const audioDir = path.join(args.staging, "audio");
  const entries = [];
  const missing = [];
  for (const track of tracks) {
    const fileName = path.basename(new URL(track.audioUrl, "https://x.invalid").pathname);
    let bytes = 0;
    try {
      bytes = (await stat(path.join(audioDir, fileName))).size;
    } catch {
      missing.push(track.trackCode);
    }
    const rules = track.productionRules ?? {};
    entries.push({
      id: resourceIdFor(track.trackCode),
      trackCode: track.trackCode,
      title: track.title,
      titleEn: track.titleEn ?? "",
      category: track.category,
      fileName,
      bytes,
      durationSeconds: Math.round((track.durationSeconds ?? 0) * 1000) / 1000,
      bpm: typeof track.bpm === "number" ? track.bpm : null,
      musicalKey: track.musicalKey ?? "",
      loop: rules.loopPlayback === true,
      fadeInSeconds: typeof rules.fadeInSeconds === "number" ? rules.fadeInSeconds : 0,
      fadeOutSeconds: typeof rules.fadeOutSeconds === "number" ? rules.fadeOutSeconds : 0,
      sha256: String(track.sha256 ?? "").toLowerCase(),
      brief: track.creativeBrief ?? "",
      tags: tagsFor(track),
    });
  }
  if (missing.length > 0) {
    console.warn(`경고: 스테이징에 오디오가 없는 트랙 ${missing.length}건 (bytes=0): ${missing.slice(0, 8).join(", ")}…`);
  }

  const totalSeconds = entries.reduce((sum, e) => sum + e.durationSeconds, 0);
  const totalBytes = entries.reduce((sum, e) => sum + e.bytes, 0);
  const provenance = `// Generated by scripts/build-bgm-catalog.mjs. Do not edit by hand.
// 원본: BGM 리뷰 카탈로그(bgmreview-h4zeq64k.manus.space) — 전곡 CC0-1.0, 무보컬 오리지널 창작.
// 오디오 파일은 레포에 없다(총 ${(totalBytes / 1024 / 1024 / 1024).toFixed(2)}GB). CDN(DigitalOcean Spaces)에서 서빙하며
// URL 조립은 bgmCdn.ts 가 담당한다.
//
// 재생성: node scripts/fetch-bgm-catalog.mjs --password <승인 비번>
//         node scripts/build-bgm-catalog.mjs`;

  const runtimeBody = entries
    .map((e) => `  [${tsString(e.id)}, { fileName: ${tsString(e.fileName)}, loop: ${e.loop} }],`)
    .join("\n");
  const runtimeSource = `${provenance}
//
// 이 파일은 **런타임(게임) 전용 최소 정보**다. 제목·카테고리·태그 같은 에디터 메타데이터는
// bgmCatalog.ts 에 있다. 둘을 합치면 245KB 짜리 에디터 메타데이터가 리소스 해석기를 타고
// 플레이어 번들에까지 실린다 — 게임은 파일명과 루프 여부만 알면 된다.

/** 재생에 필요한 최소 정보. */
export type BgmRuntimeEntry = {
  readonly fileName: string;
  /** 심리스 루프 마스터인지. false 면 앞뒤 페이드가 있어 루프 이음새가 들린다. */
  readonly loop: boolean;
};

const BGM_RUNTIME_ENTRIES: readonly (readonly [string, BgmRuntimeEntry])[] = [
${runtimeBody}
];

const BY_ID: ReadonlyMap<string, BgmRuntimeEntry> = new Map(BGM_RUNTIME_ENTRIES);

/** 카탈로그 트랙 수. 281 미만으로 줄면 카탈로그 회귀다. */
export const BGM_CATALOG_TRACK_COUNT = BGM_RUNTIME_ENTRIES.length;

/** 카탈로그 총 재생 시간(초). 곡 수만 세면 놓치는 "파일이 바뀐" 회귀를 잡는다. */
export const BGM_CATALOG_TOTAL_SECONDS = ${Math.round(totalSeconds)};

/** 이 리소스 id 가 CC0 BGM 카탈로그 소속인지. */
export function isBgmCatalogResourceId(resourceId: string): boolean {
  return BY_ID.has(resourceId);
}

/** 리소스 id → 런타임 항목. 카탈로그 밖이면 undefined. */
export function findBgmRuntimeEntry(resourceId: string): BgmRuntimeEntry | undefined {
  return BY_ID.get(resourceId);
}

/** 카탈로그의 모든 리소스 id(사전순 아님 — 카탈로그 순서). */
export function bgmCatalogResourceIds(): readonly string[] {
  return BGM_RUNTIME_ENTRIES.map(([id]) => id);
}
`;
  await writeFile(OUT_RUNTIME_TS, runtimeSource, "utf8");

  const metaBody = entries
    .map(
      (e) => `  {
    id: ${tsString(e.id)},
    trackCode: ${tsString(e.trackCode)},
    title: ${tsString(e.title)},
    titleEn: ${tsString(e.titleEn)},
    category: ${tsString(e.category)},
    bytes: ${e.bytes},
    durationSeconds: ${e.durationSeconds},
    bpm: ${e.bpm === null ? "null" : e.bpm},
    musicalKey: ${tsString(e.musicalKey)},
    fadeInSeconds: ${e.fadeInSeconds},
    fadeOutSeconds: ${e.fadeOutSeconds},
    sha256: ${tsString(e.sha256)},
    brief: ${tsString(e.brief)},
    tags: [${e.tags.map(tsString).join(", ")}],
  },`,
    )
    .join("\n");

  const source = `${provenance}
//
// 에디터 전용 메타데이터. 재생에 필요한 파일명/루프는 bgmCatalogRuntime.ts 에 있다.

import { findBgmRuntimeEntry } from "@/assets/bgmCatalogRuntime";

/** 번들 CC0 BGM 한 곡의 에디터용 메타데이터. */
export type BgmCatalogTrack = {
  readonly id: string;
  /** 원본 카탈로그의 트랙 코드(RTP-FLD-001). 문서·문의 시 식별자. */
  readonly trackCode: string;
  readonly title: string;
  readonly titleEn: string;
  /** 장면 분류("필드 · 마을"). 피커 그룹 헤더와 검색 태그의 근거다. */
  readonly category: string;
  readonly bytes: number;
  readonly durationSeconds: number;
  readonly bpm: number | null;
  readonly musicalKey: string;
  readonly fadeInSeconds: number;
  readonly fadeOutSeconds: number;
  /** 원본이 준 sha256. 60곡은 원본에 해시가 없어 빈 문자열이다. */
  readonly sha256: string;
  /** 곡 기획 의도(한국어). 에디터 검색·AI 곡 추천의 설명 근거. */
  readonly brief: string;
  readonly tags: readonly string[];
};

export const BGM_CATALOG_LICENSE = "CC0-1.0" as const;
export const BGM_CATALOG_SOURCE_NAME = "OPRN 오리지널 CC0 BGM 카탈로그" as const;

export const BGM_CATALOG: readonly BgmCatalogTrack[] = [
${metaBody}
];

const BY_ID: ReadonlyMap<string, BgmCatalogTrack> = new Map(BGM_CATALOG.map((track) => [track.id, track]));

export function findBgmTrack(resourceId: string): BgmCatalogTrack | undefined {
  return BY_ID.get(resourceId);
}

/** 심리스 루프 마스터인지 — 런타임 항목에서 읽는다(진실은 한 곳에만 둔다). */
export function isSeamlessLoopTrack(resourceId: string): boolean {
  return findBgmRuntimeEntry(resourceId)?.loop === true;
}

/**
 * 피커/목록용 표시 이름. 281곡을 id 로만 보여 주면 감독이 고를 수 없다 —
 * 제목과 장면 분류를 함께 붙여 한 줄로 판단되게 한다.
 */
export function bgmTrackLabel(track: BgmCatalogTrack): string {
  const minutes = Math.floor(track.durationSeconds / 60);
  const seconds = Math.round(track.durationSeconds % 60).toString().padStart(2, "0");
  return \`\${track.title} — \${track.category} (\${minutes}:\${seconds})\`;
}

/** 카테고리 → 곡 목록. 피커가 281곡을 평면 나열하지 않도록 그룹을 만든다. */
export function bgmTracksByCategory(): ReadonlyMap<string, readonly BgmCatalogTrack[]> {
  const groups = new Map<string, BgmCatalogTrack[]>();
  for (const track of BGM_CATALOG) {
    const bucket = groups.get(track.category);
    if (bucket) bucket.push(track);
    else groups.set(track.category, [track]);
  }
  return groups;
}
`;
  await writeFile(OUT_TS, source, "utf8");
  console.log(`${OUT_RUNTIME_TS} ← ${entries.length}곡 (런타임)`);
  console.log(`${OUT_TS} ← ${entries.length}곡 / ${(totalSeconds / 60).toFixed(1)}분 (메타데이터)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
