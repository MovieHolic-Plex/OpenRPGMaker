    x,y=offset; rows=raw.strip('\n').splitlines(); pal=ART[name][1]
    expanded=['.'*64 for _ in range(64)]
    for dy,row in enumerate(rows):
        assert x+len(row)<=64 and y+dy<64
        assert not (set(row)-set(pal)-{'.'})
        expanded[y+dy]='.'*x+row+'.'*(64-x-len(row))
    (ROOT/(name+'.pxgrid')).write_text('\n'.join(expanded)+'\n')
    (ROOT/(name+'.palette.json')).write_text(json.dumps(pal,indent=2)+'\n')
