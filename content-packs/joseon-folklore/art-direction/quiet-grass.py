"""Native 16px hand pixel candidate. Sparse leaf clusters, no random noise.
Not installed: awaits review beside the Joseon pilot tree candidates.
"""
import json
from pathlib import Path
from PIL import Image

PALETTE={'.':'#58a035','s':'#4b8232','l':'#73b83e'}
# Literal native pixel positions for four variants, not procedural scatter.
ROWS=[
 ['................','................','................','....ss..........','...sssl.........','....ssl.........','................','................','................','...........s....','..........ss....','...........sl...','................','................','................','................'],
 ['................','................','................','................','................','................','................','................','................','................','................','................','................','................','................','................'],
 ['................','................','................','................','............s...','...........ssl..','............sl..','................','....ss..........','...sssl.........','....ss..........','................','................','................','................','................'],
 ['................','................','................','................','................','................','................','................','................','................','................','................','................','................','................','................'],
]

def tiles(root):
 allowed=set(json.loads((Path(root)/'scripts/content/lib/joseon/harness/palette.json').read_text())['allowed'])
 assert set(PALETTE.values()) <= allowed
 out=[]
 for rows in ROWS:
  assert len(rows)==16 and all(len(row)==16 for row in rows)
  im=Image.new('RGBA',(16,16))
  for y,row in enumerate(rows):
   for x,c in enumerate(row):
    h=PALETTE[c];im.putpixel((x,y),tuple(bytes.fromhex(h[1:]))+(255,))
  out.append(im)
 return out
